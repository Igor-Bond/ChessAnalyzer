/** Поддельный fetch: отвечает пачкой и считает обращения. */
export function поддельнаяЗагрузка(пачка, { статус = 200 } = {}) {
    const ф = async (адрес) => {
        ф.адреса.push(адрес);
        return { ok: статус >= 200 && статус < 300, status: статус, json: async () => ({ puzzles: пачка }) };
    };
    ф.адреса = [];
    return ф;
}

/**
 * Партия с готовым разбором — без движка: оценки вписаны руками.
 * Детский мат: 3…Sf6?? — зевок чёрных, лучше было 3…g6.
 */
export function партияСРазбором(поля = {}) {
    const п = { ...новаяПартия(), белые: 'Igor', чёрные: 'Klaus', ходы: ['e4', 'e5', 'Bc4', 'Nc6', 'Qh5', 'Nf6', 'Qxf7#'], ...поля };
    const поз = позиции(п);
    const о = (оценка, лучший, линия = [лучший]) => ({ оценка, лучший, линия, второй: null, ходов: 20 });

    const оценки = [
        о({ cp: 30 }, 'e2e4'),
        о({ cp: 30 }, 'e7e5'),
        о({ cp: 30 }, 'f1c4'),
        о({ cp: 30 }, 'b8c6'),
        о({ cp: 40 }, 'd1h5'),
        о({ cp: 40 }, 'g7g6', ['g7g6', 'h5f3', 'g8f6']),
        о({ мат: 1 }, 'h5f7'),
        { оценка: { мат: 0, проигралБелые: false }, лучший: null, линия: [], второй: null, ходов: 0 }
    ];

    return { ...п, разбор: { версия: 1, глубина: 10, fens: поз.map((x) => x.fen), оценки, глубины: оценки.map(() => 10) } };
}

describe('Задачи: lichess', () => {
    it('задача из ответа lichess: позиция после хода соперника, ходит решающий', () => {
        const з = изLichess(МАТ_В_ДВА, 'mix', 'easiest');
        equal(з.id, 'li:1NElZ');
        equal(з.fen.split(' ')[1], 'w', 'ходить должны белые — первый ход решения их');
        equal(з.последний, { from: 'f7', to: 'e6' });
        equal(з.решение, ['g3g6', 'g8h8', 'g6g7']);
        equal(з.рейтинг, 1003);
        equal(з.сложность, 'easiest');
        assert(з.ссылка.endsWith('/training/1NElZ'));
    });

    it('битая задача — null, а не исключение', () => {
        equal(изLichess({ game: { pgn: 'e4 e5 Qxf7' }, puzzle: { id: 'x', solution: ['a1a2'] } }), null);
        equal(изLichess({ ...МАТ_В_ОДИН, puzzle: { ...МАТ_В_ОДИН.puzzle, solution: ['h5h8'] } }), null);
        equal(изLichess({}), null);
    });

    it('загрузка: адрес с темой и сложностью; 429 и отказ сети — словами', async () => {
        const ф = поддельнаяЗагрузка([МАТ_В_ДВА, МАТ_В_ОДИН]);
        const пачка = await загрузитьLichess({ тема: 'mateIn2', сложность: 'harder', загрузка: ф });
        equal(пачка.length, 2);
        assert(ф.адреса[0].includes('/api/puzzle/batch/mateIn2?'), ф.адреса[0]);
        assert(ф.адреса[0].includes('difficulty=harder'), ф.адреса[0]);

        let ошибка = '';
        try { await загрузитьLichess({ загрузка: поддельнаяЗагрузка([], { статус: 429 }) }); } catch (e) { ошибка = e.message; }
        assert(/подождать минуту/.test(ошибка), ошибка);

        try { await загрузитьLichess({ загрузка: async () => { throw new TypeError('Failed to fetch'); } }); } catch (e) { ошибка = e.message; }
        equal(ошибка, 'Нет связи с lichess');
    });

    it('проверка хода: верный, неверный, другой мат засчитывается', () => {
        const з = изLichess(МАТ_В_ДВА);
        equal(проверитьХод(з, з.fen, 'g3g6', 0), 'верно');
        equal(проверитьХод(з, з.fen, 'g3g4', 0), 'неверно');

        // Мат по последней горизонтали двумя ладьями: решение — Ta8, Te8 тоже матует
        const мат = { источник: 'lichess', решение: ['a1a8'] };
        equal(проверитьХод(мат, '6k1/5ppp/8/8/8/8/8/R3R1K1 w - - 0 1', 'e1e8', 0), 'мат');
    });
});

