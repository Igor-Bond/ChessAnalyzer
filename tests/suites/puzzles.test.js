describe('Задачи: свои ошибки', () => {
    it('владелец архива — имя в большинстве партий, регистр и пробелы не важны', () => {
        const п = (б, ч) => ({ белые: б, чёрные: ч });
        equal(ктоЯ([п('Igor Bond', 'A'), п('B', 'igor  bond'), п('Igor Bond', 'C'), п('', '')]), 'Igor Bond');
        equal(ктоЯ([п('Igor', 'A')]), null, 'одна партия — ещё не закономерность');
        equal(ктоЯ([п('A', 'B'), п('C', 'D'), п('E', 'A'), п('F', 'G')]), null, 'имя в половине партий не набралось');
        equal(игроки([п('Igor', 'A'), п('B', 'igor')])[0], { имя: 'Igor', партий: 2 });
        equal(ктоЯ([п('Igor', 'Klaus'), п('Klaus', 'Igor')]), null, 'ничья по партиям — владельца не угадать');
    });

    it('задачи из разобранной партии: позиция перед зевком, лучший ход — решение', () => {
        const п = партияСРазбором();
        const задачи = задачиИзПартий([п]);
        equal(задачи.length, 1, `задач: ${задачи.map((з) => з.san)}`);

        const з = задачи[0];
        equal(з.san, 'Nf6');
        equal(з.класс, 'зевок');
        equal(з.решение, ['g7g6']);
        equal(з.сыгран, 'g8f6');
        equal(з.fen.split(' ')[1], 'b');
        equal(з.последний, { from: 'd1', to: 'h5' });

        equal(задачиИзПартий([п], 'Igor').length, 0, 'у белых ошибок нет');
        equal(задачиИзПартий([п], 'klaus').length, 1);

        // Незаконченный разбор — не источник задач
        const неполная = { ...п, разбор: { ...п.разбор, глубины: п.разбор.глубины.map((г, i) => (i === 5 ? 8 : г)) } };
        equal(задачиИзПартий([неполная]).length, 0);
    });

    it('ход из партии и другой ход: «сыгран» и «проверить»', () => {
        const з = задачиИзПартий([партияСРазбором()])[0];
        equal(проверитьХод(з, з.fen, 'g7g6'), 'верно');
        equal(проверитьХод(з, з.fen, 'g8f6'), 'сыгран');
        equal(проверитьХод(з, з.fen, 'd8e7'), 'проверить');
    });

    it('другой ход принимается, если теряет против лучшего меньше 5%', async () => {
        const з = задачиИзПартий([партияСРазбором()])[0];

        // Оценки — со стороны хода (чёрных), как их даёт движок
        const движок = (свой) => ({
            оценить: async (fen, п) => {
                equal(п.ходы, ['g7g6', 'd8e7'], 'оба хода — одним поиском');
                return { лучший: 'g7g6', линии: [{ оценка: { cp: -40 }, линия: ['g7g6'] }, { оценка: { cp: свой }, линия: ['d8e7'] }] };
            }
        });

        const хорош = await оценитьОтвет(движок(-60), з, 'd8e7');
        assert(хорош.принят, `потеря ${хорош.потеря}`);

        const плох = await оценитьОтвет(движок(-300), з, 'd8e7');
        assert(!плох.принят && плох.потеря > 15, `потеря ${плох.потеря}`);
    });

    it('очередь: сначала пора повторить, потом новые — зевки раньше; выученные не идут', () => {
        const з = (id, класс, изменена) => ({ id, класс, изменена, полуход: 1 });
        const задачи = [з('a', 'ошибка', 3), з('b', 'зевок', 1), з('c', 'ошибка', 2), з('d', 'зевок', 5), з('e', 'ошибка', 9)];
        const учёт = {
            c: { когда: 100 },
            d: { когда: 5000 },
            e: { выучена: true, когда: 0 }
        };

        const о = очередьСвоих(задачи, учёт, 1000);
        equal(о.очередь.map((x) => x.id), ['c', 'b', 'a']);
        equal(о.выучено, 1);
        equal(о.следующая, 5000);
    });
});

describe('Задачи: учёт', () => {
    const ключ = 'chess.test.задачи-учёт';

    it('следующая: пачка грузится один раз, дальше — из запаса; виденные не повторяются', async () => {
        const ф = поддельнаяЗагрузка([МАТ_В_ДВА, МАТ_В_ОДИН]);
        const з = создатьЗадачник(ключ, { загрузка: ф });
        з.стереть();

        const первая = await з.следующая();
        equal(первая.задача.id, 'li:1NElZ');
        assert(ф.адреса[0].includes('difficulty=normal'), 'начальный уровень — средние');

        const вторая = await з.следующая();
        equal(вторая.задача.id, 'li:tst01');

        // Та же пачка снова — всё уже видено, новых нет
        const третья = await з.следующая();
        equal(третья.задача, null);
        assert(третья.заметка, 'нет объяснения, почему задачи нет');
        з.стереть();
    });

    it('без сети — задача из запаса другой сложности, с пометкой', async () => {
        const з = создатьЗадачник(ключ, { загрузка: поддельнаяЗагрузка([МАТ_В_ДВА]) });
        з.стереть();
        з.настроить({ уровень: 'hardest' });
        await з.пополнить();
        equal(з.вЗапасе(), 1);

        з.настроить({ уровень: 'easiest' });
        з.задатьЗагрузку(async () => { throw new TypeError('Failed to fetch'); });
        const р = await з.следующая();
        equal(р.задача?.id, 'li:1NElZ');
        assert(/Нет связи.*из запаса/.test(р.заметка), р.заметка);
        з.стереть();
    });

    it('тема сменилась, пока грузилась прежняя, — грузится новая, а не подсовывается старая', async () => {
        let отпустить;
        const адреса = [];
        const з = создатьЗадачник(ключ, {
            загрузка: async (адрес) => {
                адреса.push(адрес);
                const пачка = адрес.includes('/mateIn1?') ? [МАТ_В_ОДИН] : [МАТ_В_ДВА];
                if (адреса.length === 1) await new Promise((r) => { отпустить = r; });
                return { ok: true, status: 200, json: async () => ({ puzzles: пачка }) };
            }
        });
        з.стереть();

        const прежняя = з.пополнить();
        з.настроить({ тема: 'mateIn1' });
        const ждём = з.следующая();
        отпустить();
        await прежняя;
        const р = await ждём;

        equal(р.задача?.id, 'li:tst01', `пришла задача ${р.задача?.id} по теме ${р.задача?.тема}`);
        assert(адреса.some((а) => а.includes('/mateIn1?')), 'новую тему у lichess не спросили');
        з.стереть();
    });

    it('задача не своей темы из запаса — с пометкой, даже без ошибки сети', async () => {
        const з = создатьЗадачник(ключ, { загрузка: поддельнаяЗагрузка([]) });
        з.стереть();
        з.настроить({ запас: [изLichess(МАТ_В_ДВА, 'mix', 'normal')], тема: 'fork' });
        const р = await з.следующая();
        equal(р.задача?.id, 'li:1NElZ');
        assert(/из запаса/.test(р.заметка), `нет пометки: «${р.заметка}»`);
        з.стереть();
    });

    it('после «подождите минуту» lichess минуту не спрашивают', async () => {
        const ф = поддельнаяЗагрузка([], { статус: 429 });
        const з = создатьЗадачник(ключ, { загрузка: ф });
        з.стереть();

        const первая = await з.следующая();
        assert(/подождать минуту/.test(первая.заметка), первая.заметка);
        await з.следующая();
        await з.следующая();
        equal(ф.адреса.length, 1, `обращений к lichess: ${ф.адреса.length}`);
        з.стереть();
    });

    it('итог: рейтинг, серия, история; с подсказкой рейтинг не меняется', () => {
        const з = создатьЗадачник(ключ);
        з.стереть();
        const задача = { рейтинг: 1500 };

        const р = з.засчитать(задача, { решена: true });
        equal(р.было, НАЧАЛЬНЫЙ_РЕЙТИНГ);
        assert(р.стало > р.было);
        equal(з.состояние().серия, 1);

        const с = з.засчитать(задача, { решена: true, подсказка: true });
        equal(с.стало, с.было, 'с подсказкой рейтинг сдвинулся');
        equal(з.состояние().серия, 0);

        з.засчитать(задача, { решена: false });
        const у = з.состояние();
        equal(у.сыграно, 3);
        equal(у.решено, 1);
        equal(у.лучшаяСерия, 1);
        equal(у.история.length, 3);
        з.стереть();
    });

    it('своя задача: ящики повторения; выучена после четырёх решений подряд, ошибка — заново', () => {
        const з = создатьЗадачник(ключ);
        з.стереть();
        const задача = { id: 'g1:6' };

        let у = з.отметитьСвою(задача, false, 0);
        equal(у.ящик, 0);
        equal(у.когда, ИНТЕРВАЛЫ[0], 'не решённая — через десять минут');

        for (let i = 1; i <= 3; i++) {
            у = з.отметитьСвою(задача, true, 0);
            equal(у.ящик, i);
            equal(у.когда, ИНТЕРВАЛЫ[i]);
            assert(!у.выучена);
        }

        у = з.отметитьСвою(задача, true, 0);
        assert(у.выучена, 'четвёртое решение подряд — выучена');

        у = з.отметитьСвою({ id: 'g1:8' }, true, 0);
        у = з.отметитьСвою({ id: 'g1:8' }, false, 0);
        equal(у.ящик, 0, 'ошибка возвращает в первый ящик');
        з.стереть();
    });

    it('чьи ошибки: авто — владелец архива, «все» — обе стороны', () => {
        const з = создатьЗадачник(ключ);
        з.стереть();
        const партии = [партияСРазбором(), партияСРазбором({ id: 'g2' }), партияСРазбором({ id: 'g3', белые: 'Klaus', чёрные: 'Max' })];

        equal(з.чьи(партии), 'Klaus');
        equal(з.свои(партии).задачи.length, 2, 'ошибки Klaus — в двух партиях за чёрных');

        з.настроить({ чьи: 'все' });
        equal(з.свои(партии).задачи.length, 3);
        з.стереть();
    });
});
