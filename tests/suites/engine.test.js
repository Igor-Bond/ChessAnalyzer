describe('Stockfish', () => {
    it('находит мат в один ход', async () => {
        // Мат по последней горизонтали: Ta8#
        const о = await движок().оценить('6k1/5ppp/8/8/8/8/5PPP/R5K1 w - - 0 1', { глубина: 8, линий: 1 });
        equal(о.лучший, 'a1a8');
        equal(о.линии[0].оценка, { мат: 1 });
    });

    it('даёт две линии при MultiPV 2', async () => {
        const о = await движок().оценить('rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1', { глубина: 8, линий: 2 });
        equal(о.линии.length, 2);
        assert(о.линии[0].линия.length > 0, 'пустая линия');
    });

    it('запросы подряд не путаются: каждый получает свою позицию', async () => {
        const [а, б] = await Promise.all([
            движок().оценить('6k1/5ppp/8/8/8/8/5PPP/R5K1 w - - 0 1', { глубина: 6, линий: 1 }),
            движок().оценить('r5k1/5ppp/8/8/8/8/5PPP/6K1 b - - 0 1', { глубина: 6, линий: 1 })
        ]);
        equal(а.лучший, 'a1a8');
        equal(б.лучший, 'a8a1');
    });
});

/**
 * Поддельный движок: отвечает на знакомство, а на «go» ведёт себя как
 * сломанный — молчит или падает. Настоящий Stockfish так себя ведёт на
 * телефоне, которому не хватило памяти, и проверить это иначе нельзя.
 */
function поддельный(наGo) {
    const код = `onmessage = (e) => {
        const к = String(e.data);
        if (к === 'uci') postMessage('uciok');
        else if (к === 'isready') postMessage('readyok');
        else if (к.startsWith('go')) { ${наGo} }
    };`;
    return URL.createObjectURL(new Blob([код], { type: 'text/javascript' }));
}

/** Обещание обязано отказать за срок; зависание — провал, а не вечное ожидание. */
async function отказ(обещание, срок = 3000) {
    let часы;
    const итог = await Promise.race([
        обещание.then(() => 'выполнилось', (e) => e),
        new Promise((r) => { часы = setTimeout(() => r('зависло'), срок); })
    ]);
    clearTimeout(часы);

    if (итог === 'зависло') throw new Error(`не отказало за ${срок} мс — зависло`);
    if (итог === 'выполнилось') throw new Error('ожидался отказ, а запрос выполнился');
    return итог.message;
}

const НАЧАЛО = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';

describe('Сломанный движок', () => {
    it('молчащий движок: запрос отказывает по сроку, а не висит', async () => {
        const д = new Движок(поддельный(''), { срок: 300, видно: () => true });
        const текст = await отказ(д.оценить(НАЧАЛО, { глубина: 5 }));
        assert(/не отвечает/.test(текст), текст);
        д.остановить();
    });

    it('после отказа очередь не застревает: следующий запрос тоже получает ответ', async () => {
        const д = new Движок(поддельный(''), { срок: 300, видно: () => true });
        await отказ(д.оценить(НАЧАЛО, { глубина: 5 }));
        await отказ(д.оценить(НАЧАЛО, { глубина: 5 }));
        д.остановить();
    });

    it('упавший посреди счёта поток — отказ сразу, без ожидания срока', async () => {
        const д = new Движок(поддельный("throw new Error('wasm abort')"), { срок: 60000 });
        const текст = await отказ(д.оценить(НАЧАЛО, { глубина: 5 }), 3000);
        assert(/упал|не отвечает|abort/i.test(текст), текст);
        equal(д.поток, null, 'упавший поток не убран');
        д.остановить();
    });
});

describe('Медленный, но живой движок', () => {
    it('долгий расчёт со строками info — не зависание: ответ дожидается', async () => {
        // Считает 900 мс, подавая голос каждые 100 мс, — дольше срока в 300 мс.
        // Так считает настоящий Stockfish на глубине 18 на слабом телефоне
        const д = new Движок(поддельный(`
            let n = 0;
            const т = setInterval(() => {
                postMessage('info depth ' + (++n) + ' score cp 10 nodes 100 pv e2e4');
                if (n === 9) { clearInterval(т); postMessage('bestmove e2e4'); }
            }, 100);
        `), { срок: 300, видно: () => true });

        const ответ = await д.оценить(НАЧАЛО, { глубина: 5, линий: 1 });
        equal(ответ.лучший, 'e2e4');
        д.остановить();
    });

    it('пока приложение не на экране, молчание движка не считается', async () => {
        // Телефон убрал приложение в фон: движок заморожен и молчит. Это не
        // поломка — срок идёт только пока приложение видно
        let видно = false;
        const д = new Движок(поддельный(''), { срок: 300, видно: () => видно });
        const ответ = д.оценить(НАЧАЛО, { глубина: 5, линий: 1 }).then(() => 'ответил', (e) => e.message);

        await new Promise((r) => setTimeout(r, 900));
        const пока = await Promise.race([ответ, new Promise((r) => setTimeout(() => r('ждёт'), 10))]);
        equal(пока, 'ждёт', 'срок сработал, пока приложение было в фоне');

        // Вернулись в приложение, а движок так и молчит — вот это поломка
        видно = true;
        const итог = await Promise.race([ответ, new Promise((r) => setTimeout(() => r('зависло'), 3000))]);
        assert(/не отвечает/.test(итог), итог);
        д.остановить();
    });
});

describe('Разбор настоящей партии', () => {
    it('детский мат: 3…Sf6 — зевок, 4.Dxf7# — единственный', async () => {
        const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Bc4', 'Nc6', 'Qh5', 'Nf6', 'Qxf7#'] };
        const разбор = await разобратьПартию(п, движок(), { глубина: 8 });

        equal(разбор.оценки.length, 8);
        equal(разбор.оценки[7].оценка.мат, 0, 'финальная позиция — мат на доске');

        const ходы = разобратьХоды(позиции(п), разбор.оценки);
        equal(ходы[5].san, 'Nf6');
        equal(ходы[5].класс, 'зевок');
        // Единственный, а не просто лучший: ферзя h5 бьёт конь f6, и любой
        // другой ход белых стоит им перевеса (второй по силе — около −2.5)
        equal(ходы[6].класс, 'единственный');
        equal(ходы[6].лучший, 'h5f7');

        // После хода чёрных позиция оценена в пользу белых — знак переведён верно
        assert(разбор.оценки[6].оценка.мат > 0, `после Sf6: ${JSON.stringify(разбор.оценки[6].оценка)}`);

        assert(разборПолон({ ...п, разбор }), 'разбор не признан полным');
    });

    it('повторный разбор берёт готовые оценки и не зовёт движок', async () => {
        const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Nf3'] };
        п.разбор = await разобратьПартию(п, движок(), { глубина: 6 });

        const спрошено = [];
        const счётчик = {
            новаяПартия: async () => {},
            оценить: async (fen) => { спрошено.push(fen); return { лучший: 'a2a3', линии: [] }; }
        };

        const дальше = { ...п, ходы: [...п.ходы, 'Nc6'] };
        const снова = await разобратьПартию(дальше, счётчик, { глубина: 6 });
        const новая = позиции(дальше)[4].fen;

        assert(спрошено.length > 0 && спрошено.every((f) => f === новая), 'переоценены уже оцененные позиции');
        equal(снова.оценки.length, 5);
    });
});

/**
 * Поддельный движок для проверок порядка работы: записывает каждый запрос
 * и отвечает «лучшим» тем ходом, который подсказан для этой позиции.
 */
function записывающий(лучшие) {
    const запросы = [];
    return {
        запросы,
        новаяПартия: async () => {},
        async оценить(fen, параметры) {
            запросы.push({ fen, ...параметры });
            const лучший = параметры.ходы ? параметры.ходы[0] : (лучшие[fen] || 'a2a3');
            return { лучший, линии: [{ оценка: { cp: 10 }, линия: [лучший], глубина: параметры.глубина, multipv: 1 }] };
        }
    };
}

describe('Ускоренный разбор', () => {
    const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Nf3', 'Nc6'] };
    const поз = позиции(п);

    // Сыгран лучший ход в позициях 0 и 2 (e4 и Nf3), в 1 и 3 — нет
    const лучшие = { [поз[0].fen]: 'e2e4', [поз[1].fen]: 'a7a6', [поз[2].fen]: 'g1f3', [поз[3].fen]: 'a7a6' };

    it('движок считает одну линию, вторую — только где сыгран лучший ход, без него', async () => {
        const д = записывающий(лучшие);
        const р = await разобратьПартию(п, д, { глубина: 14, быстро: 0 });

        const основные = д.запросы.filter((з) => !з.ходы);
        assert(основные.every((з) => з.линий === 1), 'основной расчёт не в одну линию');

        const вторые = д.запросы.filter((з) => з.ходы);
        equal(вторые.map((з) => з.fen), [поз[0].fen, поз[2].fen]);
        assert(!вторые[0].ходы.includes('e2e4'), 'вторая линия не исключила лучший ход');
        assert(вторые.every((з) => з.глубина < 14), 'вторая линия считается на полной глубине — это дорого');

        assert(р.оценки[0].второй && р.оценки[2].второй, 'нет второй линии там, где сыгран лучший');
        equal(р.оценки[1].второй, null);
    });

    it('сначала вся партия быстро на малой глубине, потом уточнение', async () => {
        const д = записывающий(лучшие);
        const снимки = [];
        const р = await разобратьПартию(п, д, { глубина: 14, быстро: 8, наПозицию: (с) => снимки.push(с) });

        const глубины = д.запросы.filter((з) => !з.ходы).map((з) => з.глубина);
        equal(глубины, [8, 8, 8, 8, 8, 14, 14, 14, 14, 14], 'порядок проходов не тот');

        // Уже первый снимок после быстрого прохода показывает всю партию
        const первыйПолный = снимки.find((с) => с.оценки.filter(Boolean).length === поз.length);
        assert(первыйПолный && первыйПолный.глубины.every((г) => г === 8), 'после быстрого прохода партия не показана целиком');

        assert(р.глубины.every((г) => г === 14), 'уточнение прошло не везде');
        assert(разборПолон({ ...п, разбор: р }), 'уточнённый разбор не признан полным');
        assert(!разборПолон({ ...п, разбор: первыйПолный }), 'предварительный разбор признан полным');
    });
});
