/**
 * «Детально» — подробности по игроку на подставленных оценках.
 */

import { describe, it, equal, assert } from '../runner.js';
import { позиции, новаяПартия } from '../../js/core/game.js';
import { разобратьХоды } from '../../js/core/review.js';
import { подробно } from '../../js/core/details.js';

/** Партия и оценки: белые зевают на 3-м полуходе, чёрные отвечают неточно. */
function разбор() {
    const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Qh5', 'Nc6', 'Qxf7+', 'Kxf7'] };
    const поз = позиции(п);
    // Оценки за белых: Qh5 сыгран, лучший был Nf3; Qxf7+ — зевок ферзя
    const cp = [20, 20, 10, 10, 10, -700, -700];
    const лучшие = ['e2e4', 'e7e5', 'g1f3', 'b8c6', 'f1c4', 'e8f7', 'a2a3'];
    const оценки = cp.map((c, i) => ({ оценка: { cp: c }, лучший: лучшие[i], линия: [лучшие[i]], второй: null, ходов: 20 }));
    return { поз, ходы: разобратьХоды(поз, оценки) };
}

describe('Детально', () => {
    it('по фигурам: ход ферзём — с ошибкой, пешкой — точно', () => {
        const д = подробно(разбор(), 'w');
        equal(д.поФигурам.q.ходов, 2);
        equal(д.поФигурам.q.ошибок, 1);
        equal(д.поФигурам.p.ходов, 1);
        equal(д.поФигурам.n, null);
    });

    it('ошибки — с лучшим ходом в записи', () => {
        const д = подробно(разбор(), 'w');
        equal(д.ошибки.length, 1);
        equal(д.ошибки[0].san, 'Qxf7+');
        equal(д.ошибки[0].лучший, 'Bc4');
    });

    it('серия точных ходов и взятия с шахами', () => {
        const ч = подробно(разбор(), 'b');
        equal(ч.серия.длина, 3);
        equal(ч.взятий, 1);

        const б = подробно(разбор(), 'w');
        equal(б.шахов, 1);
        equal(б.взятий, 1);
    });

    it('упущенный шанс: соперник ошибся, а ответ его не наказал', () => {
        const р = разбор();
        // Подменяем: после зевка белых чёрные ответили плохо
        р.ходы[5] = { ...р.ходы[5], потеря: 25, класс: 'зевок' };
        const ч = подробно(р, 'b');
        equal(ч.упущенные.length, 1);
        equal(ч.упущенные[0].полуход, 6);
        assert(ч.упущенные[0].подарок >= 10);
    });

    it('точность по ходам — по одному на ход стороны', () => {
        const д = подробно(разбор(), 'w');
        equal(д.точностьПоХодам.map((т) => т.полуход), [1, 3, 5]);
    });
});
