/**
 * Архив: сохранение, порядок, устойчивость к мусору.
 */

import { describe, it, equal, assert } from '../runner.js';
import { хранилище, НАСТРОЙКИ_ПО_УМОЛЧАНИЮ } from '../../js/core/store.js';
import { новаяПартия } from '../../js/core/game.js';

describe('Хранилище', () => {
    it('ключ проверок не совпадает с настоящим', () => {
        equal(globalThis.__CHESS_KEY__, 'chess.test');
    });

    it('сохранённая партия читается обратно', () => {
        хранилище.стереть();
        const п = хранилище.сохранить({ ...новаяПартия(), белые: 'Igor', ходы: ['e4'] });
        equal(хранилище.партия(п.id).белые, 'Igor');
        equal(хранилище.партия(п.id).ходы, ['e4']);
    });

    it('архив — от последних изменённых к ранним', async () => {
        хранилище.стереть();
        const а = хранилище.сохранить(новаяПартия());
        await new Promise((r) => setTimeout(r, 5));
        const б = хранилище.сохранить(новаяПартия());
        equal(хранилище.партии().map((п) => п.id), [б.id, а.id]);
    });

    it('разбор не поднимает партию наверх архива', async () => {
        хранилище.стереть();
        const а = хранилище.сохранить(новаяПартия());
        await new Promise((r) => setTimeout(r, 5));
        const б = хранилище.сохранить(новаяПартия());
        хранилище.сохранитьРазбор(а.id, { версия: 1, глубина: 10, fens: [], оценки: [] });
        equal(хранилище.партии()[0].id, б.id);
        assert(хранилище.партия(а.id).разбор, 'разбор не сохранился');
    });

    it('удаление', () => {
        хранилище.стереть();
        const п = хранилище.сохранить(новаяПартия());
        хранилище.удалить(п.id);
        equal(хранилище.партия(п.id), null);
    });

    it('испорченное содержимое не ломает запуск', () => {
        localStorage.setItem('chess.test', '{"партии": {"x": 5, "y": {"ходы": "не массив"}}, "настройки": {"нотация": "zz", "глубина": 99}}');
        equal(хранилище.партии(), []);
        equal(хранилище.настройки(), НАСТРОЙКИ_ПО_УМОЛЧАНИЮ);

        localStorage.setItem('chess.test', 'не json');
        equal(хранилище.партии(), []);
        хранилище.стереть();
    });

    it('настройки: нотация и глубина', () => {
        хранилище.стереть();
        хранилище.настроить({ нотация: 'ru', глубина: 18 });
        equal(хранилище.настройки(), { нотация: 'ru', глубина: 18 });
        хранилище.стереть();
    });
});
