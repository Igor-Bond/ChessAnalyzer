/**
 * Разбор написанного хода и показ хода буквами нотации.
 *
 * Здесь собраны записи, которые реально встречаются на бланках: немецкие
 * буквы, двоеточие вместо «x», длинная запись, рокировка нулями, превращение
 * без знака равенства, русская раскладка. Каждая из них однажды не
 * понималась бы, и человек решил бы, что приложение не умеет его бланк.
 */

import { describe, it, equal, assert } from '../runner.js';
import { Chess } from '../../js/core/chess.js';
import { найтиХод, показатьХод } from '../../js/core/notation.js';

function san(текст, fen) {
    const р = найтиХод(new Chess(fen), текст);
    return р.ход ? р.ход.san : `ОШИБКА: ${р.ошибка}`;
}

function после(ходы) {
    const д = new Chess();
    for (const х of ходы) д.move(х);
    return д.fen();
}

describe('Ввод хода: нотации', () => {
    it('пешечный ход в любой нотации одинаков', () => {
        equal(san('e4'), 'e4');
        equal(san('e2-e4'), 'e4');
        equal(san('e2e4'), 'e4');
    });

    it('немецкие буквы: S — конь, L — слон, D — ферзь, T — ладья', () => {
        equal(san('Sf3'), 'Nf3');
        equal(san('Lc4', после(['e4', 'e5'])), 'Bc4');
        equal(san('Dh5', после(['e4', 'e5'])), 'Qh5');
        equal(san('Th2', после(['h4', 'e5'])), 'Rh2');
    });

    it('английские буквы понимаются без смены настроек', () => {
        equal(san('Nf3'), 'Nf3');
        equal(san('Bc4', после(['e4', 'e5'])), 'Bc4');
        equal(san('Qh5', после(['e4', 'e5'])), 'Qh5');
    });

    it('русские буквы: К — конь, С — слон, Ф — ферзь, Кр — король', () => {
        equal(san('Кf3'), 'Nf3');
        equal(san('Сc4', после(['e4', 'e5'])), 'Bc4');
        equal(san('Фh5', после(['e4', 'e5'])), 'Qh5');
        equal(san('Крe2', после(['e4', 'e5'])), 'Ke2');
    });

    it('поля, набранные русской раскладкой (кириллические а, с, е)', () => {
        equal(san('Кс3'), 'Nc3');
        equal(san('е4'), 'e4');
        equal(san('с4'), 'c4');
    });

    it('строчная буква фигуры с телефонной клавиатуры', () => {
        equal(san('sf3'), 'Nf3');
        equal(san('nf3'), 'Nf3');
    });

    it('длинная запись фигурой: Sg1-f3 и Sg1f3', () => {
        equal(san('Sg1-f3'), 'Nf3');
        equal(san('Ng1f3'), 'Nf3');
    });
});

describe('Ввод хода: взятия, шахи, рокировки', () => {
    const испанская = после(['e4', 'e5', 'Nf3', 'Nc6', 'Bb5', 'a6']);

    it('взятие через x, через двоеточие и без знака', () => {
        equal(san('Lxc6', испанская), 'Bxc6');
        equal(san('L:c6', испанская), 'Bxc6');
        equal(san('Lc6', испанская), 'Bxc6');
        equal(san('Lb5:c6', испанская), 'Bxc6');
    });

    it('пешечное взятие: exd5, ed5, e:d5', () => {
        const fen = после(['e4', 'd5']);
        equal(san('exd5', fen), 'exd5');
        equal(san('ed5', fen), 'exd5');
        equal(san('e:d5', fen), 'exd5');
    });

    it('строчная b — вертикаль, а не слон: bxc3', () => {
        const fen = после(['b4', 'd5', 'b5', 'Nc6', 'b6', 'e5', 'h3', 'Bd6', 'h4', 'Nf6']);
        // На b6 белая пешка, берёт c7 — проверяем именно пешечное прочтение
        equal(san('bxc7', fen), 'bxc7');
    });

    it('знаки шаха, мата и оценки не мешают', () => {
        equal(san('Sf3+!?'), 'Nf3');
        equal(san('e4!!'), 'e4');
    });

    it('рокировка нулями, буквами и ходом короля', () => {
        const fen = после(['e4', 'e5', 'Nf3', 'Nc6', 'Bc4', 'Bc5']);
        equal(san('0-0', fen), 'O-O');
        equal(san('O-O', fen), 'O-O');
        equal(san('00', fen), 'O-O');
        equal(san('Kg1', fen), 'O-O');
    });

    it('длинная рокировка', () => {
        const fen = после(['d4', 'd5', 'Nc3', 'Nc6', 'Bf4', 'Bf5', 'Qd2', 'Qd7']);
        equal(san('0-0-0', fen), 'O-O-O');
    });

    it('невозможная рокировка — понятный отказ', () => {
        assert(san('0-0').startsWith('ОШИБКА'), 'в начальной позиции рокировки нет');
    });
});

describe('Ввод хода: превращение и неоднозначность', () => {
    const превращение = '8/4P3/8/8/8/8/k7/7K w - - 0 1';

    it('превращение с буквой в любой записи: e8D, e8=D, e8Q, e8(D)', () => {
        equal(san('e8D', превращение), 'e8=Q');
        equal(san('e8=D', превращение), 'e8=Q');
        equal(san('e8Q', превращение), 'e8=Q');
        equal(san('e8(D)', превращение), 'e8=Q');
    });

    it('превращение в коня немецкой буквой', () => {
        equal(san('e8S', превращение), 'e8=N');
        equal(san('e8=N', превращение), 'e8=N');
    });

    it('превращение без буквы — ферзь', () => {
        equal(san('e8', превращение), 'e8=Q');
    });

    it('два коня на одно поле — отказ с вариантами', () => {
        const fen = после(['Nf3', 'e5', 'Nc3', 'e4', 'Nd4', 'a6', 'Nb3', 'a5', 'e3', 'a4', 'Ne2', 'a3']);
        // Кони b3 и e2 оба могут пойти на d4
        const р = найтиХод(new Chess(fen), 'Sd4');
        assert(!р.ход, 'неоднозначный ход принят');
        assert(/Неоднозначно/.test(р.ошибка), р.ошибка);
        equal(san('Sbd4', fen), 'Nbd4');
        equal(san('Sed4', fen), 'Ned4');
    });

    it('невозможный ход — отказ, а не что-то похожее', () => {
        assert(san('Sf4').startsWith('ОШИБКА'));
        assert(san('e5').startsWith('ОШИБКА'));
        assert(san('абв').startsWith('ОШИБКА'));
    });
});

describe('Показ хода в нотации', () => {
    it('немецкая: буквы фигур и превращения, рокировка нулями', () => {
        equal(показатьХод('Nf3', 'de'), 'Sf3');
        equal(показатьХод('Bxe5+', 'de'), 'Lxe5+');
        equal(показатьХод('Qd8#', 'de'), 'Dd8#');
        equal(показатьХод('Rae1', 'de'), 'Tae1');
        equal(показатьХод('exd8=Q+', 'de'), 'exd8=D+');
        equal(показатьХод('O-O-O', 'de'), '0-0-0');
    });

    it('строчные вертикали не путаются с фигурами: b4, bxc3', () => {
        equal(показатьХод('b4', 'de'), 'b4');
        equal(показатьХод('bxc3', 'de'), 'bxc3');
        equal(показатьХод('Bb4', 'de'), 'Lb4');
    });

    it('русская и английская', () => {
        equal(показатьХод('Kxe2', 'ru'), 'Крxe2');
        equal(показатьХод('Nf3', 'ru'), 'Кf3');
        equal(показатьХод('O-O', 'en'), 'O-O');
        equal(показатьХод('Nf3', 'en'), 'Nf3');
    });

    it('показанный ход читается вводом обратно', () => {
        const fen = после(['e4', 'e5', 'Nf3', 'Nc6', 'Bb5', 'a6']);
        const д = new Chess(fen);

        for (const ход of д.moves()) {
            for (const нотация of ['de', 'en', 'ru']) {
                equal(san(показатьХод(ход, нотация), fen), ход, `${нотация}: ${показатьХод(ход, нотация)}`);
            }
        }
    });
});
