/**
 * Арифметика разбора — без движка, на подставленных оценках.
 *
 * Оценки здесь придуманы, позиции настоящие: классы ходов зависят только от
 * чисел, а числа можно подобрать так, чтобы проверить каждый порог.
 */

import { describe, it, equal, assert } from '../runner.js';
import { позиции, новаяПартия } from '../../js/core/game.js';
import {
    шансыБелых, шансыСтороны, точностьХода, заБелых, показатьОценку, стадия,
    разобратьХоды, точностьПартии, сводка, переломы, оценкаКонца
} from '../../js/core/review.js';

const близко = (а, б, допуск = 0.5) => Math.abs(а - б) <= допуск;

describe('Шансы и точность', () => {
    it('равная позиция — 50%, преимущество растёт к 100', () => {
        equal(шансыБелых({ cp: 0 }), 50);
        assert(близко(шансыБелых({ cp: 100 }), 59.1), `+1: ${шансыБелых({ cp: 100 })}`);
        assert(близко(шансыБелых({ cp: 300 }), 75.2), `+3: ${шансыБелых({ cp: 300 })}`);
        assert(шансыБелых({ cp: -300 }) < 25);
    });

    it('мат — крайние значения', () => {
        assert(шансыБелых({ мат: 3 }) > 97);
        assert(шансыБелых({ мат: -2 }) < 3);
    });

    it('шансы чёрных — дополнение до ста', () => {
        equal(Math.round(шансыСтороны({ cp: 100 }, 'b') + шансыСтороны({ cp: 100 }, 'w')), 100);
    });

    it('точность хода: ноль потерь — сто, большие потери — к нулю', () => {
        equal(точностьХода(0), 100);
        assert(близко(точностьХода(10), 64.5, 1.5), `${точностьХода(10)}`);
        assert(точностьХода(60) < 10);
        assert(точностьХода(100) >= 0);
    });

    it('оценка движка переводится на сторону белых', () => {
        equal(заБелых({ cp: 50 }, 'w'), { cp: 50 });
        equal(заБелых({ cp: 50 }, 'b'), { cp: -50 });
        equal(заБелых({ мат: 2 }, 'b'), { мат: -2 });
    });

    it('показ оценки', () => {
        equal(показатьОценку({ cp: 85 }), '+0.85');
        equal(показатьОценку({ cp: -120 }), '−1.20');
        equal(показатьОценку({ cp: 0 }), '0.00');
        equal(показатьОценку({ мат: 3 }), '#3');
        equal(показатьОценку({ мат: -2 }), '#−2');
    });

    it('мат на доске оценивается без движка', () => {
        const п = { ...новаяПартия(), ходы: ['f3', 'e5', 'g4', 'Qh4#'] };
        const конец = оценкаКонца(позиции(п)[4].fen);
        assert(конец && конец.мат === 0 && конец.проигралБелые === true, JSON.stringify(конец));
        // Мат lichess считает как ±10 пешек — это около 2%, а не ноль
        assert(шансыБелых(конец) < 3);
    });
});

describe('Стадии партии', () => {
    it('начальная позиция — дебют', () => {
        equal(стадия('rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1'), 'дебют');
    });

    it('развитые фигуры — миттельшпиль', () => {
        equal(стадия('r2q1rk1/ppp2ppp/2np1n2/2b1p1B1/2B1P1b1/2NP1N2/PPP2PPP/R2Q1RK1 w - - 0 8'), 'миттельшпиль');
    });

    it('ладейный эндшпиль', () => {
        equal(стадия('8/5pk1/6p1/8/3R4/6P1/r4PK1/8 w - - 0 40'), 'эндшпиль');
    });
});

/** Партия из четырёх ходов и оценки, подобранные под пороги. */
function испытание(оценкиБелых, лучшие, вторые = []) {
    const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Nf3', 'Nc6'] };
    const поз = позиции(п);

    const оценки = оценкиБелых.map((cp, i) => ({
        оценка: { cp },
        лучший: лучшие[i] || 'a2a3',
        линия: [лучшие[i] || 'a2a3'],
        второй: вторые[i] !== undefined ? { cp: вторые[i] } : null,
        ходов: 20
    }));

    return { п, поз, оценки, ходы: разобратьХоды(поз, оценки) };
}

describe('Классы ходов', () => {
    it('сыгран ход движка — «лучший», потерь нет, даже если оценка поплыла', () => {
        const { ходы } = испытание([30, 10, 30, 30, 30], ['e2e4', 'e7e5', 'g1f3', 'b8c6']);
        equal(ходы.map((х) => х.класс), ['лучший', 'лучший', 'лучший', 'лучший']);
        equal(ходы[0].потеря, 0);
        equal(ходы[0].точность, 100);
    });

    it('пороги: отличный, хороший, неточность, ошибка, зевок', () => {
        // Шансы белых по оценкам: 0→50, −10→49.1, −40→46.3, −80→42.7, −170→34.8, −600→9.9
        const { ходы } = испытание([0, -40, -40, -40, -40], []);
        equal(ходы[0].класс, 'хороший', `потеря ${ходы[0].потеря}`);

        const н = испытание([0, -80, -80, -80, -80], []);
        equal(н.ходы[0].класс, 'неточность', `потеря ${н.ходы[0].потеря}`);

        const о = испытание([0, -170, -170, -170, -170], []);
        equal(о.ходы[0].класс, 'ошибка', `потеря ${о.ходы[0].потеря}`);

        const з = испытание([0, -600, -600, -600, -600], []);
        equal(з.ходы[0].класс, 'зевок', `потеря ${з.ходы[0].потеря}`);

        const от = испытание([0, -10, -10, -10, -10], []);
        equal(от.ходы[0].класс, 'отличный', `потеря ${от.ходы[0].потеря}`);
    });

    it('потеря считается со стороны сыгравшего: ход чёрных, улучшивший позицию белых, — их ошибка', () => {
        const { ходы } = испытание([0, 0, 150, 150, 150], ['e2e4']);
        equal(ходы[1].сторона, 'b');
        equal(ходы[1].класс, 'ошибка');
    });

    it('единственный ход: лучший сыгран, второй намного хуже', () => {
        const { ходы } = испытание([0, 0, 0, 0, 0], ['e2e4'], [-400]);
        equal(ходы[0].класс, 'единственный');
    });

    it('вынужденный ход не считается в точность', () => {
        const п = { ...новаяПартия(), ходы: ['e4'] };
        const поз = позиции(п);
        const оценки = [{ оценка: { cp: 0 }, лучший: 'd2d4', линия: [], второй: null, ходов: 1 }, { оценка: { cp: -500 }, лучший: null, линия: [], второй: null, ходов: 20 }];
        const [х] = разобратьХоды(поз, оценки);
        equal(х.класс, 'вынужденный');
        equal(х.точность, null);
    });
});

describe('Итоги партии', () => {
    it('точность сторон: безошибочная — около ста, с зевком — заметно ниже', () => {
        const { поз, оценки, ходы } = испытание([20, 20, 20, -500, -500], ['e2e4', 'e7e5', 'd2d4', 'b8c6']);
        const т = точностьПартии(поз, оценки, ходы);
        assert(т.b > 95, `чёрные ${т.b}`);
        assert(т.w < 70, `белые ${т.w}`);
    });

    it('сводка: счёт классов и средняя потеря', () => {
        const { поз, оценки, ходы } = испытание([20, 20, 20, -500, -500], ['e2e4', 'e7e5', 'd2d4', 'b8c6']);
        const с = сводка(поз, оценки, ходы);
        equal(с.w.классы.зевок, 1);
        equal(с.w.классы.лучший, 1);
        assert(с.w.средняяПотеря > 200, `${с.w.средняяПотеря}`);
        equal(с.b.средняяПотеря, 0);
        assert(с.w.стадии.дебют, 'нет стадии дебюта');
    });

    it('переломы: только заметные, по порядку партии', () => {
        const { ходы } = испытание([0, -600, -600, -600, -600], []);
        const п = переломы(ходы);
        equal(п.length, 1);
        equal(п[0].полуход, 1);
    });
});
