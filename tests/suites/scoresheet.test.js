/**
 * Сверка прочитанного бланка с правилами — без сети, на придуманных ответах.
 *
 * Ответы модели здесь сочинены так, как она реально ошибается: путает
 * похожие буквы и цифры (b5/b3, d7/d2, e6/c6), пропускает клетку, ставит
 * верное прочтение вторым. Каждая проверка — один такой случай.
 */

import { describe, it, equal, assert } from '../runner.js';
import { разобратьОтвет, сверить, сомнительные, вопрос, СХЕМА } from '../../js/core/scoresheet.js';
import { ai, причина } from '../../js/core/ai.js';

/** Полуходы из списка прочтений: каждое — строка или массив вариантов. */
function бланк(...клетки) {
    return клетки.map((к) => ({ прочтения: Array.isArray(к) ? к : [к], рамка: null, страница: 0 }));
}

describe('Ответ модели', () => {
    it('ходы в полуходы, пустой хвост отрезан, заголовки приведены', () => {
        const р = разобратьОтвет({
            white: ' Igor ', black: 'Klaus', date: '2026-09-27', result: '1 - 0',
            moves: [
                { n: 1, w: ['e4'], b: ['e5'], wBox: [100, 50, 130, 200], bBox: [100, 210, 130, 360] },
                { n: 2, w: ['Sf3', 'Sf5'], b: [], page: 0 }
            ]
        });

        equal(р.полуходы.length, 3);
        equal(р.полуходы[2].прочтения, ['Sf3', 'Sf5']);
        equal(р.полуходы[0].рамка, [100, 50, 130, 200]);
        equal(р.полуходы[2].рамка, null);
        equal(р.заголовки.белые, 'Igor');
        equal(р.заголовки.результат, '1-0');
        equal(р.заголовки.дата, '2026-09-27');
    });

    it('мусор вместо ответа — пустой бланк, а не падение', () => {
        equal(разобратьОтвет(null).полуходы, []);
        equal(разобратьОтвет({ moves: 'нет' }).полуходы, []);
        equal(разобратьОтвет({ moves: [{ w: [null, '', 'e4', 'e4'], b: 5 }] }).полуходы[0].прочтения, ['e4']);
    });

    it('вопрос называет немецкие буквы и просит не переводить; схема требует ходы', () => {
        const т = вопрос(2);
        assert(/S = knight/.test(т) && /L = bishop/.test(т), 'нет немецких букв');
        assert(/do not translate/i.test(т), 'нет запрета переводить');
        assert(/2 images/.test(т), 'не сказано про две страницы');
        equal(СХЕМА.required, ['moves']);
    });
});

describe('Сверка с правилами', () => {
    it('чистый бланк: всё уверенно', () => {
        const с = сверить(бланк('e4', 'e5', 'Sf3', 'Sc6', 'Lb5'));
        equal(с.ходы, ['e4', 'e5', 'Nf3', 'Nc6', 'Bb5']);
        equal(с.пометки.map((п) => п.статус), ['уверенно', 'уверенно', 'уверенно', 'уверенно', 'уверенно']);
        equal(с.остановка, null);
        equal(сомнительные(с), []);
    });

    it('первое прочтение невозможно — берётся второе и помечается «исправлено»', () => {
        // «Lb3» в этой позиции невозможен (слон f1 туда не ходит), «Lb5» — да
        const с = сверить(бланк('e4', 'e5', 'Sf3', 'Sc6', ['Lb3', 'Lb5']));
        equal(с.ходы.at(-1), 'Bb5');
        equal(с.пометки.at(-1).статус, 'исправлено');
        equal(сомнительные(с), [4]);
    });

    it('оба прочтения возможны — «сомнение», выбрано первое, варианты перечислены', () => {
        const с = сверить(бланк('e4', ['e6', 'c6']));
        equal(с.ходы, ['e4', 'e6']);
        equal(с.пометки[1].статус, 'сомнение');
        equal(с.пометки[1].варианты.map((в) => в.san), ['e6', 'c6']);
    });

    it('заглядывание вперёд: прочтение, ведущее в тупик, проигрывает даже первым', () => {
        // 2…d6 или 2…d5 — оба возможны, но «3. exd5» возможен только после d5
        const с = сверить(бланк('e4', 'e5', 'Sf3', ['d6', 'd5'], 'exd5'));
        equal(с.ходы, ['e4', 'e5', 'Nf3', 'd5', 'exd5']);
        equal(с.остановка, null);
        // Правила решили сами — спрашивать не о чем
        equal(с.пометки[3].статус, 'исправлено');
        equal(с.пометки[3].варианты.map((в) => в.san), ['d5']);
    });

    it('нечитаемая клетка — остановка на ней, прочитанное до неё сохранено', () => {
        const с = сверить(бланк('e4', 'e5', [], 'Sc6'));
        equal(с.ходы, ['e4', 'e5']);
        equal(с.остановка.полуход, 2);
        assert(/пустая/.test(с.остановка.причина), с.остановка.причина);
        equal(сомнительные(с), [2]);
    });

    it('ни одно прочтение не подходит — остановка с перечнем прочтений', () => {
        const с = сверить(бланк('e4', 'e5', ['Sf4', 'Sg4']));
        equal(с.остановка.полуход, 2);
        assert(/«Sf4», «Sg4»/.test(с.остановка.причина), с.остановка.причина);
    });

    it('«Sd2» без уточнения при двух конях — вопрос «какой конь», а не обрыв', () => {
        // После 1.Sf3 d5 2.d3 e5 на d2 могут пойти оба коня: b1 и f3
        const с = сверить(бланк('Sf3', 'd5', 'd3', 'e5', 'Sd2'));
        equal(с.остановка, null, `обрыв: ${с.остановка?.причина}`);
        equal(с.ходы.length, 5);
        equal(с.пометки[4].статус, 'сомнение');
        equal(с.пометки[4].варианты.map((в) => в.san).sort(), ['Nbd2', 'Nfd2']);
    });

    it('неоднозначный ход разрешается дальше по партии сам', () => {
        // «4. Sf3» возможен, только если с f3 ушёл конь, то есть после Sfd2:
        // после Sbd2 поле f3 занято своим конём. Правила выбрали коня сами,
        // а прочтение «Sd2» было верным — спрашивать не о чем
        const с = сверить(бланк('Sf3', 'd5', 'd3', 'e5', 'Sd2', 'Sc6', 'Sf3'));
        equal(с.остановка, null);
        equal(с.ходы[4], 'Nfd2');
        equal(с.пометки[4].статус, 'уверенно');
    });

    it('выбор человека закрепляется и ведёт сверку дальше', () => {
        const полуходы = бланк('e4', 'e5', [], 'Sc6', 'Lb5');
        const с = сверить(полуходы, { 2: 'Sf3' });
        equal(с.ходы, ['e4', 'e5', 'Nf3', 'Nc6', 'Bb5']);
        equal(с.пометки[2].статус, 'закреплено');
        equal(с.остановка, null);
    });

    it('закреплённый невозможный ход — остановка, а не молча другой', () => {
        const с = сверить(бланк('e4', 'e5', 'Sf3'), { 2: 'Sf6' });
        equal(с.ходы.length, 2);
        assert(/невозможен/.test(с.остановка.причина));
    });

    it('смешанная запись на одном бланке: немецкая, английская, длинная, рокировка нулями', () => {
        const с = сверить(бланк('e2-e4', 'e7-e5', 'Ng1-f3', 'Sb8c6', 'Lc4', 'Bc5', '0-0'));
        equal(с.ходы, ['e4', 'e5', 'Nf3', 'Nc6', 'Bc4', 'Bc5', 'O-O']);
    });

    it('партия на 60 полуходов сверяется быстро', () => {
        const ходы = ['Nf3', 'Nf6', 'Ng1', 'Ng8'];
        const клетки = [];
        for (let i = 0; i < 60; i++) клетки.push(['S' + ходы[i % 4].slice(1), 'T' + ходы[i % 4].slice(1)]);

        const начало = performance.now();
        const с = сверить(бланк(...клетки));
        const мс = performance.now() - начало;

        equal(с.ходы.length, 60);
        assert(мс < 3000, `сверка заняла ${Math.round(мс)} мс`);
    });
});

describe('Ответ Gemini', () => {
    it('JSON из ответа, в том числе в блоке кода', () => {
        const ответ = (текст) => ({ candidates: [{ content: { parts: [{ text: текст }] }, finishReason: 'STOP' }] });
        equal(ai.прочитатьJSON(ответ('{"moves": []}')), { moves: [] });
        equal(ai.прочитатьJSON(ответ('```json\n{"moves": [1]}\n```')), { moves: [1] });
    });

    it('мысли модели в ответ не попадают', () => {
        const данные = { candidates: [{ content: { parts: [{ text: 'думаю…', thought: true }, { text: '{"a":1}' }] }, finishReason: 'STOP' }] };
        equal(ai.прочитатьJSON(данные), { a: 1 });
    });

    it('оборванный и пустой ответ — понятные ошибки', () => {
        let текст = '';
        try { ai.прочитатьJSON({ candidates: [{ content: { parts: [{ text: '{"mo' }] }, finishReason: 'MAX_TOKENS' }] }); } catch (e) { текст = e.message; }
        assert(/оборвался/.test(текст), текст);

        try { ai.прочитатьJSON({ promptFeedback: { blockReason: 'SAFETY' } }); } catch (e) { текст = e.message; }
        assert(/фильтр/.test(текст), текст);
    });

    it('ключ, ограниченный адресом трекера, — подсказка, какой адрес добавить', () => {
        const т = причина(403, { error: { message: 'Requests from referer https://igor-bond.github.io/ChessAnalyzer/ are blocked.' } });
        assert(/ChessAnalyzer\/\*/.test(т), т);
        assert(/Google говорит так/.test(т), т);
    });

    it('выбор модели: новейшая flash, без черновых и лёгких', () => {
        equal(ai.выбрать(['gemini-2.5-pro', 'gemini-3.5-flash', 'gemini-3.5-flash-lite', 'gemini-4.0-flash-preview', 'gemini-2.5-flash']), 'gemini-3.5-flash');
        equal(ai.выбрать(['gemini-4.0-flash-preview']), 'gemini-4.0-flash-preview');
        equal(ai.выбрать([]), null);
    });
});

/**
 * Поддельный Google: отвечает по очереди из списка — кодом и телом.
 * Подменяет fetch только на время проверки.
 */
async function сПоддельнымGoogle(ответы, работа) {
    const настоящий = globalThis.fetch;
    const запросы = [];
    let i = 0;

    globalThis.fetch = async (url, параметры) => {
        запросы.push(String(url));
        const [код, тело] = ответы[Math.min(i++, ответы.length - 1)];
        return new Response(JSON.stringify(тело), { status: код, headers: { 'Content-Type': 'application/json' } });
    };

    try {
        return { итог: await работа(), запросы };
    } finally {
        globalThis.fetch = настоящий;
    }
}

const ПЕРЕГРУЖЕНА = [503, { error: { code: 503, message: 'The model is overloaded. Please try again later.', status: 'UNAVAILABLE' } }];
const ГОТОВО = [200, { candidates: [{ content: { parts: [{ text: '{"moves": []}' }] }, finishReason: 'STOP' }] }];

describe('Google перегружен', () => {
    it('перегрузка — повтор с паузой, а не ошибка человеку', async () => {
        const состояния = [];
        const { итог, запросы } = await сПоддельнымGoogle([ПЕРЕГРУЖЕНА, ПЕРЕГРУЖЕНА, ГОТОВО], () => ai.спроситьJSON({
            ключ: 'к', модели: ['gemini-3.5-flash'], текст: 'x', паузы: [0, 0, 0], наСостояние: (с) => состояния.push(с)
        }));

        equal(итог, { moves: [] });
        equal(запросы.length, 3);
        assert(состояния.some((с) => /перегружен/i.test(с)), `не сказано, что ждём: ${JSON.stringify(состояния)}`);
    });

    it('модель перегружена насовсем — переход на запасную', async () => {
        const { итог, запросы } = await сПоддельнымGoogle([ПЕРЕГРУЖЕНА, ПЕРЕГРУЖЕНА, ПЕРЕГРУЖЕНА, ГОТОВО], () => ai.спроситьJSON({
            ключ: 'к', модели: ['gemini-3.5-flash', 'gemini-2.5-flash'], текст: 'x', паузы: [0, 0, 0]
        }));

        equal(итог, { moves: [] });
        assert(запросы.at(-1).includes('gemini-2.5-flash'), 'запасная модель не спрошена');
    });

    it('все перегружены — понятный отказ со списком испробованного', async () => {
        let текст = '';
        await сПоддельнымGoogle([ПЕРЕГРУЖЕНА], async () => {
            try {
                await ai.спроситьJSON({ ключ: 'к', модели: ['a-flash', 'b-flash'], текст: 'x', паузы: [0, 0, 0] });
            } catch (e) { текст = e.message; }
        });
        assert(/перегружен/i.test(текст) && /a-flash/.test(текст) && /b-flash/.test(текст), текст);
    });

    it('неверный ключ не повторяется и запасные не перебираются', async () => {
        const { запросы } = await сПоддельнымGoogle([[400, { error: { message: 'API key not valid. Please pass a valid API key.' } }]], async () => {
            try { await ai.спроситьJSON({ ключ: 'к', модели: ['a-flash', 'b-flash'], текст: 'x', паузы: [0, 0, 0] }); } catch { /* ждём */ }
        });
        equal(запросы.length, 1);
    });

    it('запасные модели: сначала flash, потом pro, без лёгких и служебных', () => {
        equal(ai.запасные(['gemini-3.5-flash', 'gemini-2.5-flash', 'gemini-2.5-pro', 'gemini-2.5-flash-lite', 'gemini-2.5-flash-image', 'gemini-2.0-flash'], 'gemini-3.5-flash'),
            ['gemini-2.5-flash', 'gemini-2.0-flash', 'gemini-2.5-pro']);
    });
});
