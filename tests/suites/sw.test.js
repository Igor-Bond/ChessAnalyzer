/**
 * Офлайн-кэш и соседи по домену — в обе стороны.
 *
 * На igor-bond.github.io живут несколько приложений, а хранилище кэшей и
 * список сервис-воркеров браузер ведёт по источнику, не по каталогу: они
 * одни на всех.
 *
 * Сосед может стереть наш кэш. Трекер тренировок при каждом своём
 * обновлении удалял все кэши, кроме своего, — и шахматы после этого не
 * открылись бы без сети. Узнаётся такое в турнирном зале, где сети нет.
 * Первая проверка ставит настоящий сервис-воркер, стирает его кэш так же,
 * как это делал сосед, и ждёт, что следующий запуск приложения кэш
 * восстановит.
 *
 * И мы не должны стирать чужое. Страница проверок перед стартом снимает
 * воркер и кэш — вторая проверка следит, что только свои (Р-20).
 *
 * Набор идёт последним: воркер, поставленный здесь, начинает управлять
 * страницей проверок. Следующий прогон снимает его сам (см. index.html).
 */

import { describe, it, equal, assert } from '../runner.js';

const КОРЕНЬ = new URL('../', location.href);

async function списокФайлов() {
    const текст = await (await fetch(new URL('sw.js', КОРЕНЬ), { cache: 'no-store' })).text();
    const блок = /ФАЙЛЫ\s*=\s*\[(.*?)\]/s.exec(текст)?.[1] || '';
    return [...блок.matchAll(/'([^']+)'/g)].map((м) => м[1]).filter((ф) => ф !== './');
}

async function дождаться(условие, подпись, срок) {
    const край = Date.now() + срок;
    while (Date.now() < край) {
        if (await условие()) return;
        await new Promise((r) => setTimeout(r, 200));
    }
    throw new Error(`Не дождались: ${подпись}`);
}

async function недостаёт(имя, файлы) {
    const нет = [];
    for (const ф of файлы) {
        if (!(await caches.match(new URL(ф, КОРЕНЬ).href, { cacheName: имя }))) нет.push(ф);
    }
    return нет;
}

describe('Офлайн-кэш', () => {
    it('кэш, стёртый соседним приложением, восстанавливается при следующем запуске', async () => {
        if (!('serviceWorker' in navigator)) return;

        const файлы = await списокФайлов();
        assert(файлы.length > 20, `список файлов не прочитался: ${файлы.length}`);

        /*
         * Адрес скрипта — с уникальным хвостом. Страница проверок снимает
         * регистрацию при старте, но если приложение открыто в соседней
         * вкладке, та держит её живой, и регистрация того же адреса по
         * правилам браузера «воскрешает» прежний воркер без установки —
         * проверялась бы старая версия. Новый адрес ставит воркер заново.
         */
        const адрес = new URL(`sw.js?проверка=${Date.now()}`, КОРЕНЬ).href;
        const рег = await navigator.serviceWorker.register(адрес, { scope: КОРЕНЬ.href });

        try {
            // Ждём конца обновления, а не первого активного воркера: на живом
            // адресе прежнюю версию держит открытая вкладка приложения, и её
            // воркер активен ещё до того, как встанет новый
            await дождаться(() => рег.active?.state === 'activated' && !рег.installing && !рег.waiting,
                'воркер нынешней версии активирован', 30000);

            const версия = /APP_VERSION\s*=\s*'([^']+)'/.exec(
                await (await fetch(new URL('sw.js', КОРЕНЬ), { cache: 'no-store' })).text())?.[1];
            const имя = `chess-${версия}`;

            // Страница проверок при старте стирает кэши шахмат — так что это
            // уже первое восстановление, а не просто установка
            рег.active.postMessage('проверить-кэш');
            await дождаться(async () => !(await недостаёт(имя, файлы)).length, `кэш ${имя} собран`, 30000);

            // Так поступает трекер, обновляясь: удаляет все чужие кэши
            await caches.delete(имя);
            equal((await недостаёт(имя, ['index.html'])).length, 1, 'кэш не стёрся');

            // Следующий запуск приложения — оно просит воркер проверить кэш
            рег.active.postMessage('проверить-кэш');

            await дождаться(async () => !(await недостаёт(имя, файлы)).length, 'кэш восстановлен', 30000);
        } finally {
            await рег.unregister();
            for (const к of await caches.keys()) if (к.startsWith('chess-')) await caches.delete(к);
        }
    });

    it('приложение при запуске просит воркер проверить кэш', async () => {
        const main = await (await fetch(new URL('js/main.js', КОРЕНЬ), { cache: 'no-store' })).text();
        assert(/postMessage\('проверить-кэш'\)/.test(main), 'main.js не просит проверить кэш');
    });
});

/** Подделка CacheStorage: помнит имена и что из них удалили. */
function поддельныеКэши(имена) {
    const живые = new Set(имена);

    return {
        живые,
        async keys() { return [...живые]; },
        async delete(имя) { return живые.delete(имя); }
    };
}

// Кэши соседей на Pages: трекер, «Ноты», wortschatz — имена как в их sw.js
const ЧУЖИЕ_КЭШИ = ['workout-v292', 'notes-v12', 'wortschatz-v7'];

describe('Страница проверок и соседи по адресу', () => {
    /*
     * Страница проверок живёт и на Pages, и снимала с источника всё: и кэши,
     * и воркеры. Кто открыл проверки шахмат на живом адресе, оставлял
     * трекер, «Ноты» и wortschatz без офлайна: кэш стёрт, а снятому воркеру
     * его уже и не отдать. Свой кэш шахматы докачивают сами (Р-18), соседи
     * так не умеют.
     *
     * Исполняется настоящий скрипт страницы, как есть, на подделках: поиск
     * по тексту пропустил бы ту же ошибку, записанную иначе. Управляющий
     * воркер подделан «есть», поэтому скрипт заканчивается перезагрузкой, а
     * не импортом проверок, — перезагрузка и служит знаком, что он дошёл до
     * конца.
     */
    it('снимает только воркер и кэши шахмат', async () => {
        const скрипт = [...document.scripts].find((s) => s.textContent.includes('getRegistrations'));
        assert(скрипт, 'на странице не найден скрипт, снимающий воркер');

        const снятые = [];
        const регистрация = (scope) => ({ scope, unregister: async () => { снятые.push(scope); return true; } });

        const navigator = {
            serviceWorker: {
                controller: {},
                getRegistrations: async () => [
                    регистрация('https://igor-bond.github.io/ChessAnalyzer/'),
                    регистрация('https://igor-bond.github.io/workout/'),
                    регистрация('https://igor-bond.github.io/Notes/'),
                    регистрация('https://igor-bond.github.io/wordschatz/'),
                    // Начало то же, приложение другое: свой корень узнаётся
                    // только вместе с косой чертой на конце
                    регистрация('https://igor-bond.github.io/ChessAnalyzer-old/')
                ]
            }
        };

        // Свои — и нынешняя версия, и забытая прежняя
        const кэши = поддельныеКэши(['chess-v4', 'chess-v5', ...ЧУЖИЕ_КЭШИ]);

        await new Promise((готово, мимо) => {
            const location = {
                href: 'https://igor-bond.github.io/ChessAnalyzer/tests/index.html',
                reload: готово
            };

            // globalThis подменён пустым объектом: скрипт ставит ключ
            // хранения, и настоящий трогать незачем
            new Function('navigator', 'caches', 'location', 'globalThis', скрипт.textContent)(
                navigator, кэши, location, {});

            setTimeout(() => мимо(new Error('скрипт страницы не дошёл до перезагрузки')), 2000);
        });

        equal(снятые, ['https://igor-bond.github.io/ChessAnalyzer/'], 'воркеры соседей не трогаются');
        equal([...кэши.живые].sort(), [...ЧУЖИЕ_КЭШИ].sort(), 'кэши соседей не трогаются, свои стёрты');
    });
});
