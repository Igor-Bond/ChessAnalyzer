/**
 * Обмен между устройствами — на двух «устройствах» и поддельном сервере.
 *
 * Два хранилища с разными ключами — это телефон и компьютер; сервер — карта
 * в памяти со своими часами, как у Firestore: время записи ставит сервер, а
 * не устройство. Настоящий Firestore здесь не нужен и вреден: проверка
 * зависела бы от входа в Google и чужой сети.
 */

import { describe, it, equal, assert } from '../runner.js';
import { создатьХранилище } from '../../js/core/store.js';
import { создатьОбмен, вОблако, изОблака } from '../../js/core/sync.js';
import { новаяПартия } from '../../js/core/game.js';

/** Сервер: записи с серверным временем; отказ включается по желанию. */
function сервер() {
    const записи = new Map();
    let часы = 1000;

    const с = {
        отказывать: false,
        записи,
        адаптер: {
            async отправить(список) {
                if (с.отказывать) throw new Error('Нет связи');
                for (const з of список) записи.set(з.id, { ...з, syncedAt: ++часы });
            },
            async получить(курсор) {
                if (с.отказывать) throw new Error('Нет связи');
                const новые = [...записи.values()].filter((з) => з.syncedAt > курсор);
                return { записи: новые, курсор: Math.max(курсор, ...новые.map((з) => з.syncedAt)) };
            }
        }
    };

    return с;
}

function устройство(имя, с) {
    const х = создатьХранилище(`chess.test.${имя}`);
    х.стереть();
    х.настроитьОбмен({ включён: true });
    return { х, обмен: создатьОбмен({ хранилище: х, адаптер: с.адаптер }) };
}

const пауза = () => new Promise((r) => setTimeout(r, 3));

describe('Обмен между устройствами', () => {
    it('запись в облако и обратно сохраняет партию, а разбор не едет', () => {
        const п = { ...новаяПартия(), белые: 'Igor', ходы: ['e4', 'e5'], разбор: { оценки: [1, 2] } };
        const з = вОблако(п);
        equal(з.white, 'Igor');
        assert(!('разбор' in з) && !JSON.stringify(з).includes('оценки'), 'разбор уехал в облако');

        const обратно = изОблака(з);
        equal(обратно.ходы, ['e4', 'e5']);
        equal(обратно.белые, 'Igor');
        equal(изОблака({ id: 'x', moves: [1, 2] }), null);
    });

    it('партия с телефона появляется на компьютере', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        const п = телефон.х.сохранить({ ...новаяПартия(), белые: 'Igor', ходы: ['e4', 'e5', 'Nf3'] });
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        const там = комп.х.партия(п.id);
        assert(там, 'партия не доехала');
        equal(там.ходы, ['e4', 'e5', 'Nf3']);
        equal(там.белые, 'Igor');
        equal(там.изменена, п.изменена, 'отметка изменения не сохранилась');
        equal(телефон.х.обмен().грязные, [], 'после отправки отметка не снята');
        equal(комп.х.обмен().грязные, [], 'принятая партия отмечена к отправке');
    });

    it('правка и удаление доезжают обратно', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        const п = телефон.х.сохранить({ ...новаяПартия(), ходы: ['d4'] });
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        await пауза();
        комп.х.сохранить({ ...комп.х.партия(п.id), ходы: ['d4', 'd5'], результат: '1-0' });
        await комп.обмен.обменяться();
        await телефон.обмен.обменяться();
        equal(телефон.х.партия(п.id).ходы, ['d4', 'd5']);
        equal(телефон.х.партия(п.id).результат, '1-0');

        await пауза();
        телефон.х.удалить(п.id);
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();
        equal(комп.х.партия(п.id), null, 'удаление не доехало');
        equal(телефон.х.обмен().удалённые, {}, 'отметка удаления не убрана после отправки');
    });

    it('спор: побеждает последняя правка, на обоих устройствах одна и та же', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        const п = телефон.х.сохранить({ ...новаяПартия(), ходы: ['e4'] });
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        // Оба правят без связи: сначала телефон, позже компьютер
        await пауза();
        телефон.х.сохранить({ ...телефон.х.партия(п.id), белые: 'старая правка' });
        await пауза();
        комп.х.сохранить({ ...комп.х.партия(п.id), белые: 'новая правка' });

        // Связь вернулась: компьютер отправил первым, телефон — после
        await комп.обмен.обменяться();
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        equal(телефон.х.партия(п.id).белые, 'новая правка');
        equal(комп.х.партия(п.id).белые, 'новая правка');
        equal(с.записи.get(п.id).white, 'новая правка', 'на сервере осталась старая правка');
    });

    it('без связи правки ждут и уезжают при следующем обмене', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        с.отказывать = true;
        const п = телефон.х.сохранить({ ...новаяПартия(), ходы: ['c4'] });

        let ошибка = '';
        try { await телефон.обмен.обменяться(); } catch (e) { ошибка = e.message; }
        equal(ошибка, 'Нет связи');
        equal(телефон.х.обмен().грязные, [п.id], 'неотправленная правка потеряла отметку');

        с.отказывать = false;
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();
        assert(комп.х.партия(п.id), 'партия не доехала после восстановления связи');
    });

    it('пустая партия не едет, пока в ней нет ходов', async () => {
        const с = сервер();
        const телефон = устройство('а', с);

        const п = телефон.х.сохранить(новаяПартия());
        await телефон.обмен.обменяться();
        equal(с.записи.size, 0, 'пустая партия уехала');
        equal(телефон.х.обмен().грязные, [п.id], 'с пустой партии снята отметка');

        телефон.х.сохранить({ ...п, ходы: ['e4'] });
        await телефон.обмен.обменяться();
        equal(с.записи.size, 1);
    });

    it('свой разбор не стирается, когда приходит та же партия', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        const п = телефон.х.сохранить({ ...новаяПартия(), ходы: ['e4', 'c5'] });
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        комп.х.сохранитьРазбор(п.id, { версия: 1, глубина: 14, fens: [], оценки: [] });
        await пауза();
        телефон.х.сохранить({ ...телефон.х.партия(п.id), событие: 'Bezirksliga' });
        await телефон.обмен.обменяться();
        await комп.обмен.обменяться();

        equal(комп.х.партия(п.id).событие, 'Bezirksliga');
        assert(комп.х.партия(п.id).разбор, 'пришедшая правка стёрла разбор');
    });

    it('повторный обмен не тянет уже полученное: курсор по времени сервера', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const комп = устройство('б', с);

        телефон.х.сохранить({ ...новаяПартия(), ходы: ['e4'] });
        await телефон.обмен.обменяться();
        const первый = await комп.обмен.обменяться();
        const второй = await комп.обмен.обменяться();

        equal(первый.получено, 1);
        equal(второй.получено, 0);
        assert(комп.х.обмен().курсор > 0, 'курсор не сдвинулся');
    });

    it('правка, сделанная во время отправки, не теряет отметку', async () => {
        const с = сервер();
        const телефон = устройство('а', с);
        const п = телефон.х.сохранить({ ...новаяПартия(), ходы: ['e4'] });

        // Сервер отвечает не сразу — за это время человек делает ход
        const настоящий = с.адаптер.отправить;
        с.адаптер.отправить = async (список) => {
            await пауза();
            телефон.х.сохранить({ ...телефон.х.партия(п.id), ходы: ['e4', 'e5'] });
            return настоящий(список);
        };

        await телефон.обмен.отправить();
        equal(телефон.х.обмен().грязные, [п.id], 'новая правка будет потеряна');
        с.адаптер.отправить = настоящий;
    });
});

describe('Облако Firebase', () => {
    it('SDK грузится и поднимается без входа — ответ, а не зависание', async () => {
        const { облако } = await import('../../js/core/cloud.js');

        let часы;
        const кто = await Promise.race([
            облако.кто(),
            new Promise((_, отказ) => { часы = setTimeout(() => отказ(new Error('облако не ответило за 20 с')), 20000); })
        ]).finally(() => clearTimeout(часы));

        // Вошёл ли кто-то в этом браузере — не наше дело: важен ответ
        assert(кто === null || typeof кто.uid === 'string', `странный ответ: ${JSON.stringify(кто)}`);
    });
});
