/**
 * Партия: импорт текста, позиции, PGN.
 */

import { describe, it, equal, assert } from '../runner.js';
import { разобратьТекст, вPGN, позиции, новаяПартия, номерХода, результатПоПозиции, партияОкончена, доскаНа } from '../../js/core/game.js';

describe('Импорт текста партии', () => {
    it('бланк немецкой записью с номерами', () => {
        const р = разобратьТекст('1. e4 e5 2. Sf3 Sc6 3. Lb5 a6 4. La4 Sf6 5. 0-0 Le7');
        equal(р.ошибка, null);
        equal(р.ходы, ['e4', 'e5', 'Nf3', 'Nc6', 'Bb5', 'a6', 'Ba4', 'Nf6', 'O-O', 'Be7']);
    });

    it('номера слитно с ходом и многоточие чёрных: 1.e4 1...e5', () => {
        const р = разобратьТекст('1.e4 1...e5 2.Nf3 2… Nc6');
        equal(р.ходы, ['e4', 'e5', 'Nf3', 'Nc6']);
    });

    it('длинная запись с бланка', () => {
        const р = разобратьТекст('1. e2-e4 e7-e5 2. Sg1-f3 Sb8-c6');
        equal(р.ходы, ['e4', 'e5', 'Nf3', 'Nc6']);
    });

    it('PGN: заголовки, комментарии, варианты, NAG и результат', () => {
        const pgn = `[Event "Bezirksliga"]
[Date "2026.09.27"]
[White "Igor"]
[Black "Klaus"]
[Result "1-0"]

1. e4 {лучший по Фишеру} e5 (1... c5 2. Nf3 (2. c3) d6) 2. Nf3 $1 Nc6 ; комментарий до конца строки
3. Bc4 1-0`;
        const р = разобратьТекст(pgn);
        equal(р.ошибка, null);
        equal(р.ходы, ['e4', 'e5', 'Nf3', 'Nc6', 'Bc4']);
        equal(р.заголовки.белые, 'Igor');
        equal(р.заголовки.чёрные, 'Klaus');
        equal(р.заголовки.событие, 'Bezirksliga');
        equal(р.заголовки.дата, '2026-09-27');
        equal(р.заголовки.результат, '1-0');
    });

    it('ошибка в середине: номер хода, сторона и что взято до неё', () => {
        const р = разобратьТекст('1. e4 e5 2. Sf3 Sc6 3. Lb5 Lxe5');
        equal(р.ходы.length, 5);
        equal(р.ошибка.полуход, 6);
        equal(р.ошибка.текст, 'Lxe5');
        assert(р.ошибка.причина.length > 0);
    });

    it('пустой текст — пустая партия без ошибки', () => {
        const р = разобратьТекст('   ');
        equal(р.ходы, []);
        equal(р.ошибка, null);
    });
});

describe('Позиции и PGN', () => {
    it('позиций на одну больше, чем ходов', () => {
        const п = { ...новаяПартия(), ходы: ['e4', 'e5', 'Nf3'] };
        const поз = позиции(п);
        equal(поз.length, 4);
        equal(поз[0].ход, null);
        equal(поз[3].ход.san, 'Nf3');
    });

    it('PGN читается обратно тем же импортом', () => {
        const п = { ...новаяПартия(), белые: 'Игорь "И"', чёрные: 'Klaus', дата: '2026-09-27', результат: '0-1',
            ходы: ['f3', 'e5', 'g4', 'Qh4#'] };
        const pgn = вPGN(п);

        assert(pgn.includes('[Date "2026.09.27"]'), pgn);
        assert(pgn.includes('[White "Игорь \\"И\\""]'), pgn);
        assert(pgn.trim().endsWith('2. g4 Qh4# 0-1'), pgn);

        const обратно = разобратьТекст(pgn);
        equal(обратно.ходы, п.ходы);
        equal(обратно.заголовки.результат, '0-1');
    });

    it('номер хода для подписи', () => {
        equal(номерХода(1), '1.');
        equal(номерХода(2), '1…');
        equal(номерХода(23), '12.');
    });

    it('троекратное повторение — не конец партии: ничья только по заявлению', () => {
        const ходы = ['Nf3', 'Nf6', 'Ng1', 'Ng8', 'Nf3', 'Nf6', 'Ng1', 'Ng8'];
        const доска = доскаНа({ ходы }, ходы.length);
        assert(доска.isThreefoldRepetition(), 'позиция не повторилась трижды — проверка неверна');
        equal(результатПоПозиции(доска), null);
        equal(партияОкончена(доска), false);
    });

    it('мёртвая позиция — ничья сама, без заявления', () => {
        const п = { ходы: [] };
        const доска = доскаНа(п, 0);
        доска.load('8/8/4k3/8/8/4K3/8/8 w - - 0 60');
        equal(результатПоПозиции(доска), '1/2-1/2');
        equal(партияОкончена(доска), true);
    });

    it('результат по мату и пату', () => {
        equal(результатПоПозиции(доскаНа({ ходы: ['f3', 'e5', 'g4', 'Qh4#'] }, 4)), '0-1');
        equal(результатПоПозиции(доскаНа({ ходы: ['e4'] }, 1)), null);
    });
});

describe('Импорт: пометки из книг', () => {
    it('отдельные пометки не обрывают импорт: e.p., !?, +, ±, +-, =, ∞', () => {
        const р = разобратьТекст('1. e4 ± e6 2. d4 d5 3. e5 c5 4. c3 !? Nc6 5. Nf3 += Qb6 6. a3 ∞ c4 7. Nbd2 = Na5');
        equal(р.ошибка, null, JSON.stringify(р.ошибка));
        equal(р.ходы.length, 14);
    });

    it('взятие на проходе с «e.p.» через пробел', () => {
        const р = разобратьТекст('1. e4 a6 2. e5 d5 3. exd6 e.p.');
        equal(р.ошибка, null, JSON.stringify(р.ошибка));
        equal(р.ходы.at(-1), 'exd6');
    });

    it('многоточие чёрных отдельно: «12. ... Sf6»', () => {
        const р = разобратьТекст('1. e4 ... e5 2. Sf3 … Sc6');
        equal(р.ошибка, null, JSON.stringify(р.ошибка));
        equal(р.ходы, ['e4', 'e5', 'Nf3', 'Nc6']);
    });
});
