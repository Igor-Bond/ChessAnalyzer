/**
 * Доигрыш движком и расстановка позиции.
 */

import { describe, it, equal, assert } from '../runner.js';
import { доиграть, вFen, проверитьРасстановку, итогДоигрыша } from '../../js/core/playout.js';
import { Движок } from '../../js/core/engine.js';
import { Chess } from '../../js/core/chess.js';
import { расстановка as изFen } from '../../js/core/board.js';

let общий = null;
const движок = () => (общий ||= new Движок());

/** Поддельный движок: ходит по списку, по кругу. */
function поСписку(ходы) {
    let i = 0;
    return {
        новаяПартия: async () => {},
        оценить: async () => {
            const u = ходы[i++ % ходы.length];
            return { лучший: u, линии: [{ оценка: { cp: 0 }, линия: [u] }] };
        }
    };
}

describe('Доигрыш движком', () => {
    it('ферзь против голого короля — движок доводит до мата', async () => {
        const р = await доиграть('8/8/8/4k3/8/8/8/3QK3 w - - 0 1', движок(), { глубина: 10, предел: 80 });
        equal(р.итог.вид, 'мат', `итог: ${р.итог.текст}, ходов ${р.ходы.length}`);
        assert(р.итог.текст.includes('белые'));
        assert(р.ходы.every((х) => х.san && х.fen), 'ход без записи или позиции');
    });

    it('кони туда-обратно — ничья повторением, а не бесконечность', async () => {
        const р = await доиграть('1n2k3/8/8/8/8/8/8/1N2K3 w - - 0 1', поСписку(['b1c3', 'b8c6', 'c3b1', 'c6b8']), { предел: 50 });
        equal(р.итог.вид, 'повторение');
        assert(р.ходы.length <= 10, `ходов ${р.ходы.length}`);
    });

    it('продолжение с уже сделанных ходов учитывает их в повторениях', async () => {
        const р = await доиграть('1n2k3/8/8/8/8/8/8/1N2K3 w - - 0 1', поСписку(['b1c3', 'b8c6', 'c3b1', 'c6b8']),
            { предел: 50, предыдущие: ['Nc3', 'Nc6', 'Nb1', 'Nb8'] });
        equal(р.итог.вид, 'повторение');
        equal(р.ходы.length, 4, 'повторение не узнано по ходам до продолжения');
    });

    it('предел и остановка', async () => {
        const р = await доиграть('1n2k3/8/8/8/8/8/8/1N2K3 w - - 0 1', поСписку(['b1c3', 'b8c6', 'c3a4', 'c6a5', 'a4c3', 'a5c6']), { предел: 3 });
        equal(р.итог.вид, 'предел');
        equal(р.ходы.length, 3);

        let n = 0;
        const с = await доиграть('1n2k3/8/8/8/8/8/8/1N2K3 w - - 0 1', поСписку(['b1c3', 'b8c6']), { отменён: () => ++n > 2 });
        equal(с.итог.вид, 'стоп');
    });

    it('итог мата и пата', () => {
        equal(итогДоигрыша(new Chess('7k/6Q1/6K1/8/8/8/8/8 b - - 0 1')).вид, 'мат');
        equal(итогДоигрыша(new Chess('7k/5Q2/6K1/8/8/8/8/8 b - - 0 1')).вид, 'пат');
        equal(итогДоигрыша(new Chess()), null);
    });
});

