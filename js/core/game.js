// ================== ИМПОРТ ТЕКСТА ==================

const РЕЗУЛЬТАТЫ = ['1-0', '0-1', '1/2-1/2', '½-½', '*'];

/**
 * Пометки комментатора отдельным словом — не ходы: «±», «+-», «!?», «e.p.»,
 * многоточие. В книгах и базах они стоят после хода через пробел, и раньше
 * импорт на них останавливался, как на непонятом ходе.
 */
const ПОМЕТКА = /^(e\.?p\.?|i\.?V\.?|[!?]+|[+#=∞±∓⩲⩱]+|\+\/?[-=]|[-=]\/?\+|N|\.+)$/i;

/**
 * Заголовки PGN вида [White "Иванов"].
 *
 * Поддержаны те, что видны в приложении. Остальные не теряются бесследно —
 * их просто нет в модели: PGN-файлы с двадцатью тегами бывают, но смотреть
 * на ECO-код и часовой пояс в архиве своих партий незачем.
 */
function заголовки(текст) {
    const итог = {};
    const соответствие = { White: 'белые', Black: 'чёрные', Event: 'событие', Date: 'дата', Result: 'результат' };

    for (const м of текст.matchAll(/\[(\w+)\s+"([^"]*)"\]/g)) {
        const поле = соответствие[м[1]];
        if (поле) итог[поле] = м[2];
    }

    // В PGN дата пишется через точки и с вопросами: 2026.09.?? — приводим
    if (итог.дата) {
        const д = /^(\d{4})\.(\d{2}|\?\?)\.(\d{2}|\?\?)$/.exec(итог.дата);
        итог.дата = д && !итог.дата.includes('?') ? `${д[1]}-${д[2]}-${д[3]}` : '';
    }

    return итог;
}

/**
 * Разобрать текст партии: PGN, запись из книги, переписанный бланк.
 *
 * Отрезается всё, что ходом не является: заголовки, комментарии {…} и ;…,
 * варианты (…) любой вложенности, NAG вида $1, номера ходов (12. и 12…),
 * результат. Остаток — ходы через пробел, каждый ищется в своей позиции.
 *
 * На первом непонятом ходе разбор останавливается и говорит, на каком
 * именно: ошибка переписчика в середине бланка — обычное дело, и человеку
 * нужен номер хода, а не «неверный формат».
 *
 * @returns {{ ходы: string[], заголовки: object, ошибка: null | { полуход, текст, причина } }}
 */
export function разобратьТекст(текст) {
    const з = заголовки(текст);

    let тело = String(текст ?? '')
        .replace(/\[[^\]]*\]/g, ' ')
        .replace(/\{[^}]*\}/g, ' ')
        .replace(/;[^\n]*/g, ' ');

    // Варианты могут быть вложены: снимаем самые внутренние, пока есть
    let было;
    do {
        было = тело;
        тело = тело.replace(/\([^()]*\)/g, ' ');
    } while (тело !== было);

    // Номер хода — только отдельным словом: в «e4 ... e5» цифра хода с
    // многоточием за ним — не номер, и раньше от «e4» оставалась одна «e»
    тело = тело
        .replace(/\$\d+/g, ' ')
        .replace(/(^|\s)\d+\s*(\.\s*)+/g, '$1 ')
        .replace(/(^|\s)\d+\s*…/g, '$1 ')
        .replace(/…/g, ' ');

    const доска = new Chess();
    const ходы = [];

    for (const кусок of тело.split(/\s+/).filter(Boolean)) {
        if (ПОМЕТКА.test(кусок)) continue;

        if (РЕЗУЛЬТАТЫ.includes(кусок)) {
            з.результат = кусок === '½-½' ? '1/2-1/2' : кусок;
            continue;
        }

        const найдено = найтиХод(доска, кусок);

        if (!найдено.ход) {
            return {
                ходы,
                заголовки: з,
                ошибка: { полуход: ходы.length + 1, текст: кусок, причина: найдено.ошибка }
            };
        }

        доска.move(найдено.ход.san);
        ходы.push(найдено.ход.san);
    }

    return { ходы, заголовки: з, ошибка: null };
}

// ================== ВЫГРУЗКА ==================

function датаPGN(дата) {
    return /^\d{4}-\d{2}-\d{2}$/.test(дата || '') ? дата.replace(/-/g, '.') : '????.??.??';
}

function экранироватьPGN(значение) {
    return String(значение || '?').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** PGN по стандарту: семь обязательных тегов и ходы по восемь в строке. */
export function вPGN(партия) {
    const теги = [
        ['Event', партия.событие],
        ['Site', '?'],
        ['Date', датаPGN(партия.дата)],
        ['Round', '?'],
        ['White', партия.белые],
        ['Black', партия.чёрные],
        ['Result', партия.результат || '*']
    ];

    const шапка = теги.map(([к, з]) => `[${к} "${к === 'Date' ? з : экранироватьPGN(з)}"]`).join('\n');

    const слова = [];
    партия.ходы.forEach((san, i) => {
        if (i % 2 === 0) слова.push(`${i / 2 + 1}.`);
        слова.push(san);
    });
    слова.push(партия.результат || '*');

    const строки = [];
    for (let i = 0; i < слова.length; i += 16) строки.push(слова.slice(i, i + 16).join(' '));

    return `${шапка}\n\n${строки.join('\n')}\n`;
}

/**
 * Кончена ли партия сама, без заявления игрока.
 *
 * Только мат, пат и мёртвая позиция (материала на мат нет ни у кого).
 * Троекратное повторение и правило 50 ходов по правилам FIDE — ничья по
 * заявлению: в турнирной партии игроки часто повторяют ходы и играют
 * дальше. chess.js считает их концом партии (isGameOver), и ввод после
 * повторения закрывался надписью «Партия окончена», а результат сам
 * становился ничьей.
 */
export function партияОкончена(доска) {
    return доска.isCheckmate() || доска.isStalemate() || доска.isInsufficientMaterial();
}

/**
 * Результат партии, если он следует из позиции.
 *
 * Мат и пат результат определяют сами; всё остальное — сдача, время,
 * соглашение — видно только из бланка, и его вписывает человек.
 */
export function результатПоПозиции(доска) {
    if (доска.isCheckmate()) return доска.turn() === 'w' ? '0-1' : '1-0';
    // Повторение и 50 ходов — по заявлению, их результат вписывает человек
    if (доска.isStalemate() || доска.isInsufficientMaterial()) return '1/2-1/2';
    return null;
}
