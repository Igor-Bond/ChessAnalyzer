/**
 * Доска — SVG строкой.
 *
 * Строкой, а не узлами: экраны перерисовываются целиком (см. app.js), и
 * доска собирается вместе с остальной разметкой. Клетка в координатах —
 * сто единиц, доска — восемьсот; браузер сам растягивает её под ширину.
 *
 * Цветов здесь нет ни одного: всё — классами, а краски живут в CSS. Иначе
 * тема и доска разъехались бы при первой же смене палитры.
 *
 * Фигуры — набор cburnett (GPLv2+, как на lichess), по картинке на фигуру.
 * Символы шрифта (♞) не годятся: на части Android они рисуются цветными
 * эмодзи, и доска превращается в стикеры (Р-7).
 */

const ВЕРТИКАЛИ = 'abcdefgh';
const К = 100;

/** Расстановка из FEN: { e4: 'wP', … }. */
export function расстановка(fen) {
    const итог = {};
    const ряды = fen.split(' ')[0].split('/');

    ряды.forEach((ряд, i) => {
        const горизонталь = 8 - i;
        let в = 0;

        for (const с of ряд) {
            if (/\d/.test(с)) {
                в += Number(с);
            } else {
                const цвет = с === с.toUpperCase() ? 'w' : 'b';
                итог[`${ВЕРТИКАЛИ[в]}${горизонталь}`] = цвет + с.toUpperCase();
                в += 1;
            }
        }
    });

    return итог;
}

/** Левый верхний угол клетки с учётом того, чьей стороной доска к зрителю. */
export function угол(поле, сторона = 'w') {
    const в = ВЕРТИКАЛИ.indexOf(поле[0]);
    const г = Number(поле[1]) - 1;

    return сторона === 'w'
        ? { x: в * К, y: (7 - г) * К }
        : { x: (7 - в) * К, y: г * К };
}

function центр(поле, сторона) {
    const у = угол(поле, сторона);
    return { x: у.x + К / 2, y: у.y + К / 2 };
}

/**
 * Стрелка из центра в центр — многоугольником, а не линией с маркером.
 *
 * Маркер наконечника в SVG не наследует прозрачность линии и на
 * пересечении двух стрелок даёт тёмный узел. Многоугольник прозрачен
 * целиком и ровно.
 */
function стрелка(откуда, куда, сторона, вид) {
    const а = центр(откуда, сторона);
    const б = центр(куда, сторона);

    const dx = б.x - а.x;
    const dy = б.y - а.y;
    const длина = Math.hypot(dx, dy);
    if (!длина) return '';

    const ux = dx / длина;
    const uy = dy / длина;
    const nx = -uy;
    const ny = ux;

    const древко = 7;      // половина толщины
    const голова = 22;     // половина ширины наконечника
    const остриё = 32;     // длина наконечника
    const отступ = 18;     // наконечник не залезает в центр клетки

    const конец = длина - отступ;
    const шея = конец - остриё;

    const т = (вдоль, поперёк) => `${(а.x + ux * вдоль + nx * поперёк).toFixed(1)},${(а.y + uy * вдоль + ny * поперёк).toFixed(1)}`;

    const точки = [
        т(14, древко), т(шея, древко), т(шея, голова),
        т(конец, 0),
        т(шея, -голова), т(шея, -древко), т(14, -древко)
    ];

    return `<polygon class="arrow arrow-${вид}" points="${точки.join(' ')}"/>`;
}

/**
 * Знак класса хода в углу клетки: ★, ?!, ?? …
 *
 * Сдвинут к краю доски, если клетка крайняя справа сверху: иначе кружок
 * обрезается рамкой.
 */
function значок(поле, сторона, класс, знак) {
    const у = угол(поле, сторона);
    const x = Math.min(у.x + К - 8, 800 - 24);
    const y = Math.max(у.y + 8, 24);

    return `<g class="badge badge-${класс}" transform="translate(${x} ${y})">
        <circle r="22"/>
        <text text-anchor="middle" dominant-baseline="central" y="1">${знак}</text>
    </g>`;
}

/**
 * Нарисовать доску.
 *
 * @param {object} п
 * @param {string} п.fen
 * @param {'w'|'b'} [п.сторона] — чьей стороной к зрителю
 * @param {{from, to}} [п.последний] — подсветка последнего хода
 * @param {string} [п.выбрано] — поле выбранной фигуры
 * @param {string[]} [п.цели] — куда выбранная может пойти
 * @param {Array<{from, to, вид}>} [п.стрелки]
 * @param {{поле, класс, знак}} [п.значок]
 * @param {string} [п.шах] — поле короля под шахом
 * @param {boolean} [п.нажимаемая] — клетки отвечают на нажатия
 * @param {string} [п.путь] — где лежат картинки фигур
 */
export function нарисоватьДоску({
    fen, сторона = 'w', последний = null, выбрано = null, цели = [],
    стрелки = [], значок: знак = null, шах = null, нажимаемая = false,
    путь = 'assets/pieces/'
}) {
    const фигуры = расстановка(fen);
    const части = [];

    // Клетки
    for (let г = 1; г <= 8; г++) {
        for (let в = 0; в < 8; в++) {
            const поле = `${ВЕРТИКАЛИ[в]}${г}`;
            const у = угол(поле, сторона);
            const светлая = (в + г) % 2 === 0;  // a1 тёмная
            const действие = нажимаемая ? ` data-action="клетка" data-square="${поле}"` : '';

            части.push(`<rect class="sq ${светлая ? 'light' : 'dark'}" x="${у.x}" y="${у.y}" width="${К}" height="${К}" data-sq="${поле}"${действие}/>`);
        }
    }

    // Подсветка: последний ход, выбор, шах
    if (последний) {
        for (const поле of [последний.from, последний.to]) {
            const у = угол(поле, сторона);
            части.push(`<rect class="hl-last" x="${у.x}" y="${у.y}" width="${К}" height="${К}"/>`);
        }
    }

    if (выбрано) {
        const у = угол(выбрано, сторона);
        части.push(`<rect class="hl-sel" x="${у.x}" y="${у.y}" width="${К}" height="${К}"/>`);
    }

    if (шах) {
        const ц = центр(шах, сторона);
        части.push(`<circle class="hl-check" cx="${ц.x}" cy="${ц.y}" r="${К * 0.55}"/>`);
    }

    // Подписи полей — внутри крайних клеток, как на настоящей доске
    for (let i = 0; i < 8; i++) {
        const вертикаль = сторона === 'w' ? ВЕРТИКАЛИ[i] : ВЕРТИКАЛИ[7 - i];
        const горизонталь = сторона === 'w' ? 8 - i : i + 1;

        // Подпись берёт цвет противоположной клетки, чтобы читаться на любой
        const светлаяСнизу = i % 2 === 1;
        const светлаяСлева = (i % 2 === 0);

        части.push(`<text class="coord ${светлаяСнизу ? 'on-light' : 'on-dark'}" x="${i * К + К - 6}" y="${8 * К - 7}" text-anchor="end">${вертикаль}</text>`);
        части.push(`<text class="coord ${светлаяСлева ? 'on-light' : 'on-dark'}" x="6" y="${i * К + 22}">${горизонталь}</text>`);
    }

    // Фигуры
    for (const [поле, фигура] of Object.entries(фигуры)) {
        const у = угол(поле, сторона);
        части.push(`<image class="piece" href="${путь}${фигура}.svg" x="${у.x}" y="${у.y}" width="${К}" height="${К}" data-piece="${фигура}" data-at="${поле}"/>`);
    }

    // Куда можно пойти — поверх фигур: на занятой клетке это кольцо взятия
    for (const поле of цели) {
        const ц = центр(поле, сторона);
        части.push(фигуры[поле]
            ? `<circle class="target-capture" cx="${ц.x}" cy="${ц.y}" r="${К * 0.46}"/>`
            : `<circle class="target" cx="${ц.x}" cy="${ц.y}" r="${К * 0.16}"/>`);
    }

    for (const с of стрелки) части.push(стрелка(с.from, с.to, сторона, с.вид || 'best'));

    if (знак) части.push(значок(знак.поле, сторона, знак.класс, знак.знак));

    /*
     * Нажатия ловят клетки, а фигуры, стрелки и подсветка их пропускают
     * (pointer-events: none в CSS). Иначе нажатие на фигуру приходило бы от
     * картинки без data-action, и выбрать фигуру можно было бы, только
     * попав в свободный уголок клетки.
     */
    return `<svg class="board" viewBox="0 0 800 800" role="img" aria-label="Шахматная доска" xmlns="http://www.w3.org/2000/svg">${части.join('')}</svg>`;
}

/** Поле короля стороны, которая ходит, если ей шах. */
export function полеШаха(доска) {
    if (!доска.inCheck()) return null;
    const цвет = доска.turn();
    const фигуры = расстановка(доска.fen());
    return Object.keys(фигуры).find((поле) => фигуры[поле] === `${цвет}K`) || null;
}
