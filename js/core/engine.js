/**
 * Stockfish в браузере.
 *
 * Сборка — облегчённая однопоточная Stockfish 19 (vendor/stockfish, 1,8 МБ,
 * GPL-3). Полная весит сто мегабайт и на Pages не ложится, а многопоточной
 * нужен SharedArrayBuffer, то есть заголовки изоляции, которых GitHub Pages
 * не отдаёт (Р-5). Для разбора своей партии облегчённой хватает с запасом:
 * она играет сильнее любого человека, а различать «неточность» и «ошибку»
 * помогает не лишняя сотня пунктов движка, а честная глубина на каждом ходу.
 *
 * Движок живёт в отдельном потоке (Worker) и говорит текстом по протоколу
 * UCI. Здесь этот разговор превращается в обещания: дал позицию — получил
 * оценку. Запросы выстраиваются в очередь: движок один, и второй «go»
 * посреди первого сбил бы оба.
 */

const ПУТЬ = new URL('../../vendor/stockfish/stockfish-19-lite-single.js', import.meta.url).href;

/**
 * Разобрать строку «info … score cp 35 … multipv 1 … pv e2e4 e7e5».
 *
 * Строки с lowerbound/upperbound — промежуточные, движок в них ещё не
 * уверен; их пропускаем, иначе в разбор попадёт оценка недосчитанной
 * линии.
 */
export function разобратьInfo(строка) {
    if (!строка.startsWith('info ') || !строка.includes(' pv ')) return null;
    if (/ (lower|upper)bound /.test(строка)) return null;

    const слова = строка.split(' ');
    const итог = { multipv: 1, глубина: 0, оценка: null, линия: [] };

    for (let i = 1; i < слова.length; i++) {
        const с = слова[i];

        if (с === 'depth') итог.глубина = Number(слова[++i]);
        else if (с === 'multipv') итог.multipv = Number(слова[++i]);
        else if (с === 'score') {
            const вид = слова[++i];
            const число = Number(слова[++i]);
            итог.оценка = вид === 'mate' ? { мат: число } : { cp: число };
        } else if (с === 'pv') {
            итог.линия = слова.slice(i + 1);
            break;
        }
    }

    return итог.оценка ? итог : null;
}

/**
 * Сколько движок может молчать, прежде чем считаться сломанным.
 *
 * Мерится молчание, а не время расчёта (Р-22). Первая версия сторожа
 * считала полторы минуты от начала позиции по обычным часам — и путала
 * поломку с медленным счётом и с паузой: на глубине 18 на слабом телефоне
 * живой движок считал дольше, а убранное в фон приложение Android
 * замораживает вместе с таймером, и по возвращении таймер срабатывал сразу.
 * Человек видел «Движок не ответил за 90 с» посреди исправного разбора.
 *
 * Живой Stockfish подаёт голос строками info на каждой глубине, а на долгих
 * — ещё и каждую секунду (currmove). Минута тишины на экране — это уже не
 * расчёт.
 */
const СРОК_МОЛЧАНИЯ = 60000;

/**
 * Запуск ждём дольше: первый раз движок скачивает почти два мегабайта, и в
 * турнирном зале со слабой связью это может занять не одну минуту.
 */
const СРОК_ЗАПУСКА = 180000;

/** Видно ли приложение: молчание в фоне не считается — движок там заморожен. */
const наЭкране = () => typeof document === 'undefined' || document.visibilityState !== 'hidden';

export class Движок {

    constructor(путь = ПУТЬ, { срок = СРОК_МОЛЧАНИЯ, срокЗапуска = СРОК_ЗАПУСКА, видно = наЭкране } = {}) {
        this.путь = путь;
        this.срок = срок;
        this.срокЗапуска = срокЗапуска;
        this.видно = видно;
        this.поток = null;
        this.готов = null;
        this.очередь = Promise.resolve();
        this.слушатель = null;
        this.отказ = null;
        this.multipv = 1;
    }

    /** Поднять поток и дождаться «uciok» — один раз, пока поток жив. */
    запустить() {
        if (this.готов) return this.готов;

        this.готов = new Promise((готово, мимо) => {
            let поток;

            try {
                поток = this.поток = new Worker(this.путь);
            } catch (e) {
                this.готов = null;
                мимо(e);
                return;
            }

            // Сообщения и ошибки убранного потока не должны трогать нового
            поток.onmessage = (e) => {
                if (this.поток === поток) this.слушатель?.(String(e.data));
            };

            поток.onerror = (e) => {
                e.preventDefault?.();
                if (this.поток === поток) this.сломался(new Error(`Движок упал: ${e.message || 'ошибка потока'}`));
            };

            this.ждать('uciok', () => this.послать('uci'), null, this.срокЗапуска)
                .then(() => {
                    this.послать('setoption name Hash value 32');
                    return this.ждать('readyok', () => this.послать('isready'));
                })
                .then(готово, мимо);
        });

        return this.готов;
    }

    послать(команда) {
        this.поток.postMessage(команда);
    }

    /**
     * Дождаться строки, начинающейся с ожидаемого; по пути отдать прочие.
     *
     * Сторож считает молчание движка, и только пока приложение на экране
     * (Р-22): каждая строка движка — знак жизни, время в фоне не в счёт.
     * Промолчал на экране дольше срока — движок сломан, и ожидание
     * отказывает, а не висит. Тот же отказ приходит, если поток упал.
     *
     * Заморозку страницы сторож узнаёт сам: если между двумя его шагами
     * прошло намного больше шага, страница спала, и отсчёт начинается
     * заново — событие о возвращении на экран может прийти и позже шага.
     */
    ждать(начало, действие, наСтроку, срок = this.срок) {
        return new Promise((готово, отказ) => {
            const шаг = Math.min(1000, Math.max(50, срок / 6));
            let жив = Date.now();
            let прошлыйШаг = жив;

            const сторож = setInterval(() => {
                const сейчас = Date.now();

                // Сон — пауза больше пяти секунд, а не «больше трёх шагов»:
                // браузер притормаживает таймеры фоновых страниц до раза в
                // секунду, и каждую такую паузу сторож принимал бы за сон,
                // обнуляя отсчёт навсегда. Заморозка же длится минутами
                const спал = сейчас - прошлыйШаг > Math.max(шаг * 3, 5000);
                прошлыйШаг = сейчас;

                if (спал || !this.видно()) {
                    жив = сейчас;
                    return;
                }

                if (сейчас - жив > срок) {
                    this.сломался(new Error(`Движок не отвечает уже ${Math.round(срок / 1000)} с`));
                }
            }, шаг);

            const убрать = () => {
                clearInterval(сторож);
                this.слушатель = null;
                this.отказ = null;
            };

            this.отказ = (ошибка) => {
                убрать();
                отказ(ошибка);
            };

            this.слушатель = (строка) => {
                жив = Date.now();

                if (строка.startsWith(начало)) {
                    убрать();
                    готово(строка);
                } else {
                    наСтроку?.(строка);
                }
            };

            try {
                действие();
            } catch (e) {
                this.отказ?.(e);
            }
        });
    }

    /**
     * Движок сломан: убрать поток и отказать тому, кто ждёт ответа.
     *
     * Следующий запрос поднимет поток заново (запустить), поэтому разбор
     * после «Попробовать снова» продолжается, а не требует перезагрузки.
     */
    сломался(ошибка) {
        const отказ = this.отказ;

        this.поток?.terminate();
        this.поток = null;
        this.готов = null;
        this.слушатель = null;
        this.отказ = null;
        this.multipv = 1;

        отказ?.(ошибка);
    }

    /**
     * Оценить позицию.
     *
     * @param {string} fen
     * @param {{ глубина?: number, линий?: number, ходы?: string[] }} параметры
     * @returns {Promise<{ лучший: string, линии: Array<{оценка, линия, глубина}> }>}
     *   оценки — со стороны того, кто ходит, как их даёт движок
     */
    оценить(fen, { глубина = 14, линий = 1, ходы = null } = {}) {
        const работа = this.очередь.then(async () => {
            await this.запустить();

            if (this.multipv !== линий) {
                this.послать(`setoption name MultiPV value ${линий}`);
                this.multipv = линий;
            }

            const линии = [];

            // ходы — searchmoves: искать только среди них. Так считается
            // «второй по силе ход» — лучший без лучшего (см. analyze.js)
            const поиск = ходы?.length ? ` searchmoves ${ходы.join(' ')}` : '';

            this.послать(`position fen ${fen}`);
            const конец = await this.ждать('bestmove', () => this.послать(`go depth ${глубина}${поиск}`), (строка) => {
                const info = разобратьInfo(строка);
                if (info) линии[info.multipv - 1] = info;
            });

            return { лучший: конец.split(' ')[1], линии: линии.filter(Boolean) };
        });

        // Упавший запрос не должен останавливать очередь для следующих
        this.очередь = работа.catch(() => {});
        return работа;
    }

    /** Новая партия: движок забывает таблицу позиций прошлой. */
    новаяПартия() {
        this.очередь = this.очередь.then(async () => {
            await this.запустить();
            this.послать('ucinewgame');
            await this.ждать('readyok', () => this.послать('isready'));
        }).catch(() => {});
        return this.очередь;
    }

    остановить() {
        this.сломался(new Error('Движок остановлен'));
        this.очередь = Promise.resolve();
    }
}

/** Один движок на приложение: поток весит мегабайты памяти. */
let общий = null;

export function движок() {
    if (!общий) общий = new Движок();
    return общий;
}
