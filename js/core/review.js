/**
 * Разбор партии: из оценок движка — классы ходов, точность, стадии.
 *
 * Здесь только арифметика, без движка и без экрана. Движок даёт по каждой
 * позиции оценку лучшей игры; всё остальное — что ход был ошибкой, насколько
 * точно играли белые, где кончился дебют — выводится отсюда и проверяется
 * числами, без браузерного Stockfish.
 *
 * Мерило — не пешки, а шансы на победу (Р-4). Потеря двух пешек в позиции
 * +0.3 — катастрофа, а в позиции +9 — ничто: партия выиграна при любом
 * ходе. Сантипешки этого не видят, проценты видят. Так считают и lichess, и
 * chess.com; формулы ниже — lichess, они открыты и проверены на миллионах
 * партий.
 */

import { Chess } from './chess.js';

/** Классы ходов: порядок — от лучшего к худшему. */
export const КЛАССЫ = {
    единственный: { имя: 'Единственный ход', знак: '!', кратко: 'единственный' },
    лучший:       { имя: 'Лучший ход', знак: '★', кратко: 'лучший' },
    отличный:     { имя: 'Отличный ход', знак: '✓', кратко: 'отличный' },
    хороший:      { имя: 'Хороший ход', знак: '✓', кратко: 'хороший' },
    неточность:   { имя: 'Неточность', знак: '?!', кратко: 'неточность' },
    ошибка:       { имя: 'Ошибка', знак: '?', кратко: 'ошибка' },
    зевок:        { имя: 'Зевок', знак: '??', кратко: 'зевок' },
    вынужденный:  { имя: 'Вынужденный ход', знак: '□', кратко: 'вынужденный' }
};

/**
 * Пороги потери шансов, в процентах.
 *
 * Те же, что у chess.com (ожидаемые очки 0,02 / 0,05 / 0,10 / 0,20): они
 * привычны тем, кто разбирал там партии, и неточность здесь будет
 * неточностью и там.
 */
export const ПОРОГИ = { отличный: 2, хороший: 5, неточность: 10, ошибка: 20 };

/**
 * Единственный ход: лучший сыгран, а второй по силе хуже на столько.
 *
 * И при двух условиях. После хода у сыгравшего ещё есть за что бороться —
 * выбрать лучший из проигрывающих ходов не подвиг. А второй ход уже
 * упускает перевес: мат в один, когда и без него партия выиграна, — просто
 * лучший ход, а не единственный.
 */
const РАЗРЫВ_ЕДИНСТВЕННОГО = 20;
const ЕСТЬ_ЗА_ЧТО_БОРОТЬСЯ = 30;
const ВТОРОЙ_УПУСКАЕТ = 50;

/** Оценки дальше этой — уже не про пешки, а про то, что партия решена. */
const ПРЕДЕЛ_CP = 1000;

// ================== ОЦЕНКИ ==================

/**
 * Оценка движка всегда со стороны того, кто ходит. Здесь — со стороны
 * белых: так её показывают шкала и график, и так её проще складывать.
 *
 * @param {{cp?: number, мат?: number}} оценка — как прислал движок
 * @param {'w'|'b'} очередь — чей ход в оцененной позиции
 */
export function заБелых(оценка, очередь) {
    if (!оценка) return null;
    const знак = очередь === 'w' ? 1 : -1;

    if (оценка.мат !== undefined && оценка.мат !== null) return { мат: оценка.мат * знак };
    return { cp: (оценка.cp || 0) * знак };
}

/** Оценка в сантипешках с пределом: мат превращается в ±предел. */
export function вСантипешки(оценка) {
    if (!оценка) return 0;

    if (оценка.мат !== undefined && оценка.мат !== null) {
        // Мат на доске (0) — это проигрыш того, кто ходит; знак уже учтён снаружи
        if (оценка.мат === 0) return оценка.проигралБелые ? -ПРЕДЕЛ_CP : ПРЕДЕЛ_CP;
        return оценка.мат > 0 ? ПРЕДЕЛ_CP : -ПРЕДЕЛ_CP;
    }

    return Math.max(-ПРЕДЕЛ_CP, Math.min(ПРЕДЕЛ_CP, оценка.cp || 0));
}

/**
 * Шансы белых на победу, 0–100 (lichess).
 *
 * Коэффициент подобран lichess по реальным партиям: при +1.00 белые
 * выигрывают примерно в 59% случаев, при +3.00 — в 75%.
 */
export function шансыБелых(оценка) {
    const cp = вСантипешки(оценка);
    return 50 + 50 * (2 / (1 + Math.exp(-0.00368208 * cp)) - 1);
}

/** Шансы стороны: белых как есть, чёрных — дополнение до ста. */
export function шансыСтороны(оценка, сторона) {
    const б = шансыБелых(оценка);
    return сторона === 'w' ? б : 100 - б;
}

/**
 * Точность хода по потере шансов (lichess).
 *
 * Ноль потерь — сто процентов; потеря двадцати — около сорока. Плюс один в
 * конце — поправка lichess на неточность самого движка: оценка на малой
 * глубине шумит, и лучший ход, оцененный чуть хуже, не должен стоить очков.
 */
export function точностьХода(потеря) {
    const т = 103.1668 * Math.exp(-0.04354 * Math.max(0, потеря)) - 3.1669 + 1;
    return Math.max(0, Math.min(100, т));
}

/** Оценка для показа: +0.85, −1.20, #3, #−2 — со стороны белых. */
export function показатьОценку(оценка) {
    if (!оценка) return '';

    if (оценка.мат !== undefined && оценка.мат !== null) {
        if (оценка.мат === 0) return '#';
        return оценка.мат > 0 ? `#${оценка.мат}` : `#−${-оценка.мат}`;
    }

    const п = (оценка.cp || 0) / 100;
    if (Math.abs(п) < 0.005) return '0.00';
    return п > 0 ? `+${п.toFixed(2)}` : `−${(-п).toFixed(2)}`;
}

// ================== СТАДИИ ==================

/**
 * Стадия партии по позиции — упрощённый «делитель» lichess.
 *
 * Эндшпиль — когда тяжёлых и лёгких фигур на доске осталось шесть или
 * меньше. Миттельшпиль начинается, когда их десять или меньше, либо когда
 * фигуры развиты: на одной из крайних горизонталей осталось меньше четырёх
 * фигур, или на обеих вместе — не больше двух коней и слонов. Второе
 * правило — своё, у lichess его место занимает мудрёная «перемешанность»:
 * без него рокированная позиция с развитыми фигурами на восьмом ходу
 * числилась бы дебютом, потому что ладьи, ферзь и король стоят дома.
 *
 * Номер хода в правило не входит намеренно: размен ферзей на десятом ходу
 * делает партию эндшпилем, сколько бы ходов ни прошло.
 */
export function стадия(fen) {
    const расстановка = fen.split(' ')[0];
    const ряды = расстановка.split('/');

    const фигур = (расстановка.match(/[qrbnQRBN]/g) || []).length;
    if (фигур <= 6) return 'эндшпиль';
    if (фигур <= 10) return 'миттельшпиль';

    const наРяду = (ряд) => (ряд.match(/[a-zA-Z]/g) || []).length;
    if (наРяду(ряды[0]) < 4 || наРяду(ряды[7]) < 4) return 'миттельшпиль';

    const лёгкихДома = (ряды[0] + ряды[7]).match(/[nbNB]/g)?.length || 0;
    if (лёгкихДома <= 2) return 'миттельшпиль';

    return 'дебют';
}

export const СТАДИИ = ['дебют', 'миттельшпиль', 'эндшпиль'];

// ================== РАЗБОР ==================

/**
 * Позиции, где партия кончилась на доске, движку не отдаются: оценивать там
 * нечего, а Stockfish на мате отвечает «bestmove (none)». Оценку им ставит
 * сама позиция.
 */
export function оценкаКонца(fen) {
    const доска = new Chess(fen);

    if (доска.isCheckmate()) {
        // Ходит тот, кому поставлен мат
        return { мат: 0, проигралБелые: доска.turn() === 'w' };
    }

    // Не isDraw: в него входит правило 50 ходов, а после сотого полухода
    // партия может идти дальше, и оценивать её должен движок, а не ноль
    if (доска.isStalemate() || доска.isInsufficientMaterial()) return { cp: 0 };
    return null;
}

/**
 * Разбор ходов по оценкам позиций.
 *
 * @param {Array<{fen: string, ход: object|null}>} поз — из game.позиции()
 * @param {Array<object>} оценки — по одной на позицию:
 *   { оценка: {cp|мат} за белых, лучший: 'e2e4', линия: ['e2e4', …],
 *     второй: {cp|мат} за белых | null, ходов: число допустимых ходов }
 * @returns {Array<object>} по одному на ход (полуходы 1…n)
 */
export function разобратьХоды(поз, оценки) {
    const итог = [];

    for (let i = 1; i < поз.length; i++) {
        const ход = поз[i].ход;
        const до = оценки[i - 1];
        const после = оценки[i];
        if (!до || !после) break;

        const сторона = ход.color;
        const uci = ход.from + ход.to + (ход.promotion || '');

        const шансыДо = шансыСтороны(до.оценка, сторона);
        const шансыПосле = шансыСтороны(после.оценка, сторона);

        const лучшийСыгран = до.лучший === uci;

        // Сыгран лучший — потерь нет, даже если оценка на следующем ходу
        // чуть поплыла: это шум глубины, а не ошибка игрока
        const потеря = лучшийСыгран ? 0 : Math.max(0, шансыДо - шансыПосле);

        let класс;
        if (до.ходов === 1) {
            класс = 'вынужденный';
        } else if (лучшийСыгран) {
            const второй = до.второй ? шансыСтороны(до.второй, сторона) : null;
            const единственный = второй !== null
                && шансыДо - второй >= РАЗРЫВ_ЕДИНСТВЕННОГО
                && второй < ВТОРОЙ_УПУСКАЕТ
                && шансыПосле >= ЕСТЬ_ЗА_ЧТО_БОРОТЬСЯ;
            класс = единственный ? 'единственный' : 'лучший';
        } else if (потеря < ПОРОГИ.отличный) {
            класс = 'отличный';
        } else if (потеря < ПОРОГИ.хороший) {
            класс = 'хороший';
        } else if (потеря < ПОРОГИ.неточность) {
            класс = 'неточность';
        } else if (потеря < ПОРОГИ.ошибка) {
            класс = 'ошибка';
        } else {
            класс = 'зевок';
        }

        const cpДо = вСантипешки(до.оценка) * (сторона === 'w' ? 1 : -1);
        const cpПосле = вСантипешки(после.оценка) * (сторона === 'w' ? 1 : -1);

        итог.push({
            полуход: i,
            san: ход.san,
            uci,
            сторона,
            класс,
            потеря,
            точность: класс === 'вынужденный' ? null : точностьХода(потеря),
            потеряCp: лучшийСыгран ? 0 : Math.max(0, cpДо - cpПосле),
            шансыДо,
            шансыПосле,
            оценкаДо: до.оценка,
            оценкаПосле: после.оценка,
            лучший: до.лучший,
            линияЛучшего: до.линия || [],
            ответ: после.линия || [],
            стадия: стадия(поз[i - 1].fen)
        });
    }

    return итог;
}

// ================== ИТОГИ ==================

function среднее(xs) {
    return xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null;
}

function разброс(xs) {
    const с = среднее(xs);
    return Math.sqrt(среднее(xs.map((x) => (x - с) ** 2)));
}

function гармоническое(xs) {
    if (!xs.length) return null;
    return xs.length / xs.reduce((a, x) => a + 1 / Math.max(x, 1e-9), 0);
}

/**
 * Точность за партию по сторонам (lichess).
 *
 * Простое среднее точностей хода обманывает: двадцать ходов в мёртвой
 * ничьей по сто процентов прячут зевок, решивший партию. Поэтому lichess
 * смешивает два среднего. Взвешенное — где вес хода растёт с тем, насколько
 * в этот момент металась оценка: острые места весят больше спокойных. И
 * гармоническое — оно сильно тянется вниз от одного провала. Итог —
 * полусумма.
 */
export function точностьПартии(поз, оценки, ходы) {
    const шансы = оценки.slice(0, поз.length).map((о) => шансыБелых(о.оценка));
    const n = ходы.length;
    if (!n) return { w: null, b: null };

    const окно = Math.max(2, Math.min(8, Math.round(шансы.length / 10)));
    const окна = [];

    for (let i = 0; i < Math.min(окно - 2, шансы.length); i++) окна.push(шансы.slice(0, окно));
    for (let i = 0; i + окно <= шансы.length; i++) окна.push(шансы.slice(i, i + окно));

    const веса = окна.map((xs) => Math.max(0.5, Math.min(12, разброс(xs))));

    const итог = {};

    for (const сторона of ['w', 'b']) {
        const свои = ходы
            .map((х, i) => ({ х, вес: веса[i] ?? 1 }))
            .filter(({ х }) => х.сторона === сторона && х.точность !== null);

        if (!свои.length) {
            итог[сторона] = null;
            continue;
        }

        const сумма = свои.reduce((a, { вес }) => a + вес, 0);
        const взвешенное = свои.reduce((a, { х, вес }) => a + х.точность * вес, 0) / сумма;
        const гарм = гармоническое(свои.map(({ х }) => х.точность));

        итог[сторона] = (взвешенное + гарм) / 2;
    }

    return итог;
}

/**
 * Сводка по стороне: точность, средняя потеря, счёт классов, стадии.
 */
export function сводка(поз, оценки, ходы) {
    const точность = точностьПартии(поз, оценки, ходы);
    const итог = {};

    for (const сторона of ['w', 'b']) {
        const свои = ходы.filter((х) => х.сторона === сторона);

        const классы = Object.fromEntries(Object.keys(КЛАССЫ).map((к) => [к, 0]));
        for (const х of свои) классы[х.класс] += 1;

        const стадии = {};
        for (const с of СТАДИИ) {
            const вСтадии = свои.filter((х) => х.стадия === с && х.точность !== null);
            стадии[с] = вСтадии.length
                ? { точность: среднее(вСтадии.map((х) => х.точность)), ходов: вСтадии.length }
                : null;
        }

        const считаемые = свои.filter((х) => х.класс !== 'вынужденный');

        итог[сторона] = {
            точность: точность[сторона],
            средняяПотеря: считаемые.length ? Math.round(среднее(считаемые.map((х) => х.потеряCp))) : null,
            классы,
            стадии
        };
    }

    return итог;
}

/**
 * Переломные моменты: ходы, сильнее всего сдвинувшие шансы.
 *
 * Не больше трёх и только заметные: партия, сыгранная ровно, переломов не
 * имеет, и придумывать их незачем.
 */
export function переломы(ходы, сколько = 3) {
    return ходы
        .filter((х) => х.потеря >= ПОРОГИ.неточность)
        .sort((а, б) => б.потеря - а.потеря)
        .slice(0, сколько)
        .sort((а, б) => а.полуход - б.полуход);
}
