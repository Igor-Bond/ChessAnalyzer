/**
 * Запись ходов: понять написанное человеком и показать ход его буквами.
 *
 * Бланки здесь немецкие (K, D, T, L, S), но приходят партии и с английской
 * записью, и с русской — из книги, из чата, от тренера. Главное открытие:
 * буквы трёх нотаций почти не пересекаются, поэтому выбирать нотацию для
 * ВВОДА не нужно вовсе (Р-3). Латинские D, T, L, S — только немецкие;
 * Q, R, B, N — только английские; кириллица — только русская; K — король и
 * там и там. Единственная ловушка — русская «К», это конь, а не король, но
 * она кириллическая и с латинской K не совпадает.
 *
 * Поэтому разбор устроен не как грамматика нотации, а как сверка: из
 * написанного вытаскивается что можно — фигура, поле, откуда, превращение, —
 * и с этим сличается каждый допустимый в позиции ход. Подошёл ровно один —
 * это он. Так сами собой понимаются и короткая запись (Sf3), и длинная
 * (Sg1-f3), и бланковая со взятием через двоеточие (L:e5), и машинная
 * (g1f3), и рокировка, записанная ходом короля (Kg1).
 */

/** Буквы фигур по нотациям — для показа. */
export const НОТАЦИИ = {
    de: { имя: 'Немецкая', k: 'K', q: 'D', r: 'T', b: 'L', n: 'S' },
    en: { имя: 'Английская', k: 'K', q: 'Q', r: 'R', b: 'B', n: 'N' },
    ru: { имя: 'Русская', k: 'Кр', q: 'Ф', r: 'Л', b: 'С', n: 'К' }
};

/**
 * Все буквы фигур, которые понимает ввод, — сразу всех нотаций.
 *
 * Строчные латинские тоже: на телефоне клавиатура не ставит заглавную сама,
 * и «sf3» означает коня. Строчных b и d здесь нет — это вертикали, и
 * «bd2» должно оставаться пешечным взятием. Если же пешечное прочтение не
 * подошло, разбор ниже пробует их как фигуры.
 */
const БУКВЫ = {
    K: 'k', D: 'q', T: 'r', L: 'b', S: 'n',
    Q: 'q', R: 'r', B: 'b', N: 'n',
    k: 'k', t: 'r', l: 'b', s: 'n', q: 'q', r: 'r', n: 'n',
    'Ф': 'q', 'Л': 'r', 'С': 'b', 'К': 'n',
    'ф': 'q', 'л': 'r', 'с': 'b', 'к': 'n'
};

/** Запасное прочтение строчных b и d, если пешка не подошла. */
const ЗАПАСНЫЕ = { b: 'b', d: 'q' };

/** Буквы превращения — те же фигуры без короля. */
function фигураПревращения(буква) {
    const ф = БУКВЫ[буква] || ЗАПАСНЫЕ[буква];
    return ф && ф !== 'k' ? ф : null;
}

/**
 * Вычистить всё, что не влияет на выбор хода.
 *
 * Шах, мат, оценки (!?), знак взятия любого вида, «e.p.» — всё это
 * подтверждает ход, но не выбирает его, а на бланке пишется как попало.
 */
function вычистить(текст) {
    return String(текст ?? '')
        .trim()
        .replace(/e\.?\s?p\.?$/i, '')          // взятие на проходе: e.p., ep
        .replace(/i\.?\s?V\.?$/, '')           // немецкое «im Vorbeigehen»
        .replace(/[+#†‡!?]+/g, '')
        .replace(/\s+/g, '');
}

/** Рокировка в любом написании: O-O, 0-0, о-о (кириллицей), 000. */
function рокировка(текст) {
    const м = /^([0OoОо])-?([0OoОо])(-?([0OoОо]))?$/.exec(текст);
    if (!м) return null;
    return м[3] ? 'O-O-O' : 'O-O';
}

/**
 * Разложить написанное на части.
 *
 * Возвращает список прочтений: обычно одно, а для строчной b и d — два
 * (пешка и фигура). Каждое прочтение — { фигура, откуда, куда, превращение },
 * где «откуда» может быть вертикалью, горизонталью, полем или пустым.
 */
function прочтения(текст) {
    const итог = [];

    const попробовать = (фигура, остаток) => {
        let превращение = null;

        /*
         * Поля, набранные русской раскладкой: «Кс3» с кириллической «с».
         * Человек пишет русскую нотацию, не переключая клавиатуру, и
         * а, с, е выглядят ровно как латинские — разницы он не видит.
         */
        остаток = остаток.replace(/[асе]/g, (б) => ({ 'а': 'a', 'с': 'c', 'е': 'e' }[б]));

        // Превращение в конце: e8D, e8=D, e8(D), e8/D
        const п = /^(.*[a-h][18])[=/(]?([A-Za-zА-Яа-я])\)?$/.exec(остаток);
        if (п && фигураПревращения(п[2])) {
            остаток = п[1];
            превращение = фигураПревращения(п[2]);
        }

        // Разделители взятия и хода: x, :, -, —
        const поля = остаток.replace(/[x:×\-–—]/g, '');

        const м = /^([a-h])?([1-8])?([a-h][1-8])$/.exec(поля);
        if (!м) return;

        итог.push({
            фигура,
            откудаВертикаль: м[1] || null,
            откудаГоризонталь: м[2] || null,
            куда: м[3],
            превращение
        });
    };

    // «Кр» — русский король, две буквы; проверяется раньше коня «К»
    if (/^[Кк]р/.test(текст)) {
        попробовать('k', текст.slice(2));
        return итог;
    }

    const первая = текст[0];

    if (БУКВЫ[первая]) {
        попробовать(БУКВЫ[первая], текст.slice(1));

        // Строчная кириллическая «с» — и слон, и вертикаль c в русской раскладке
        if (первая === 'с') попробовать('p', текст);
    } else {
        попробовать('p', текст);
        if (ЗАПАСНЫЕ[первая]) попробовать(ЗАПАСНЫЕ[первая], текст.slice(1));
    }

    return итог;
}

function подходит(ход, п) {
    if (ход.piece !== п.фигура) return false;
    if (ход.to !== п.куда) return false;
    if (п.откудаВертикаль && ход.from[0] !== п.откудаВертикаль) return false;
    if (п.откудаГоризонталь && ход.from[1] !== п.откудаГоризонталь) return false;

    /*
     * Превращение без указанной фигуры — ферзь.
     *
     * На бланках его не пишут чаще, чем пишут: «e8» и всё. Требовать букву
     * значило бы спотыкаться на каждой такой партии, а выбор не ферзя
     * настолько редок, что его как раз записывают.
     */
    if (ход.promotion) return ход.promotion === (п.превращение || 'q');
    return !п.превращение;
}

/**
 * Найти ход по написанному.
 *
 * @param {import('../../vendor/chess.js/chess.js').Chess} позиция
 * @param {string} текст — как написал человек или прочитала модель
 * @returns {{ ход: object } | { ошибка: string, варианты?: object[] }}
 *   ход — объект хода chess.js (san, from, to, …), годный для позиция.move()
 */
export function найтиХод(позиция, текст) {
    const чистый = вычистить(текст);
    if (!чистый) return { ошибка: 'Пустой ход' };

    const допустимые = позиция.moves({ verbose: true });

    const р = рокировка(чистый);
    if (р) {
        const ход = допустимые.find((х) => х.san.replace(/[+#]/g, '') === р);
        return ход ? { ход } : { ошибка: 'Рокировка сейчас невозможна' };
    }

    const варианты = прочтения(чистый);
    if (!варианты.length) return { ошибка: `Не похоже на ход: «${текст}»` };

    // Прочтения идут по старшинству: пешечное раньше запасного фигурного
    for (const п of варианты) {
        const найдено = допустимые.filter((х) => подходит(х, п));

        if (найдено.length === 1) return { ход: найдено[0] };

        if (найдено.length > 1) {
            return {
                ошибка: `Неоднозначно: подходят ${найдено.map((х) => х.san).join(', ')}`,
                варианты: найдено
            };
        }
    }

    return { ошибка: `Ход «${текст}» в этой позиции невозможен` };
}

/**
 * Показать ход буквами нотации.
 *
 * SAN хранится всегда английским: это формат PGN, его понимают lichess,
 * chess.com и любая программа. Перевод — только при показе. Буквы фигур в
 * SAN стоят в двух местах — первой и после «=», — и больше нигде: строчные
 * a–h это вертикали, их не трогаем.
 */
export function показатьХод(san, нотация = 'de') {
    const н = НОТАЦИИ[нотация] || НОТАЦИИ.de;
    if (!san) return '';

    if (san.startsWith('O-O')) {
        // На немецких и русских бланках рокировку пишут нулями
        return нотация === 'en' ? san : san.replace(/O/g, '0');
    }

    const буква = (б) => ({ K: н.k, Q: н.q, R: н.r, B: н.b, N: н.n }[б] || б);

    return san
        .replace(/^[KQRBN]/, буква)
        .replace(/=([QRBN])/, (_, б) => `=${буква(б)}`);
}

/** Буква фигуры в нотации — для подписей вроде «ловите коня». */
export function букваФигуры(тип, нотация = 'de') {
    return (НОТАЦИИ[нотация] || НОТАЦИИ.de)[тип] || '';
}
