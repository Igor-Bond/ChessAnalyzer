/**
 * Архив партий и настройки — в localStorage.
 *
 * Партия с разбором — около десяти килобайт: ходы, заголовки и по оценке на
 * позицию. Сотня партий — мегабайт, при пределе хранилища в пять. Заводить
 * ради этого IndexedDB со схемой и миграциями рано (Р-6); понадобится, когда
 * в архив поедут фотографии бланков.
 *
 * Отказ хранилища не должен ронять приложение. В приватном окне
 * localStorage бросает исключение на любом обращении — тогда партии живут в
 * памяти до закрытия вкладки, и разбор работает как работал.
 */

/** Подменяется проверками, чтобы не стереть настоящий архив. */
const КЛЮЧ = globalThis.__CHESS_KEY__ || 'chess.v1';

export const НАСТРОЙКИ_ПО_УМОЛЧАНИЮ = {
    нотация: 'de',
    глубина: 14
};

/** Глубины на выбор: быстро, обычно, тщательно. */
export const ГЛУБИНЫ = [10, 14, 18];

let вПамяти = null;

function прочитатьСырое() {
    try {
        const текст = localStorage.getItem(КЛЮЧ);
        return текст ? JSON.parse(текст) : null;
    } catch {
        return null;
    }
}

/**
 * Чужое или испорченное содержимое не должно ломать запуск: ключ мог
 * пережить смену версии или оказаться чужим — домен у Pages один на все
 * проекты владельца.
 */
function привести(данные) {
    const партии = {};

    if (данные && typeof данные.партии === 'object') {
        for (const [id, п] of Object.entries(данные.партии)) {
            if (!п || typeof п !== 'object' || !Array.isArray(п.ходы)) continue;
            партии[id] = { ...п, id };
        }
    }

    const н = { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, ...(данные?.настройки || {}) };
    if (!['de', 'en', 'ru'].includes(н.нотация)) н.нотация = НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.нотация;
    if (!ГЛУБИНЫ.includes(Number(н.глубина))) н.глубина = НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.глубина;
    н.глубина = Number(н.глубина);

    return { партии, настройки: н };
}

function прочитать() {
    return вПамяти || привести(прочитатьСырое());
}

function записать(данные) {
    try {
        localStorage.setItem(КЛЮЧ, JSON.stringify(данные));
        вПамяти = null;
    } catch {
        // Переполнение или приватное окно: держим в памяти, чтобы не терять
        // сделанное хотя бы до закрытия вкладки
        вПамяти = данные;
    }
}

export const хранилище = {

    /** Партии от новых к старым. */
    партии() {
        return Object.values(прочитать().партии)
            .sort((а, б) => (б.изменена || 0) - (а.изменена || 0));
    },

    партия(id) {
        return прочитать().партии[id] || null;
    },

    сохранить(партия) {
        const данные = прочитать();
        данные.партии[партия.id] = { ...партия, изменена: Date.now() };
        записать(данные);
        return данные.партии[партия.id];
    },

    /**
     * Сохранить разбор, не трогая отметку изменения.
     *
     * Разбор — не правка партии: если бы он поднимал партию наверх
     * архива, порядок прыгал бы от каждого открытия.
     */
    сохранитьРазбор(id, разбор) {
        const данные = прочитать();
        if (!данные.партии[id]) return;
        данные.партии[id].разбор = разбор;
        записать(данные);
    },

    удалить(id) {
        const данные = прочитать();
        delete данные.партии[id];
        записать(данные);
    },

    настройки() {
        return прочитать().настройки;
    },

    настроить(изменения) {
        const данные = прочитать();
        данные.настройки = привести({ настройки: { ...данные.настройки, ...изменения } }).настройки;
        записать(данные);
        return данные.настройки;
    },

    /** Только для проверок. */
    стереть() {
        вПамяти = null;
        try { localStorage.removeItem(КЛЮЧ); } catch { /* приватное окно */ }
    }
};
