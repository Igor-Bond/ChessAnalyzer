/**
 * Архив партий и настройки — в localStorage.
 *
 * Партия с разбором — десятки килобайт: ходы, заголовки и по оценке на
 * позицию. Заводить ради этого IndexedDB со схемой и миграциями рано (Р-6);
 * понадобится, когда в архив поедут фотографии бланков.
 *
 * Отказ хранилища не должен ронять приложение. В приватном окне
 * localStorage бросает исключение на любом обращении — тогда партии живут в
 * памяти до закрытия вкладки, и разбор работает как работал.
 *
 * Здесь же учёт для обмена между устройствами (Р-19): какие партии менялись
 * с прошлой отправки и какие удалены. Учёт ведёт хранилище, а не модуль
 * обмена, потому что меняют партии все экраны, и забыть отметить правку в
 * одном из них значило бы потерять её на втором устройстве.
 */

export const НАСТРОЙКИ_ПО_УМОЛЧАНИЮ = {
    нотация: 'de',
    глубина: 14,

    // Gemini для чтения бланков: ключ личный и с устройства не уезжает,
    // модель пустая — значит, выбрать из списка Google при первом запросе
    ключ: '',
    модель: '',
    модели: []
};

/** Глубины на выбор: быстро, обычно, тщательно. */
export const ГЛУБИНЫ = [10, 14, 18];

/**
 * Состояние обмена на этом устройстве.
 *
 * грязные — партии, изменённые с прошлой удачной отправки; удалённые —
 * удалённые партии и когда (отправляются отметкой, чтобы удаление доехало
 * до другого устройства); курсор — время сервера, до которого всё чужое
 * уже получено.
 */
const ОБМЕН_ПО_УМОЛЧАНИЮ = { включён: false, грязные: [], удалённые: {}, курсор: 0, когда: 0 };

/**
 * Хранилище под своим ключом.
 *
 * Фабрикой, а не одним объектом, ради проверок обмена: им нужны два
 * «устройства» с разными архивами в одном браузере.
 */
export function создатьХранилище(КЛЮЧ) {
    let вПамяти = null;
    const слушатели = new Set();

    function прочитатьСырое() {
        try {
            const текст = localStorage.getItem(КЛЮЧ);
            return текст ? JSON.parse(текст) : null;
        } catch {
            return null;
        }
    }

    /**
     * Чужое или испорченное содержимое не должно ломать запуск: ключ мог
     * пережить смену версии или оказаться чужим — домен у Pages один на все
     * проекты владельца.
     */
    function привести(данные) {
        const партии = {};

        if (данные && typeof данные.партии === 'object') {
            for (const [id, п] of Object.entries(данные.партии)) {
                if (!п || typeof п !== 'object' || !Array.isArray(п.ходы)) continue;
                партии[id] = { ...п, id };
            }
        }

        const н = { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, ...(данные?.настройки || {}) };
        if (!['de', 'en', 'ru'].includes(н.нотация)) н.нотация = НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.нотация;
        if (!ГЛУБИНЫ.includes(Number(н.глубина))) н.глубина = НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.глубина;
        н.глубина = Number(н.глубина);
        н.ключ = typeof н.ключ === 'string' ? н.ключ.trim() : '';
        н.модель = typeof н.модель === 'string' ? н.модель.trim() : '';
        н.модели = Array.isArray(н.модели) ? н.модели.filter((м) => typeof м === 'string') : [];

        const о = { ...ОБМЕН_ПО_УМОЛЧАНИЮ, ...(данные?.обмен || {}) };
        о.включён = о.включён === true;
        о.грязные = Array.isArray(о.грязные) ? о.грязные.filter((id) => typeof id === 'string') : [];
        о.удалённые = о.удалённые && typeof о.удалённые === 'object' ? { ...о.удалённые } : {};
        о.курсор = Number(о.курсор) || 0;
        о.когда = Number(о.когда) || 0;

        return { партии, настройки: н, обмен: о };
    }

    function прочитать() {
        return вПамяти || привести(прочитатьСырое());
    }

    /**
     * Не удалось записать — признак для экрана (Р-28).
     *
     * Раньше переполнение хранилища молча переводило архив в память: всё
     * работало, а после закрытия приложения пропадало. Место на адресе
     * общее с трекером и «Нотами», и закончиться оно может не по вине шахмат.
     */
    let неСохраняется = false;

    function записать(данные) {
        try {
            localStorage.setItem(КЛЮЧ, JSON.stringify(данные));
            вПамяти = null;
            неСохраняется = false;
        } catch {
            // Переполнение или приватное окно: держим в памяти, чтобы не терять
            // сделанное хотя бы до закрытия вкладки, — и говорим об этом
            вПамяти = данные;
            неСохраняется = true;
        }
    }

    function отметить(данные, id) {
        if (!данные.обмен.грязные.includes(id)) данные.обмен.грязные.push(id);
    }

    function известить() {
        for (const ф of слушатели) {
            try { ф(); } catch (e) { console.error('[Хранилище] Ошибка слушателя:', e); }
        }
    }

    const хранилище = {

        /** Последняя запись не удалась: архив живёт только в памяти до закрытия. */
        get неСохраняется() {
            return неСохраняется;
        },

        /**
         * Отметить партию к отправке снова — обмен узнал, что на сервере
         * лежит более старая её версия, чем у нас (sync.js).
         */
        отметитьКОтправке(id) {
            const данные = прочитать();
            if (!данные.партии[id]) return;
            отметить(данные, id);
            записать(данные);
        },

        /** Партии от новых к старым. */
        партии() {
            return Object.values(прочитать().партии)
                .sort((а, б) => (б.изменена || 0) - (а.изменена || 0));
        },

        партия(id) {
            return прочитать().партии[id] || null;
        },

        /** Правка партии человеком: отметка времени и учёт для обмена. */
        сохранить(партия) {
            const данные = прочитать();
            // Отметка правки — не меньше прежней плюс миг: часы устройства могут
            // отставать от часов того, откуда партия пришла, и правка «в прошлом»
            // проиграла бы спор правок и не доехала (Р-19)
            const было = данные.партии[партия.id]?.изменена || 0;
            данные.партии[партия.id] = { ...партия, изменена: Math.max(Date.now(), было + 1) };
            delete данные.обмен.удалённые[партия.id];
            отметить(данные, партия.id);
            записать(данные);
            известить();
            return данные.партии[партия.id];
        },

        /**
         * Сохранить разбор, не трогая отметку изменения.
         *
         * Разбор — не правка партии: если бы он поднимал партию наверх
         * архива, порядок прыгал бы от каждого открытия. И на другое
         * устройство он не едет — там его пересчитают.
         */
        сохранитьРазбор(id, разбор) {
            const данные = прочитать();
            if (!данные.партии[id]) return;
            данные.партии[id].разбор = разбор;
            записать(данные);
        },

        удалить(id) {
            const данные = прочитать();
            // Удаление — тоже правка, и тоже не раньше последней правки партии
            данные.обмен.удалённые[id] = Math.max(Date.now(), (данные.партии[id]?.изменена || 0) + 1);
            delete данные.партии[id];
            отметить(данные, id);
            записать(данные);
            известить();
        },

        // ================== ОБМЕН ==================

        обмен() {
            return прочитать().обмен;
        },

        настроитьОбмен(изменения) {
            const данные = прочитать();
            данные.обмен = { ...данные.обмен, ...изменения };
            записать(данные);
            return данные.обмен;
        },

        /**
         * Партия с другого устройства — как есть, со своей отметкой времени.
         *
         * Не отмечается грязной: отправлять обратно то, что только что
         * пришло, незачем. Свой разбор остаётся, если ходы не поменялись, —
         * а если поменялись, разбор сам признает себя чужим (report.js).
         */
        принять(партия) {
            const данные = прочитать();
            const было = данные.партии[партия.id];
            данные.партии[партия.id] = { ...партия, разбор: было?.разбор ?? null };

            // Чужая правка новее нашей и заменила её: наша больше не ждёт отправки
            delete данные.обмен.удалённые[партия.id];
            данные.обмен.грязные = данные.обмен.грязные.filter((id) => id !== партия.id);
            записать(данные);
        },

        /** Удаление, пришедшее с другого устройства: без отметки, без учёта. */
        убрать(id) {
            const данные = прочитать();
            delete данные.партии[id];
            данные.обмен.грязные = данные.обмен.грязные.filter((г) => г !== id);
            записать(данные);
        },

        /**
         * Отправлено удачно — снять отметки.
         *
         * Только с того, что ушло в том же виде: метка — отметка изменения
         * партии (или время удаления) на момент отправки. Поправленная за
         * время отправки партия остаётся отмеченной.
         *
         * @param {Array<{id, метка}>} ушло
         */
        отправлено(ушло) {
            const данные = прочитать();
            const о = данные.обмен;

            for (const { id, метка } of ушло) {
                const партия = данные.партии[id];
                const та = партия ? партия.изменена === метка : (о.удалённые[id] ?? null) === метка;
                if (!та) continue;

                о.грязные = о.грязные.filter((г) => г !== id);
                if (!партия) delete о.удалённые[id];
            }

            записать(данные);
        },

        /** Подписка на правки человеком — по ней обмен решает, когда отправлять. */
        наИзменение(функция) {
            слушатели.add(функция);
            return () => слушатели.delete(функция);
        },

        // ================== НАСТРОЙКИ ==================

        настройки() {
            return прочитать().настройки;
        },

        настроить(изменения) {
            const данные = прочитать();
            данные.настройки = привести({ настройки: { ...данные.настройки, ...изменения } }).настройки;
            записать(данные);
            return данные.настройки;
        },

        /** Только для проверок. */
        стереть() {
            вПамяти = null;
            try { localStorage.removeItem(КЛЮЧ); } catch { /* приватное окно */ }
        }
    };

    return хранилище;
}

/** Подменяется проверками, чтобы не стереть настоящий архив. */
export const хранилище = создатьХранилище(globalThis.__CHESS_KEY__ || 'chess.v1');
