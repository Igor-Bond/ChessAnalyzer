/**
 * Подробности по игроку в одной партии — для экрана «Детально» (Р-30).
 *
 * Сводка разбора отвечает «насколько точно»; здесь — «где и чем»: какой
 * фигурой игрок ходил хуже, где ошибся и что было лучше, какие шансы
 * соперник ему дал и он их не взял, сколько ходов подряд держал точность.
 * Всё выводится из уже разобранных ходов (review.js) — движок не нужен.
 */

import { линияВSan } from './explain.js';

/** Фигуры в порядке показа. */
export const ФИГУРЫ = ['p', 'n', 'b', 'r', 'q', 'k'];

export const ИМЕНА_ФИГУР = { p: 'Пешка', n: 'Конь', b: 'Слон', r: 'Ладья', q: 'Ферзь', k: 'Король' };

const ОШИБКИ = ['неточность', 'ошибка', 'зевок'];
const ТОЧНЫЕ = ['единственный', 'лучший', 'отличный'];

/** Упущенный шанс: соперник потерял столько, а ответ не наказал. */
const ДАЛ_ШАНС = 10;
const НЕ_ВЗЯЛ = 10;

function среднее(xs) {
    return xs.length ? xs.reduce((а, б) => а + б, 0) / xs.length : null;
}

/**
 * @param {{ поз, ходы }} р — из report.собратьРазбор
 * @param {'w'|'b'} сторона
 */
export function подробно(р, сторона) {
    const свои = р.ходы.filter((х) => х.сторона === сторона);
    const считаемые = свои.filter((х) => х.точность !== null);

    // По фигурам: какой фигурой сделан ход — из подробного хода chess.js
    const поФигурам = {};
    for (const ф of ФИГУРЫ) {
        const ходы = считаемые.filter((х) => р.поз[х.полуход]?.ход?.piece === ф);
        поФигурам[ф] = ходы.length
            ? {
                ходов: ходы.length,
                точность: среднее(ходы.map((х) => х.точность)),
                ошибок: ходы.filter((х) => ОШИБКИ.includes(х.класс)).length
            }
            : null;
    }

    // Ошибки — с лучшим ходом в SAN, чтобы экран мог показать его буквами
    const ошибки = свои
        .filter((х) => ОШИБКИ.includes(х.класс))
        .map((х) => ({
            полуход: х.полуход,
            san: х.san,
            класс: х.класс,
            потеря: х.потеря,
            лучший: линияВSan(р.поз[х.полуход - 1].fen, [х.лучший], 1)[0]?.san || null
        }));

    // Упущенные шансы: предыдущий ход соперника был ошибкой, а наш ответ
    // сам стоил заметной доли шансов — подарок не взят
    const упущенные = [];
    for (const х of свои) {
        const прежний = р.ходы[х.полуход - 2];
        if (!прежний || прежний.сторона === сторона) continue;
        if (прежний.потеря >= ДАЛ_ШАНС && х.потеря >= НЕ_ВЗЯЛ) {
            упущенные.push({
                полуход: х.полуход,
                san: х.san,
                подарок: прежний.потеря,
                отдано: х.потеря,
                лучший: линияВSan(р.поз[х.полуход - 1].fen, [х.лучший], 1)[0]?.san || null
            });
        }
    }

    // Самая длинная серия точных ходов подряд
    let серия = 0;
    let лучшаяСерия = { длина: 0, с: null, по: null };
    let начало = null;
    for (const х of свои) {
        if (ТОЧНЫЕ.includes(х.класс) || х.класс === 'вынужденный') {
            if (!серия) начало = х.полуход;
            серия++;
            if (серия > лучшаяСерия.длина) лучшаяСерия = { длина: серия, с: начало, по: х.полуход };
        } else {
            серия = 0;
        }
    }

    // Пик перевеса — самый высокий шанс на победу, до которого доходил игрок
    let пик = null;
    for (const х of свои) {
        if (!пик || х.шансыПосле > пик.шансы) пик = { шансы: х.шансыПосле, полуход: х.полуход };
    }

    return {
        ходов: свои.length,
        точностьПоХодам: свои.map((х) => ({ полуход: х.полуход, точность: х.точность, класс: х.класс })),
        поФигурам,
        ошибки,
        упущенные,
        серия: лучшаяСерия,
        единственных: свои.filter((х) => х.класс === 'единственный').map((х) => ({ полуход: х.полуход, san: х.san })),
        взятий: свои.filter((х) => х.san.includes('x')).length,
        шахов: свои.filter((х) => /[+#]/.test(х.san)).length,
        пик
    };
}
