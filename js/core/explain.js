/**
 * Подсказка к ходу человеческим языком — из того, что посчитал движок.
 *
 * Текст строится по шаблонам, а не просится у языковой модели (Р-8): модель
 * в шахматах уверенно ошибается — видит несуществующие вилки и не видит
 * мата в два. Всё, что здесь сказано, — пересказ счёта движка: какой ход был
 * лучше, чем он лучше, чем наказывается сыгранный. Модели позже можно будет
 * поручить пересказ поживее, но опираться она будет на эти же факты.
 */

import { Chess } from './chess.js';
import { показатьХод } from './notation.js';
import { КЛАССЫ, показатьОценку } from './review.js';

/** Ход в машинной записи (e2e4, e7e8q) → объект хода в позиции или null. */
function ходИзUci(доска, uci) {
    if (!uci || uci.length < 4) return null;

    try {
        return доска.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });
    } catch {
        return null;
    }
}

/**
 * Линия движка в SAN.
 *
 * Обрывается на первом ходе, который в позиции невозможен: такое бывает,
 * если линия взята от другой глубины, и показывать её дальше значило бы
 * показывать неправду.
 */
export function линияВSan(fen, линия, сколько = 8) {
    const доска = new Chess(fen);
    const итог = [];

    for (const uci of (линия || []).slice(0, сколько)) {
        const ход = ходИзUci(доска, uci);
        if (!ход) break;
        итог.push({ san: ход.san, from: ход.from, to: ход.to, fen: доска.fen(), цвет: ход.color });
    }

    return итог;
}

/** Линия текстом с номерами: «14. Sf3 Lg4 15. h3». */
export function линияТекстом(fen, линия, нотация, сколько = 8) {
    const ходы = линияВSan(fen, линия, сколько);
    const номер = Number(fen.split(' ')[5]) || 1;
    const первыйЧёрных = fen.split(' ')[1] === 'b';

    return ходы.map((х, i) => {
        const полуход = i + (первыйЧёрных ? 1 : 0);
        const н = номер + Math.floor(полуход / 2);
        const ход = показатьХод(х.san, нотация);

        if (полуход % 2 === 0) return `${н}. ${ход}`;
        return i === 0 ? `${н}… ${ход}` : ход;
    }).join(' ');
}

function оценкаСловами(оценка, сторона) {
    if (!оценка) return '';

    if (оценка.мат !== undefined && оценка.мат !== null) {
        if (оценка.мат === 0) return 'мат';
        const свой = (оценка.мат > 0) === (сторона === 'w');
        return свой ? `мат в ${Math.abs(оценка.мат)}` : `мат вам в ${Math.abs(оценка.мат)}`;
    }

    return показатьОценку(оценка);
}

/**
 * Подсказка к ходу.
 *
 * @param {object} х — элемент из review.разобратьХоды
 * @param {string} fenДо — позиция до хода
 * @param {string} fenПосле — позиция после
 * @param {string} нотация
 * @returns {{ заголовок, текст, лучшийТекстом, ответТекстом }}
 */
export function подсказка(х, fenДо, fenПосле, нотация) {
    const класс = КЛАССЫ[х.класс];
    const сыгран = показатьХод(х.san, нотация);

    const лучшийSan = линияВSan(fenДо, [х.лучший], 1)[0]?.san;
    const лучший = лучшийSan ? показатьХод(лучшийSan, нотация) : null;

    const лучшийТекстом = линияТекстом(fenДо, х.линияЛучшего, нотация);
    const ответТекстом = линияТекстом(fenПосле, х.ответ, нотация);

    const после = оценкаСловами(х.оценкаПосле, х.сторона);
    const былоБы = оценкаСловами(х.оценкаДо, х.сторона);

    let текст;

    switch (х.класс) {
        case 'вынужденный':
            текст = 'Другого хода не было.';
            break;
        case 'единственный':
            текст = `${сыгран} — единственный ход, который держит позицию. Остальные заметно хуже.`;
            break;
        case 'лучший':
            текст = `${сыгран} — ход движка. Оценка ${после}.`;
            break;
        case 'отличный':
        case 'хороший':
            текст = `${сыгран} почти не уступает лучшему ${лучший}. Оценка ${после}.`;
            break;
        default: {
            const потеря = Math.round(х.потеря);
            текст = `Лучше было ${лучший} (${былоБы}). После ${сыгран} — ${после}, шансы упали на ${потеря}%.`;

            const наказание = линияВSan(fenПосле, х.ответ, 1)[0];
            if (наказание) {
                текст += ` Сильнейший ответ соперника — ${показатьХод(наказание.san, нотация)}.`;
            }
        }
    }

    return { заголовок: класс.имя, знак: класс.знак, текст, лучший, лучшийТекстом, ответТекстом };
}
