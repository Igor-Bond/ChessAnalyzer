/**
 * Прогон партии через движок.
 *
 * Каждая позиция оценивается один раз и запоминается в партии: разбор
 * восьмидесяти полуходов на телефоне — минута-другая, и повторять её при
 * каждом открытии незачем. Хранятся сырые оценки, а не классы ходов: пороги
 * классов могут поменяться, и тогда старые партии пересчитаются мгновенно,
 * без движка.
 */

import { Chess } from './chess.js';
import { позиции } from './game.js';
import { заБелых, оценкаКонца } from './review.js';

/** Сколько ходов лучшей линии хранить: дальше вариант уже не читают. */
const ДЛИНА_ЛИНИИ = 10;

/** Версия формата разбора: меняется — старые разборы пересчитываются. */
export const ВЕРСИЯ_РАЗБОРА = 1;

/**
 * Оценка одной позиции в том виде, в каком она хранится.
 *
 * Всё приведено к стороне белых: в хранилище не должно быть чисел, смысл
 * которых зависит от того, чей был ход, — на этом путаются при первой же
 * правке.
 */
export async function оценитьПозицию(движок, fen, глубина) {
    const доска = new Chess(fen);
    const ходов = доска.moves().length;

    const конец = оценкаКонца(fen);
    if (конец) return { оценка: конец, лучший: null, линия: [], второй: null, ходов };

    const очередь = доска.turn();
    const ответ = await движок.оценить(fen, { глубина, линий: 2 });
    const [первая, вторая] = ответ.линии;

    return {
        оценка: заБелых(первая?.оценка || { cp: 0 }, очередь),
        лучший: ответ.лучший,
        линия: (первая?.линия || [ответ.лучший]).slice(0, ДЛИНА_ЛИНИИ),
        второй: вторая ? заБелых(вторая.оценка, очередь) : null,
        ходов
    };
}

/**
 * Разобрать партию целиком.
 *
 * Уже оцененные позиции не пересчитываются, если глубина та же: так
 * прерванный разбор продолжается с того места, где его оставили, а правка
 * хода в конце партии не гонит движок по всему дебюту заново.
 *
 * @param {object} партия
 * @param {object} движок — экземпляр Движок
 * @param {{ глубина: number, наПрогресс?: Function, отменён?: () => boolean,
 *           наПозицию?: Function }} параметры
 * @returns {Promise<object>} разбор: { версия, глубина, fens, оценки }
 */
export async function разобратьПартию(партия, движок, { глубина, наПрогресс, отменён, наПозицию } = {}) {
    const поз = позиции(партия);
    const прежний = партия.разбор?.версия === ВЕРСИЯ_РАЗБОРА && партия.разбор.глубина === глубина
        ? партия.разбор
        : null;

    const оценки = [];

    await движок.новаяПартия();

    for (let i = 0; i < поз.length; i++) {
        if (отменён?.()) break;

        const fen = поз[i].fen;

        if (прежний && прежний.fens[i] === fen && прежний.оценки[i]) {
            оценки.push(прежний.оценки[i]);
        } else {
            оценки.push(await оценитьПозицию(движок, fen, глубина));
        }

        const разбор = { версия: ВЕРСИЯ_РАЗБОРА, глубина, fens: поз.slice(0, i + 1).map((п) => п.fen), оценки: [...оценки] };
        наПозицию?.(разбор);
        наПрогресс?.(i + 1, поз.length);
    }

    return { версия: ВЕРСИЯ_РАЗБОРА, глубина, fens: поз.slice(0, оценки.length).map((п) => п.fen), оценки };
}

/** Разбор полон: оценена каждая позиция партии в нынешнем виде. */
export function разборПолон(партия, глубина) {
    const р = партия.разбор;
    if (!р || р.версия !== ВЕРСИЯ_РАЗБОРА) return false;
    if (глубина !== undefined && р.глубина !== глубина) return false;

    const поз = позиции(партия);
    return р.оценки.length === поз.length && поз.every((п, i) => р.fens[i] === п.fen);
}
