/**
 * Прогон партии через движок.
 *
 * Каждая позиция оценивается один раз и запоминается в партии: разбор
 * восьмидесяти полуходов на телефоне — не мгновенный, и повторять его при
 * каждом открытии незачем. Хранятся сырые оценки, а не классы ходов: пороги
 * классов могут поменяться, и тогда старые партии пересчитаются мгновенно,
 * без движка.
 *
 * Как сделан быстрым (Р-23, замеры на партии в 80 полуходов):
 *
 * — Движок считает одну линию, а не две. Вторая нужна лишь для пометки
 *   «единственный ход», и только там, где сыгран лучший ход: её добирают
 *   отдельно, коротким поиском без лучшего хода. Это втрое быстрее, а
 *   против эталона на глубине 20 ошибок находится не меньше: 14 из 14
 *   против 13 у двух линий.
 *
 * — Сначала вся партия проходит быстро на малой глубине — это доли секунды,
 *   и график с примерными пометками появляется сразу. Потом каждая позиция
 *   уточняется на полной глубине и заменяет грубую оценку.
 */

import { Chess } from './chess.js';
import { позиции } from './game.js';
import { заБелых, оценкаКонца } from './review.js';

/** Сколько ходов лучшей линии хранить: дальше вариант уже не читают. */
const ДЛИНА_ЛИНИИ = 10;

/** Версия формата разбора: меняется — старые разборы пересчитываются. */
export const ВЕРСИЯ_РАЗБОРА = 1;

/** Глубина быстрого прохода: вся партия — за доли секунды. */
export const БЫСТРАЯ_ГЛУБИНА = 8;

/**
 * Глубина второй линии.
 *
 * Ей не нужна точность лучшей: она отвечает на один вопрос — намного ли
 * хуже остальные ходы, — а «намного» здесь двадцать процентов шансов.
 */
const ГЛУБИНА_ВТОРОЙ = 10;

const uci = (ход) => ход.from + ход.to + (ход.promotion || '');

/**
 * Оценка одной позиции в том виде, в каком она хранится.
 *
 * Всё приведено к стороне белых: в хранилище не должно быть чисел, смысл
 * которых зависит от того, чей был ход, — на этом путаются при первой же
 * правке.
 *
 * @param {object} движок
 * @param {string} fen
 * @param {number} глубина
 * @param {string|null} сыгран — ход, сделанный в партии из этой позиции
 *   (uci); по нему решается, нужна ли вторая линия
 * @param {{ безВторой?: boolean }} [п] — быстрый проход вторую не считает
 */
export async function оценитьПозицию(движок, fen, глубина, сыгран = null, { безВторой = false } = {}) {
    const доска = new Chess(fen);
    const допустимые = доска.moves({ verbose: true });
    const ходов = допустимые.length;

    const конец = оценкаКонца(fen);
    if (конец) return { оценка: конец, лучший: null, линия: [], второй: null, ходов };

    const очередь = доска.turn();
    const ответ = await движок.оценить(fen, { глубина, линий: 1 });
    const первая = ответ.линии[0];

    // Вторая линия — только если сыгран лучший ход и было из чего выбирать
    let второй = null;
    if (!безВторой && сыгран && сыгран === ответ.лучший && ходов > 1) {
        const прочие = допустимые.map(uci).filter((х) => х !== ответ.лучший);
        const ответ2 = await движок.оценить(fen, { глубина: Math.min(глубина, ГЛУБИНА_ВТОРОЙ), линий: 1, ходы: прочие });
        if (ответ2.линии[0]) второй = заБелых(ответ2.линии[0].оценка, очередь);
    }

    return {
        оценка: заБелых(первая?.оценка || { cp: 0 }, очередь),
        лучший: ответ.лучший,
        линия: (первая?.линия || [ответ.лучший]).slice(0, ДЛИНА_ЛИНИИ),
        второй,
        ходов
    };
}

/** Глубина, на которой оценена позиция i прежнего разбора. */
function глубинаПрежней(разбор, i) {
    return разбор.глубины?.[i] ?? разбор.глубина;
}

/**
 * Разобрать партию целиком.
 *
 * Уже оцененные позиции не пересчитываются, если оценены на той же глубине
 * или глубже: так прерванный разбор продолжается с того места, где его
 * оставили, а правка хода в конце партии не гонит движок по всему дебюту.
 *
 * @param {object} партия
 * @param {object} движок — экземпляр Движок
 * @param {{ глубина: number, быстро?: number, наПрогресс?: Function,
 *           отменён?: () => boolean, наПозицию?: Function }} параметры
 *   быстро — глубина предварительного прохода, 0 — без него;
 *   наПрогресс(готово, всего, этап) — этап 'быстро' или 'точно'
 * @returns {Promise<object>} разбор: { версия, глубина, fens, оценки, глубины }
 *   глубины[i] — на какой глубине оценена позиция i
 */
export async function разобратьПартию(партия, движок, { глубина, быстро = БЫСТРАЯ_ГЛУБИНА, наПрогресс, отменён, наПозицию } = {}) {
    const поз = позиции(партия);
    const n = поз.length;
    const fens = поз.map((п) => п.fen);
    const сыграно = поз.map((_, i) => (поз[i + 1]?.ход ? uci(поз[i + 1].ход) : null));

    const оценки = new Array(n).fill(null);
    const глубины = new Array(n).fill(0);

    const прежний = партия.разбор?.версия === ВЕРСИЯ_РАЗБОРА ? партия.разбор : null;
    if (прежний) {
        for (let i = 0; i < n; i++) {
            if (прежний.fens[i] === fens[i] && прежний.оценки[i]) {
                оценки[i] = прежний.оценки[i];
                глубины[i] = глубинаПрежней(прежний, i);
            }
        }
    }

    // Снимок для сохранения и показа: до первой дыры — так его понимает
    // report.js, который берёт оценки подряд с начала партии
    const снимок = () => {
        let k = 0;
        while (k < n && оценки[k]) k++;
        return { версия: ВЕРСИЯ_РАЗБОРА, глубина, fens: fens.slice(0, k), оценки: оценки.slice(0, k), глубины: глубины.slice(0, k) };
    };

    await движок.новаяПартия();

    // Быстрый проход — только по позициям, у которых нет никакой оценки
    const пустые = оценки.map((о, i) => (о ? -1 : i)).filter((i) => i >= 0);

    if (быстро && быстро < глубина && пустые.length) {
        let готово = 0;
        for (const i of пустые) {
            if (отменён?.()) return снимок();
            оценки[i] = await оценитьПозицию(движок, fens[i], быстро, сыграно[i], { безВторой: true });
            глубины[i] = быстро;
            наПрогресс?.(++готово, пустые.length, 'быстро');
        }
        // Один раз, а не на каждой позиции: быстрый проход — доли секунды,
        // и перерисовка экрана на каждую позицию стоила бы дороже его самого
        наПозицию?.(снимок());
    }

    // Точный проход: всё, что оценено мельче нужного
    const грубые = глубины.map((г, i) => (г < глубина ? i : -1)).filter((i) => i >= 0);

    let готово = 0;
    for (const i of грубые) {
        if (отменён?.()) break;
        оценки[i] = await оценитьПозицию(движок, fens[i], глубина, сыграно[i]);
        глубины[i] = глубина;
        наПозицию?.(снимок());
        наПрогресс?.(++готово, грубые.length, 'точно');
    }

    /*
     * Итог сохраняется всегда, даже если считать было нечего.
     *
     * Партию разобрали, потом отменили последний ход: все позиции есть, ни
     * одна не пересчитывается — и без этого сохранения в партии остался бы
     * прежний, более длинный разбор, навсегда «неполный» для укороченной
     * партии. Экран разбора запускал его заново на каждой отрисовке, без
     * конца, дёргая движок и съедая нажатия.
     */
    if (!отменён?.()) наПозицию?.(снимок());

    return снимок();
}

/**
 * Разбор полон: оценена каждая позиция партии в нынешнем виде, и каждая —
 * на глубине самого разбора. Предварительный (быстрый) проход полным не
 * считается: после него разбор продолжается сам.
 */
export function разборПолон(партия, глубина) {
    const р = партия.разбор;
    if (!р || р.версия !== ВЕРСИЯ_РАЗБОРА) return false;
    if (глубина !== undefined && р.глубина !== глубина) return false;

    const поз = позиции(партия);
    if (р.оценки.length !== поз.length || !поз.every((п, i) => р.fens[i] === п.fen)) return false;

    return поз.every((_, i) => глубинаПрежней(р, i) >= р.глубина);
}

/** Разбор пока предварительный: часть позиций оценена только быстрым проходом. */
export function разборПредварительный(разбор) {
    return !!разбор?.глубины?.some((г) => г < разбор.глубина);
}
