/**
 * Обмен партиями между устройствами — логика без Firebase.
 *
 * Сценарий, ради которого он есть: бланк снят телефоном в турнирном зале,
 * а разбирают партию дома за компьютером. И заодно архив перестаёт жить в
 * одном браузере: очистка данных на телефоне больше не стирает партии.
 *
 * Что едет: ходы и заголовки партии. Разбор не едет — он пересчитывается
 * на месте за минуту, а весит в сотню раз больше самой партии.
 *
 * Как решаются споры: побеждает последняя правка (по отметке изменения
 * партии). Одну партию на двух устройствах одновременно правят редко, а
 * при правке, разнесённой во времени, последняя и есть нужная. Удаление —
 * тоже правка: удалённая партия едет отметкой «удалена» и побеждает только
 * более раннюю правку.
 *
 * Сеть здесь — адаптер с двумя действиями, отправить и получить. Настоящий
 * — в cloud.js (Firestore), поддельный — в проверках: так логика обмена
 * проверяется на двух «устройствах» без сети и без входа в Google.
 */

/** Версия формата записи в облаке: поля латиницей и не зависят от экранов. */
const ВЕРСИЯ = 1;

/** Партия — в запись для облака. */
export function вОблако(партия) {
    return {
        v: ВЕРСИЯ,
        id: партия.id,
        white: партия.белые || '',
        black: партия.чёрные || '',
        event: партия.событие || '',
        date: партия.дата || '',
        result: партия.результат || '*',
        moves: [...партия.ходы],
        created: партия.создана || 0,
        modified: партия.изменена || 0,
        deleted: false
    };
}

/** Отметка об удалении — запись без партии. */
function отметкаУдаления(id, когда) {
    return { v: ВЕРСИЯ, id, deleted: true, modified: когда };
}

/**
 * Запись из облака — в партию, с недоверием ко всему: её могла записать
 * будущая версия приложения или испортить что угодно по дороге.
 *
 * @returns {object|null} партия или null, если запись не годится
 */
export function изОблака(запись) {
    if (!запись || typeof запись.id !== 'string' || !Array.isArray(запись.moves)) return null;
    if (!запись.moves.every((х) => typeof х === 'string')) return null;

    const строка = (з) => (typeof з === 'string' ? з : '');

    return {
        id: запись.id,
        белые: строка(запись.white),
        чёрные: строка(запись.black),
        событие: строка(запись.event),
        дата: строка(запись.date),
        результат: ['1-0', '0-1', '1/2-1/2', '*'].includes(запись.result) ? запись.result : '*',
        ходы: запись.moves,
        создана: Number(запись.created) || 0,
        изменена: Number(запись.modified) || 0,
        разбор: null
    };
}

/**
 * Обмен для одного хранилища и одного адаптера.
 *
 * @param {{ хранилище, адаптер: { отправить(записи), получить(курсор) } }} п
 *   адаптер.получить(курсор) → { записи, курсор } — всё, записанное на
 *   сервер позже курсора, и новый курсор (время сервера)
 */
export function создатьОбмен({ хранилище, адаптер }) {

    /**
     * Забрать чужое.
     *
     * Курсор — время сервера, а не своё: часы телефона и компьютера
     * расходятся, и по своим часам запись, сделанная «в прошлом» другого
     * устройства, не пришла бы никогда. Курсор двигается по всему
     * увиденному, а не только по принятому: иначе отклонённая как
     * устаревшая запись возвращалась бы на каждом обмене.
     */
    async function получить() {
        const о = хранилище.обмен();
        const { записи, курсор } = await адаптер.получить(о.курсор);
        let принято = 0;

        for (const запись of записи) {
            if (!запись || typeof запись.id !== 'string') continue;

            const местная = хранилище.партия(запись.id);
            const удаленаЗдесь = хранилище.обмен().удалённые[запись.id];
            const нашаМетка = местная ? (местная.изменена || 0) : (удаленаЗдесь || -1);

            const их = Number(запись.modified) || 0;

            /*
             * На сервере старее нашего, а наше уже не ждёт отправки — значит,
             * поверх нашей правки легла застрявшая чужая отправка (без сети
             * Firestore не отказывает, а досылает позже). Отмечаем своё к
             * отправке снова: иначе сервер и другие устройства так и жили бы
             * со старой версией.
             */
            if (местная && их < нашаМетка && !хранилище.обмен().грязные.includes(запись.id)) {
                хранилище.отметитьКОтправке(запись.id);
            }

            // Своё новее или то же самое (эхо своей же отправки) — не трогаем
            if (их <= нашаМетка) continue;

            if (запись.deleted) {
                if (местная) {
                    хранилище.убрать(запись.id);
                    принято++;
                }
                continue;
            }

            const партия = изОблака(запись);
            if (!партия) continue;

            хранилище.принять(партия);
            принято++;
        }

        хранилище.настроитьОбмен({ курсор: Math.max(о.курсор, Number(курсор) || 0) });
        return принято;
    }

    /**
     * Отправить своё.
     *
     * Пустые партии (ни одного хода) не едут: «Новая партия» заводит
     * запись сразу, и без этого правила каждый открытый и брошенный ввод
     * разносился бы по всем устройствам. Отметка с них не снимается — как
     * только появится первый ход, партия уедет.
     *
     * Отметка снимается только с того, что ушло в том же виде: если
     * человек поправил партию, пока шла отправка, правка останется
     * отмеченной и уедет следующим обменом.
     */
    async function отправить() {
        const о = хранилище.обмен();
        const записи = [];
        const ушло = [];

        for (const id of о.грязные) {
            const партия = хранилище.партия(id);

            if (партия) {
                if (!партия.ходы.length) continue;
                записи.push(вОблако(партия));
                ушло.push({ id, метка: партия.изменена });
            } else if (о.удалённые[id]) {
                записи.push(отметкаУдаления(id, о.удалённые[id]));
                ушло.push({ id, метка: о.удалённые[id] });
            } else {
                // Ни партии, ни отметки удаления — отправлять нечего
                ушло.push({ id, метка: null });
            }
        }

        if (записи.length) await адаптер.отправить(записи);
        хранилище.отправлено(ушло);
        return записи.length;
    }

    return {
        получить,
        отправить,

        /**
         * Полный обмен: сначала забрать, потом отправить.
         *
         * Не наоборот: устройство, долго бывшее без сети, отправив первым,
         * затёрло бы на сервере более позднюю правку с другого устройства —
         * сервер принимает запись вслепую. Забрав первым, оно увидит, что
         * чужая правка новее, примет её и своё старое не отправит.
         */
        async обменяться() {
            const получено = await получить();
            const отправлено = await отправить();
            хранилище.настроитьОбмен({ когда: Date.now() });
            return { получено, отправлено };
        }
    };
}
