/**
 * Разбор партии в готовом к показу виде: позиции, ходы с классами, сводка.
 *
 * Собирается из сохранённых оценок за миллисекунды, поэтому не хранится:
 * поменялись пороги классов — все партии архива тут же показывают новое.
 */

import { позиции } from './game.js';
import { разборПолон } from './analyze.js';
import { разобратьХоды, сводка, переломы } from './review.js';

/**
 * @returns {null | { поз, оценки, ходы, сводка, переломы, полный }}
 *   null — если не оценено ни одной позиции
 */
export function собратьРазбор(партия) {
    const р = партия.разбор;
    if (!р || !р.оценки?.length) return null;

    const поз = позиции(партия);

    // Оценки годны, пока позиции совпадают с нынешними ходами: после правки
    // партии хвост разбора относится уже к другой партии
    let годных = 0;
    while (годных < р.оценки.length && годных < поз.length && р.fens[годных] === поз[годных].fen) годных++;

    const оценки = р.оценки.slice(0, годных);
    const ходы = разобратьХоды(поз, оценки);

    return {
        поз,
        оценки,
        ходы,
        сводка: сводка(поз, оценки, ходы),
        переломы: переломы(ходы),
        полный: разборПолон(партия)
    };
}
