/**
 * Когда обмениваться: при запуске, после правки, при возврате в приложение.
 *
 * Так же, как в трекере, где это проверено жизнью. Постоянного соединения
 * (onSnapshot) нет намеренно: партию не смотрят на двух устройствах сразу, а
 * висящее соединение на телефоне — это батарея и ещё один повод для
 * зависаний. Вернулся в приложение — оно забрало свежее.
 *
 * Здесь же состояние для экранов: включён ли обмен, кто вошёл, когда был
 * последний обмен и чем кончился.
 */

import { хранилище } from './store.js';
import { создатьОбмен } from './sync.js';
import { облако } from './cloud.js';

/** Правку отправляем не сразу: ход за ходом — это не десять обменов, а один. */
const ПАУЗА = 2000;

const состояние = {
    идёт: false,
    кто: null,            // { uid, email, имя }
    ошибка: '',
    последний: null       // { получено, отправлено }
};

const слушатели = new Set();
let часы = null;
let ещё = false;
let подключено = false;

/** Облако подменяется проверками: входа в Google у них нет и быть не должно. */
let облакоСейчас = облако;

function известить() {
    for (const ф of слушатели) {
        try { ф(состояние); } catch (e) { console.error('[Обмен]', e); }
    }
}

async function обменяться() {
    if (!хранилище.обмен().включён) return;

    // Обмен уже идёт — правка, сделанная за это время, уедет следующим
    if (состояние.идёт) {
        ещё = true;
        return;
    }

    состояние.идёт = true;
    состояние.ошибка = '';
    известить();

    try {
        состояние.кто = await облакоСейчас.кто();
        if (!состояние.кто) throw new Error('Вход не выполнен');

        const обмен = создатьОбмен({ хранилище, адаптер: await облакоСейчас.адаптер() });
        состояние.последний = await обмен.обменяться();
    } catch (e) {
        console.warn('[Обмен]', e);
        состояние.ошибка = e.message || String(e);
    } finally {
        состояние.идёт = false;
        известить();
    }

    if (ещё) {
        ещё = false;
        запланировать();
    }
}

function запланировать(через = ПАУЗА) {
    clearTimeout(часы);
    часы = setTimeout(обменяться, через);
}

/** Слушать правки, возврат в приложение и появление сети — один раз. */
function подключить() {
    if (подключено) return;
    подключено = true;

    хранилище.наИзменение(() => {
        if (хранилище.обмен().включён) запланировать();
    });

    document.addEventListener('visibilitychange', () => {
        if (document.visibilityState === 'visible' && хранилище.обмен().включён) запланировать(300);
    });

    window.addEventListener('online', () => {
        if (хранилище.обмен().включён) запланировать(300);
    });
}

export const синхронизация = {

    состояние,

    get включена() {
        return хранилище.обмен().включён;
    },

    /** При запуске приложения: если обмен включён — обменяться. */
    запустить() {
        подключить();
        if (хранилище.обмен().включён) запланировать(500);
    },

    /**
     * Включить: войти, если ещё не вошли, и сделать первый обмен.
     *
     * Первый обмен забирает всё (курсор ноль) и отправляет всё здешнее —
     * все партии отмечаются: до включения обмена их никто не отмечал для
     * отправки, а терять архив, собранный до включения, нельзя.
     *
     * @returns {Promise<boolean>} включён ли обмен; false — человек закрыл
     *   окно входа, или вход ушёл переходом по адресу
     */
    async включить() {
        подключить();
        состояние.ошибка = '';

        /*
         * «Включён» записывается до входа, а не после.
         *
         * В установленном приложении на телефоне окно входа часто не
         * открывается, и вход идёт переходом по адресу: страница уходит к
         * Google и возвращается заново, а этот код до конца не доживает.
         * Записанный заранее признак доживает — и после возврата обмен
         * продолжается сам (запустить), без второго нажатия. Откатываем
         * его, только если человек закрыл окно входа сам.
         */
        const о = хранилище.обмен();
        const все = хранилище.партии().map((п) => п.id);
        хранилище.настроитьОбмен({
            включён: true,
            курсор: 0,
            грязные: [...new Set([...о.грязные, ...все])]
        });

        let кто = await облакоСейчас.кто();
        if (!кто) кто = await облакоСейчас.войти();

        if (!кто) {
            хранилище.настроитьОбмен({ включён: false });
            известить();
            return false;
        }

        состояние.кто = кто;
        await обменяться();
        return true;
    },

    /** Выключить на этом устройстве. Партии остаются, вход в Google — тоже. */
    выключить() {
        clearTimeout(часы);
        хранилище.настроитьОбмен({ включён: false });
        состояние.ошибка = '';
        известить();
    },

    /** Обменяться сейчас, не дожидаясь паузы. */
    сейчас() {
        clearTimeout(часы);
        return обменяться();
    },

    наИзменение(функция) {
        слушатели.add(функция);
        return () => слушатели.delete(функция);
    },

    /** Только для проверок: облако без Google. Без аргумента — настоящее. */
    задатьОблако(поддельное) {
        облакоСейчас = поддельное || облако;
    }
};
