/**
 * Задачи: с lichess и из своих ошибок (Р-32).
 *
 * Два источника, потому что у каждого своё. Задачи lichess — миллионы
 * проверенных позиций с рейтингом и темой: на них растёт уровень, и
 * сложность подбирается под него. Свои ошибки — позиции из собственных
 * партий, где был сыгран зевок: «найдите ход, который тогда не нашли».
 * Их немного, зато это ровно те дыры, что стоят очков в турнире; они
 * возвращаются по интервалам, пока не будут решены несколько раз подряд.
 *
 * Здесь — счёт и учёт, без экрана: проверка хода, рейтинг, запас задач
 * lichess на время без сети, выбор следующей своей задачи. Хранится на
 * устройстве отдельно от архива партий: обмен партиями сюда не ходит.
 */

