// ================== LICHESS ==================

const АДРЕС_LICHESS = 'https://lichess.org/api/puzzle/batch/';

/** Сколько задач брать за раз: одна просьба к lichess — на десяток задач вперёд. */
export const ПАЧКА = 12;

/** Предел запаса: дальше старые задачи вытесняются новыми. */
const ПРЕДЕЛ_ЗАПАСА = 48;

/**
 * Задача lichess в нашем виде.
 *
 * pgn у lichess — ходы партии до задачи; последний из них — ход соперника,
 * после него и начинается задача: ходит решающий, первый ход решения —
 * его. Проверено на живом ответе: в pgn ровно initialPly + 1 полуходов.
 *
 * @returns {object|null} null — если ходы не сходятся
 */
export function изLichess(запись, тема = 'mix', сложность = 'normal') {
    try {
        const { game, puzzle } = запись;
        const доска = new Chess();
        for (const san of String(game.pgn).trim().split(/\s+/)) доска.move(san);

        const последний = доска.history({ verbose: true }).at(-1) || null;
        if (!Array.isArray(puzzle.solution) || !puzzle.solution.length) return null;

        // Решение должно играться в этой позиции — иначе задача битая
        const проверка = new Chess(доска.fen());
        for (const uci of puzzle.solution) проверка.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });

        return {
            id: `li:${puzzle.id}`,
            источник: 'lichess',
            fen: доска.fen(),
            последний: последний ? { from: последний.from, to: последний.to } : null,
            решение: puzzle.solution,
            рейтинг: Number(puzzle.rating) || НАЧАЛЬНЫЙ_РЕЙТИНГ,
            темы: Array.isArray(puzzle.themes) ? puzzle.themes : [],
            ссылка: `https://lichess.org/training/${puzzle.id}`,
            тема,
            сложность
        };
    } catch {
        return null;
    }
}

/**
 * Пачка задач с lichess.
 *
 * Без входа: lichess отдаёт задачи анонимно и с заголовком CORS для
 * любого адреса. На «слишком часто» (429) отвечает просьбой подождать
 * минуту — это говорится словами, а не кодом.
 */
export async function загрузитьLichess({ тема = 'mix', сложность = 'normal', сколько = ПАЧКА, загрузка = globalThis.fetch } = {}) {
    let ответ;
    try {
        ответ = await загрузка(`${АДРЕС_LICHESS}${encodeURIComponent(тема)}?nb=${сколько}&difficulty=${сложность}`, {
            headers: { Accept: 'application/json' }
        });
    } catch {
        throw new Error('Нет связи с lichess');
    }

    if (ответ.status === 429) throw Object.assign(new Error('lichess просит подождать минуту'), { подождать: true });
    if (!ответ.ok) throw new Error(`lichess ответил ошибкой ${ответ.status}`);

    const данные = await ответ.json();
    return (данные.puzzles || []).map((з) => изLichess(з, тема, сложность)).filter(Boolean);
}

// ================== СВОИ ОШИБКИ ==================

/** Какие ходы становятся задачами: неточность — слишком мелко для задачи. */
const ВИДЫ_ОШИБОК = ['ошибка', 'зевок'];

/** Другой ход засчитывается, если он теряет меньше этого против лучшего. */
export const ПРИНЯТЬ_ПОТЕРЮ = ПОРОГИ.хороший;

const норм = (имя) => String(имя || '').trim().replace(/\s+/g, ' ').toLowerCase();

/** Имена игроков архива по частоте: [{ имя, партий }]. */
export function игроки(партии) {
    const счёт = new Map();

    for (const п of партии) {
        for (const имя of new Set([п.белые, п.чёрные].map((и) => String(и || '').trim()).filter(Boolean))) {
            const к = норм(имя);
            const было = счёт.get(к);
            счёт.set(к, { имя: было?.имя || имя, партий: (было?.партий || 0) + 1 });
        }
    }

    return [...счёт.values()].sort((а, б) => б.партий - а.партий);
}

/**
 * Кто владелец архива — имя, которое встречается в большинстве партий.
 *
 * Свои партии человек записывает со своим именем; соперники меняются.
 * Имя в двух партиях и больше чем в половине партий с именами — владелец:
 * соперник из своего клуба может попасться дважды, но не в каждой второй.
 * Нет такого — null: тогда задачи берутся из ошибок обеих сторон.
 */
export function ктоЯ(партии) {
    const сИменами = партии.filter((п) => норм(п.белые) || норм(п.чёрные)).length;
    const [первый, второй] = игроки(партии);

    // Двое поровну — две партии одних и тех же соперников: кто из них владелец, не понять
    if (!первый || (второй && второй.партий === первый.партий)) return null;
    return первый.партий >= 2 && первый.партий * 2 > сИменами ? первый.имя : null;
}

/**
 * Задачи из ошибок в разобранных партиях.
 *
 * Только из законченного разбора: на быстром проходе глубина мала, и
 * «зевок» там бывает шумом движка, а задача с неверным ответом хуже, чем
 * никакой.
 *
 * @param {string|null} чьи — имя игрока; null — ошибки обеих сторон
 */
export function задачиИзПартий(партии, чьи = null) {
    const итог = [];
    const я = чьи ? норм(чьи) : null;

    for (const п of партии) {
        const р = собратьРазбор(п);
        if (!р?.полный) continue;

        for (const х of р.ходы) {
            if (!ВИДЫ_ОШИБОК.includes(х.класс) || !х.лучший) continue;
            if (я && норм(х.сторона === 'w' ? п.белые : п.чёрные) !== я) continue;

            const до = р.поз[х.полуход - 1];
            const прежний = до.ход;

            итог.push({
                id: `${п.id}:${х.полуход}`,
                источник: 'партия',
                партия: п.id,
                полуход: х.полуход,
                fen: до.fen,
                последний: прежний ? { from: прежний.from, to: прежний.to } : null,
                решение: [х.лучший],
                сыгран: х.uci,
                san: х.san,
                класс: х.класс,
                потеря: х.потеря,
                оценкаЛучшего: х.оценкаДо,
                линия: х.линияЛучшего,
                белые: п.белые || 'Белые',
                чёрные: п.чёрные || 'Чёрные',
                дата: п.дата || '',
                изменена: п.изменена || 0
            });
        }
    }

    return итог;
}

/**
 * Интервалы повторения своих задач — по «ящикам» Лейтнера.
 *
 * Решена — в следующий ящик и вернётся позже: через день, три дня,
 * неделю; не решена — в первый, и вернётся через десять минут, в том же
 * подходе. Решённая четыре раза подряд — выучена и больше не показывается.
 */
const ЧАС = 3600 * 1000;
export const ИНТЕРВАЛЫ = [10 * 60 * 1000, 24 * ЧАС, 3 * 24 * ЧАС, 7 * 24 * ЧАС];

/**
 * Что из своих задач решать и когда следующие.
 *
 * Сначала — те, что пора повторить (по сроку); потом новые: зевки раньше
 * ошибок, свежие партии раньше старых.
 */
export function очередьСвоих(задачи, учёт, сейчас = Date.now()) {
    const живые = задачи.filter((з) => !учёт[з.id]?.выучена);

    const пора = живые
        .filter((з) => учёт[з.id] && учёт[з.id].когда <= сейчас)
        .sort((а, б) => учёт[а.id].когда - учёт[б.id].когда);

    const новые = живые
        .filter((з) => !учёт[з.id])
        .sort((а, б) => (б.класс === 'зевок') - (а.класс === 'зевок') || б.изменена - а.изменена || а.полуход - б.полуход);

    const ждут = живые
        .filter((з) => учёт[з.id] && учёт[з.id].когда > сейчас)
        .map((з) => учёт[з.id].когда);

    return {
        очередь: [...пора, ...новые],
        выучено: задачи.length - живые.length,
        следующая: ждут.length ? Math.min(...ждут) : null
    };
}

// ================== ПРОВЕРКА ХОДА ==================

export const uciХода = (ход) => ход.from + ход.to + (ход.promotion || '');

/**
 * Ход решающего против решения.
 *
 * @returns {'верно'|'мат'|'сыгран'|'проверить'|'неверно'}
 *   мат — не тот ход, но матует: у lichess любой мат засчитывается,
 *   в задачах на мат матующих ходов бывает несколько;
 *   сыгран — повторён ход из партии, тот самый, что был ошибкой;
 *   проверить — своя задача, ход другой: решает движок (оценитьОтвет)
 */
export function проверитьХод(задача, fen, uci, шаг = 0) {
    if (uci === задача.решение[шаг]) return 'верно';

    const доска = new Chess(fen);
    try {
        доска.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });
    } catch {
        return 'неверно';
    }
    if (доска.isCheckmate()) return 'мат';

    if (задача.источник === 'партия') return uci === задача.сыгран ? 'сыгран' : 'проверить';
    return 'неверно';
}

/**
 * Другой ход в своей задаче — не хуже ли он лучшего.
 *
 * Оба хода считаются одним поиском (searchmoves из двух ходов, две линии):
 * так они оценены на одной глубине, и разница — разница ходов, а не
 * глубин. Оценка лучшего из разбора не годится: она с другой глубины.
 *
 * @returns {Promise<{ потеря: number, принят: boolean }>}
 */
export async function оценитьОтвет(движок, задача, uci, глубина = 12) {
    const очередь = new Chess(задача.fen).turn();
    const лучший = задача.решение[0];

    const ответ = await движок.оценить(задача.fen, { глубина, линий: 2, ходы: [лучший, uci] });

    const линия = (ход) => ответ.линии.find((л) => л.линия[0] === ход);
    const шансы = (л) => (л ? шансыСтороны(заБелых(л.оценка, очередь), очередь) : null);

    const заЛучший = шансы(линия(лучший)) ?? шансыСтороны(задача.оценкаЛучшего, очередь);
    const заСвой = шансы(линия(uci));
    if (заСвой === null) return { потеря: 100, принят: false };

    const потеря = Math.max(0, заЛучший - заСвой);
    return { потеря, принят: потеря < ПРИНЯТЬ_ПОТЕРЮ };
}

