export const ЗВАНИЯ = [
    { от: 0, имя: 'Начинающий' },
    { от: 1000, имя: 'Любитель' },
    { от: 1400, имя: 'Разрядник' },
    { от: 1800, имя: 'Кандидат в мастера' },
    { от: 2200, имя: 'Мастер' }
];

export function звание(рейтинг) {
    let i = 0;
    while (i + 1 < ЗВАНИЯ.length && рейтинг >= ЗВАНИЯ[i + 1].от) i++;

    const следующее = ЗВАНИЯ[i + 1] || null;
    const доля = следующее ? (рейтинг - ЗВАНИЯ[i].от) / (следующее.от - ЗВАНИЯ[i].от) : 1;

    return { имя: ЗВАНИЯ[i].имя, следующее, доля: Math.max(0, Math.min(1, доля)) };
}

/** Сложность lichess под рейтинг: ступень, чьи задачи ближе всего к нему. */
export function сложностьДля(рейтинг) {
    let лучшая = СЛОЖНОСТИ[0];
    for (const с of СЛОЖНОСТИ) {
        if (Math.abs(с.около - рейтинг) < Math.abs(лучшая.около - рейтинг)) лучшая = с;
    }
    return лучшая.ключ;
}

/**
 * Рейтинг после задачи — по Эло, как у lichess.
 *
 * Шаг крупный на первых задачах и мельчает к двадцатой: начальные 1500 —
 * догадка, и подтянуть её к настоящему уровню надо за десяток задач, а не
 * за сотню. Решил задачу сильнее себя — плюс много, слабее — мало.
 */
export function новыйРейтинг(рейтинг, рейтингЗадачи, решена, сыграно = 0) {
    const К = Math.max(16, 48 - сыграно * 1.6);
    const ожидание = 1 / (1 + 10 ** ((рейтингЗадачи - рейтинг) / 400));
    const итог = рейтинг + К * ((решена ? 1 : 0) - ожидание);
    return Math.round(Math.max(400, Math.min(3000, итог)));
}

