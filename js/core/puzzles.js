/**
 * Учёт задач под своим ключом — фабрикой, как хранилище партий, чтобы
 * проверки не трогали настоящий.
 */
export function создатьЗадачник(КЛЮЧ, { загрузка = (...а) => globalThis.fetch(...а) } = {}) {
    let вПамяти = null;
    let грузится = null;
    let паузаДо = 0;

    function прочитать() {
        if (вПамяти) return вПамяти;

        let данные = null;
        try {
            данные = JSON.parse(localStorage.getItem(КЛЮЧ) || 'null');
        } catch {
            данные = null;
        }

        const у = { ...ПО_УМОЛЧАНИЮ, ...(данные && typeof данные === 'object' ? данные : {}) };
        у.рейтинг = Number(у.рейтинг) || НАЧАЛЬНЫЙ_РЕЙТИНГ;
        for (const к of ['запас', 'виденные', 'история']) if (!Array.isArray(у[к])) у[к] = [];
        if (!у.свои || typeof у.свои !== 'object') у.свои = {};
        if (у.уровень !== 'мой' && !СЛОЖНОСТИ.some((с) => с.ключ === у.уровень)) у.уровень = 'мой';
        if (!ТЕМЫ_ВЫБОРА.includes(у.тема)) у.тема = 'mix';
        return у;
    }

    function записать(у) {
        try {
            localStorage.setItem(КЛЮЧ, JSON.stringify(у));
            вПамяти = null;
        } catch {
            // Переполнение или приватное окно — учёт живёт до закрытия
            вПамяти = у;
        }
    }

    const з = {

        состояние: прочитать,

        настроить(изменения) {
            const у = { ...прочитать(), ...изменения };
            записать(у);
            return прочитать();
        },

        /** Сложность, с которой просить задачи у lichess сейчас. */
        сложность() {
            const у = прочитать();
            return у.уровень === 'мой' ? сложностьДля(у.рейтинг) : у.уровень;
        },

        /** Сколько задач лежит впрок под нынешние тему и сложность. */
        вЗапасе() {
            const у = прочитать();
            const сл = з.сложность();
            return у.запас.filter((к) => к.тема === у.тема && к.сложность === сл).length;
        },

        /**
         * Подгрузить пачку под нынешние тему и сложность — в запас.
         *
         * Одна загрузка за раз: два нажатия не просят у lichess дважды. Но
         * идущая загрузка годится, только если она за тем же: сменили тему,
         * пока грузилась прежняя, — дождаться её и спросить новую, иначе
         * вместо «мата в 1» пришла бы задача прежней темы (ревизия Р-32).
         */
        async пополнить() {
            const тема = прочитать().тема;
            const сложность = з.сложность();
            const за = `${тема}|${сложность}`;

            if (грузится?.за === за) return грузится.обещание;
            if (грузится) {
                await грузится.обещание.catch(() => {});
                if (грузится?.за === за) return грузится.обещание;
            }

            // После «подождите минуту» lichess не дёргаем, пока минута не пройдёт:
            // иначе каждая решённая задача просила бы снова и продлевала запрет
            if (Date.now() < паузаДо) throw new Error('lichess просит подождать минуту');

            const обещание = (async () => {
                try {
                    let пачка;
                    try {
                        пачка = await загрузитьLichess({ тема, сложность, загрузка });
                    } catch (e) {
                        if (e.подождать) паузаДо = Date.now() + 60 * 1000;
                        throw e;
                    }
                    const свежее = прочитать();
                    const было = new Set([...свежее.виденные, ...свежее.запас.map((к) => к.id)]);
                    const новые = пачка.filter((к) => !было.has(к.id));
                    свежее.запас = [...свежее.запас, ...новые].slice(-ПРЕДЕЛ_ЗАПАСА);
                    записать(свежее);
                    return новые.length;
                } finally {
                    if (грузится?.обещание === обещание) грузится = null;
                }
            })();

            грузится = { за, обещание };
            return обещание;
        },

        /**
         * Вернуть невиданную задачу в запас — её достали, но так и не
         * показали: тема сменилась или человек ушёл, пока она грузилась.
         */
        вернуть(задача) {
            const у = прочитать();
            if (у.запас.some((к) => к.id === задача.id)) return;
            у.запас = [задача, ...у.запас].slice(0, ПРЕДЕЛ_ЗАПАСА);
            у.виденные = у.виденные.filter((id) => id !== задача.id);
            записать(у);
        },

        /**
         * Следующая задача lichess.
         *
         * Из запаса под тему и сложность; нет — загрузить пачку. Сеть не
         * ответила — любая из запаса той же темы, потом любая вообще: в
         * турнирном зале без связи задачи всё равно есть. Запас доливается
         * заранее, когда в нём остаётся мало.
         *
         * @returns {Promise<{ задача: object|null, заметка: string }>}
         */
        async следующая() {
            const у = прочитать();
            const сл = з.сложность();
            const подходит = (к) => к.тема === у.тема && к.сложность === сл;

            let заметка = '';
            if (!у.запас.some(подходит)) {
                try {
                    await з.пополнить();
                } catch (e) {
                    заметка = e.message || String(e);
                }
            }

            const свежее = прочитать();
            const задача = свежее.запас.find(подходит)
                || свежее.запас.find((к) => к.тема === свежее.тема)
                || свежее.запас[0]
                || null;

            if (!задача) return { задача: null, заметка: заметка || 'lichess не прислал задач' };
            // Не своей темы или сложности — сказать об этом, была ошибка сети или нет
            заметка = подходит(задача) ? '' : `${заметка || 'Под эту тему и сложность задач пока нет'} — задача из запаса`;

            свежее.запас = свежее.запас.filter((к) => к.id !== задача.id);
            свежее.виденные = [...свежее.виденные, задача.id].slice(-500);
            записать(свежее);

            // Долить заранее, без ожидания: следующая задача уже будет здесь
            if (з.вЗапасе() < 3) з.пополнить().catch(() => {});

            return { задача, заметка };
        },

        /**
         * Итог задачи lichess — один раз на задачу.
         *
         * @param {{ решена: boolean, подсказка?: boolean }} итог
         *   решена с подсказкой — рейтинг не меняется: решал уже не сам
         * @returns {{ было: number, стало: number }}
         */
        засчитать(задача, { решена, подсказка = false }) {
            const у = прочитать();
            const было = у.рейтинг;

            if (!(решена && подсказка)) у.рейтинг = новыйРейтинг(было, задача.рейтинг, решена, у.сыграно);
            у.сыграно += 1;

            if (решена && !подсказка) {
                у.решено += 1;
                у.серия += 1;
                у.лучшаяСерия = Math.max(у.лучшаяСерия, у.серия);
            } else {
                у.серия = 0;
            }

            у.история = [...у.история, { когда: Date.now(), рейтинг: у.рейтинг }].slice(-100);
            записать(у);
            return { было, стало: у.рейтинг };
        },

        /** Итог своей задачи: ящик повторения. */
        отметитьСвою(задача, решена, сейчас = Date.now()) {
            const у = прочитать();
            const был = у.свои[задача.id] || { ящик: 0, попыток: 0, решено: 0 };
            const ящик = решена ? был.ящик + 1 : 0;

            у.свои[задача.id] = {
                ящик,
                попыток: был.попыток + 1,
                решено: был.решено + (решена ? 1 : 0),
                когда: сейчас + (ИНТЕРВАЛЫ[ящик] ?? 0),
                выучена: ящик >= ИНТЕРВАЛЫ.length
            };
            записать(у);
            return у.свои[задача.id];
        },

        /** Чьи ошибки брать: имя или null (обе стороны). */
        чьи(партии) {
            const у = прочитать();
            if (у.чьи === 'все') return null;
            if (у.чьи === 'авто') return ктоЯ(партии);
            return у.чьи;
        },

        /** Свои задачи и очередь их решения. */
        свои(партии, сейчас = Date.now()) {
            const задачи = задачиИзПартий(партии, з.чьи(партии));
            return { задачи, ...очередьСвоих(задачи, прочитать().свои, сейчас) };
        },

        /** Только для проверок. */
        задатьЗагрузку(функция) {
            загрузка = функция;
        },

        стереть() {
            вПамяти = null;
            грузится = null;
            паузаДо = 0;
            try { localStorage.removeItem(КЛЮЧ); } catch { /* приватное окно */ }
        }
    };

    return з;
}

export const задачник = создатьЗадачник(`${globalThis.__CHESS_KEY__ || 'chess.v1'}.задачи`);
