/**
 * Доигрыш движком и расстановка позиции — для свободной доски (Р-31).
 *
 * «Доиграть партию»: движок играет за обе стороны с заданной позиции до
 * конца — видно, как при этом раскладе сил партию довели бы лучшие ходы.
 * Позиция берётся из разбора, из конца записанной партии или
 * выставляется вручную.
 */

import { Chess } from './chess.js';
import { заБелых } from './review.js';

export const НАЧАЛО = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';

/** Предел доигрыша: дальше — уже не «довести партию», а бесконечность. */
export const ПРЕДЕЛ_ПОЛУХОДОВ = 200;

/**
 * Чем кончилась партия на доске — или null, если продолжается.
 *
 * Здесь, в отличие от записи партии (Р-17), повторение и 50 ходов — конец:
 * движок за обе стороны будет повторять ходы вечно, и ничью по заявлению
 * за него «заявляем» сами.
 */
export function итогДоигрыша(доска) {
    if (доска.isCheckmate()) {
        const победили = доска.turn() === 'w' ? 'чёрные' : 'белые';
        return { вид: 'мат', текст: `Мат — победили ${победили}`, результат: доска.turn() === 'w' ? '0-1' : '1-0' };
    }
    if (доска.isStalemate()) return { вид: 'пат', текст: 'Пат — ничья', результат: '1/2-1/2' };
    if (доска.isInsufficientMaterial()) return { вид: 'материал', текст: 'Ничья — материала на мат не осталось', результат: '1/2-1/2' };
    if (доска.isThreefoldRepetition()) return { вид: 'повторение', текст: 'Ничья — позиция повторилась трижды', результат: '1/2-1/2' };
    if (доска.isDrawByFiftyMoves()) return { вид: '50 ходов', текст: 'Ничья — 50 ходов без взятий и ходов пешками', результат: '1/2-1/2' };
    return null;
}

/**
 * Доиграть движком за обе стороны.
 *
 * Ход за ходом, с отчётом о каждом (наХод) — экран показывает доигрыш по
 * мере счёта, а не после минуты молчания.
 *
 * @param {string} fen — с чего начать
 * @param {object} движок — экземпляр Движок
 * @param {{ глубина?: number, предел?: number, наХод?: Function, отменён?: () => boolean,
 *           предыдущие?: string[] }} п
 *   предыдущие — SAN уже сделанных из этой позиции ходов: продолжить с конца
 * @returns {Promise<{ ходы: Array<{san, from, to, fen, оценка}>, итог }>}
 */
export async function доиграть(fen, движок, { глубина = 12, предел = ПРЕДЕЛ_ПОЛУХОДОВ, наХод, отменён, предыдущие = [] } = {}) {
    const доска = new Chess(fen);
    const ходы = [];

    // Уже сделанные ходы проигрываются на доске — ради истории повторений
    for (const san of предыдущие) доска.move(san);

    await движок.новаяПартия();

    while (ходы.length + предыдущие.length < предел) {
        const конец = итогДоигрыша(доска);
        if (конец) return { ходы, итог: конец };
        if (отменён?.()) return { ходы, итог: { вид: 'стоп', текст: 'Остановлено' } };

        const очередь = доска.turn();
        const ответ = await движок.оценить(доска.fen(), { глубина, линий: 1 });
        if (!ответ.лучший || ответ.лучший === '(none)') break;

        const ход = доска.move({ from: ответ.лучший.slice(0, 2), to: ответ.лучший.slice(2, 4), promotion: ответ.лучший[4] });
        const запись = {
            san: ход.san,
            from: ход.from,
            to: ход.to,
            fen: доска.fen(),
            оценка: ответ.линии[0] ? заБелых(ответ.линии[0].оценка, очередь) : null
        };

        ходы.push(запись);
        наХод?.(запись, ходы);
    }

    return { ходы, итог: итогДоигрыша(доска) || { вид: 'предел', текст: `Остановлено на ${предел} полуходах` } };
}

// ================== РАССТАНОВКА ==================

const ВЕРТИКАЛИ = 'abcdefgh';

/** Расстановка ({ e1: 'wK', … }) и очередь хода — в FEN. Рокировки — по местам королей и ладей. */
export function вFen(расстановка, очередь = 'w') {
    const ряды = [];

    for (let г = 8; г >= 1; г--) {
        let ряд = '';
        let пусто = 0;

        for (let в = 0; в < 8; в++) {
            const ф = расстановка[`${ВЕРТИКАЛИ[в]}${г}`];
            if (!ф) {
                пусто++;
                continue;
            }
            if (пусто) {
                ряд += пусто;
                пусто = 0;
            }
            ряд += ф[0] === 'w' ? ф[1] : ф[1].toLowerCase();
        }

        if (пусто) ряд += пусто;
        ряды.push(ряд);
    }

    // Рокировка возможна, только если король и ладья стоят на своих местах;
    // ходили ли они раньше — по расстановке не узнать, считаем, что нет
    const на = (поле, ф) => расстановка[поле] === ф;
    const права = [
        на('e1', 'wK') && на('h1', 'wR') ? 'K' : '',
        на('e1', 'wK') && на('a1', 'wR') ? 'Q' : '',
        на('e8', 'bK') && на('h8', 'bR') ? 'k' : '',
        на('e8', 'bK') && на('a8', 'bR') ? 'q' : ''
    ].join('') || '-';

    return `${ряды.join('/')} ${очередь} ${права} - 0 1`;
}

/**
 * Можно ли с этой расстановки играть — и если нет, то почему, словами.
 *
 * @returns {string|null} причина или null, если позиция годна
 */
export function проверитьРасстановку(расстановка, очередь = 'w') {
    const фигуры = Object.entries(расстановка);
    const сколько = (ф) => фигуры.filter(([, к]) => к === ф).length;

    if (сколько('wK') !== 1) return сколько('wK') ? 'Белый король должен быть один' : 'Нет белого короля';
    if (сколько('bK') !== 1) return сколько('bK') ? 'Чёрный король должен быть один' : 'Нет чёрного короля';

    if (фигуры.some(([поле, к]) => к[1] === 'P' && (поле[1] === '1' || поле[1] === '8'))) {
        return 'Пешка не может стоять на первой или последней горизонтали';
    }

    let доска;
    try {
        доска = new Chess(вFen(расстановка, очередь));
    } catch (e) {
        return `Позиция невозможна: ${e.message || e}`;
    }

    // Король стороны, которая НЕ ходит, под шахом — так не бывает: значит,
    // предыдущим ходом его оставили под шахом
    const наоборот = new Chess(вFen(расстановка, очередь === 'w' ? 'b' : 'w'));
    if (наоборот.inCheck()) return `${очередь === 'w' ? 'Чёрному' : 'Белому'} королю шах, а ход ${очередь === 'w' ? 'белых' : 'чёрных'} — так не бывает`;

    if (итогДоигрыша(доска)?.вид === 'мат') return 'В этой позиции уже мат';
    if (итогДоигрыша(доска)?.вид === 'пат') return 'В этой позиции пат';

    return null;
}
