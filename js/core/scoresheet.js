/**
 * Бланк: что спросить у модели и как сверить прочитанное с правилами.
 *
 * Слабость всех приложений, читающих бланки, — почерк. «Lb5» и «Lb3»,
 * «Sd7» и «Sd2», «e6» и «c6» модель путает, и ошибку замечают, когда партия
 * на доске уже идёт не туда. Здесь модель не решает, какой ход был: она
 * перечисляет, как ещё можно прочитать каждую клетку, а решают правила (Р-12).
 *
 * Сверка — поиск лучом: идём по ходам, держа несколько самых правдоподобных
 * цепочек. Прочтение, невозможное в позиции, отбрасывается сразу. Из двух
 * возможных предпочитается то, что модель назвала первым, — но только пока
 * оно не заводит в тупик: неверно прочитанный двенадцатый ход обычно делает
 * невозможным пятнадцатый, и тогда выживает цепочка с другим двенадцатым.
 */

import { Chess } from './chess.js';
import { найтиХод } from './notation.js';

// ================== ВОПРОС МОДЕЛИ ==================

/**
 * Схема ответа — Gemini обязан ответить ровно этим JSON.
 *
 * Рамка клетки — [ymin, xmin, ymax, xmax] в долях тысячи: так Gemini
 * описывает места на снимке, и так он делает это точнее всего.
 */
export const СХЕМА = {
    type: 'OBJECT',
    properties: {
        white: { type: 'STRING' },
        black: { type: 'STRING' },
        event: { type: 'STRING' },
        date: { type: 'STRING' },
        result: { type: 'STRING' },
        moves: {
            type: 'ARRAY',
            items: {
                type: 'OBJECT',
                properties: {
                    n: { type: 'INTEGER' },
                    page: { type: 'INTEGER' },
                    w: { type: 'ARRAY', items: { type: 'STRING' } },
                    b: { type: 'ARRAY', items: { type: 'STRING' } },
                    wBox: { type: 'ARRAY', items: { type: 'INTEGER' } },
                    bBox: { type: 'ARRAY', items: { type: 'INTEGER' } }
                },
                required: ['n', 'w', 'b']
            }
        }
    },
    required: ['moves']
};

/**
 * Вопрос модели — по-английски: на нём модели читают инструкции точнее
 * всего, а ответ всё равно идёт в JSON, не человеку.
 *
 * Главное в нём — не переводить нотацию и давать варианты. Переводом
 * модель портит чаще, чем помогает: немецкая L становится английской
 * L, которой нет. Переводит разбор хода — он понимает все три нотации.
 */
export function вопрос(страниц = 1) {
    return `You are reading a handwritten chess scoresheet${страниц > 1 ? ` (${страниц} images, consecutive pages of the same game, in order)` : ''}.
The player writes in German algebraic notation: K = king, D = queen, T = rook, L = bishop, S = knight, pawns have no letter; captures as "x" or ":", castling as "0-0" / "0-0-0". Some moves may be in English (Q, R, B, N) or Russian (Кр, Ф, Л, С, К) notation, or in long form like "Sg1-f3".

Return every move in game order. Scoresheets usually have columns: moves 1–30 in the left block, 31–60 in the right block; a second page continues the numbering.
For each move number give:
- "w": white's half-move, "b": black's half-move — each as a list of up to 3 alternative readings of the handwriting, most likely first. Copy the characters exactly as written (do not translate letters to another notation, do not add check signs that are not there). If the handwriting is clear, give one reading. If a cell is empty, give an empty list.
- "wBox", "bBox": the bounding box of that handwritten cell as [ymin, xmin, ymax, xmax], normalized to 0–1000 of its image.
- "page": the 0-based index of the image the move is on.
Stop after the last move actually written. Never invent moves, never continue the game yourself.
Also read the header if present: "white", "black" (player names), "event", "date" (as YYYY-MM-DD if possible), "result" (1-0, 0-1, 1/2-1/2). Leave unknown fields empty.`;
}

/**
 * Ответ модели — в полуходы, с недоверием ко всему.
 *
 * Номера ходов модель иногда пропускает или повторяет; порядок здесь
 * задаётся местом в списке, а не номером. Пустая клетка белых посреди
 * партии — сигнал «не прочитано», а не конец: конец — это последний
 * непустой полуход.
 *
 * @returns {{ полуходы: Array<{прочтения, рамка, страница}>, заголовки }}
 */
export function разобратьОтвет(ответ) {
    const ходы = Array.isArray(ответ?.moves) ? ответ.moves : [];
    const полуходы = [];

    const прочтения = (список) => (Array.isArray(список) ? список : [])
        .map((с) => String(с ?? '').trim())
        .filter(Boolean)
        .filter((с, i, все) => все.indexOf(с) === i)
        .slice(0, 4);

    const рамка = (р) => (Array.isArray(р) && р.length === 4 && р.every((ч) => Number.isFinite(Number(ч)))
        ? р.map(Number)
        : null);

    for (const х of ходы) {
        const страница = Number.isInteger(х?.page) ? х.page : 0;
        полуходы.push({ прочтения: прочтения(х?.w), рамка: рамка(х?.wBox), страница });
        полуходы.push({ прочтения: прочтения(х?.b), рамка: рамка(х?.bBox), страница });
    }

    // Хвост пустых клеток — это конец записи, а не нечитаемые ходы
    while (полуходы.length && !полуходы.at(-1).прочтения.length) полуходы.pop();

    const результат = String(ответ?.result || '').replace(/\s/g, '').replace('½-½', '1/2-1/2');
    const дата = /^\d{4}-\d{2}-\d{2}$/.test(String(ответ?.date || '').trim()) ? ответ.date.trim() : '';

    return {
        полуходы,
        заголовки: {
            белые: String(ответ?.white || '').trim(),
            чёрные: String(ответ?.black || '').trim(),
            событие: String(ответ?.event || '').trim(),
            дата,
            результат: ['1-0', '0-1', '1/2-1/2'].includes(результат) ? результат : ''
        }
    };
}

// ================== СВЕРКА ==================

/** Сколько цепочек держать одновременно. */
const ЛУЧ = 16;

/**
 * Цена выбора не первого прочтения.
 *
 * Единица за ранг: второе прочтение стоит одну, третье две. Этого хватает,
 * чтобы при прочих равных побеждало первое, а цепочка, ушедшая дальше,
 * побеждала любую с меньшей ценой — длина сравнивается раньше цены.
 */
const ЦЕНА_РАНГА = 1;

/** Допустимые ходы из прочтений: { ход, ранг } без повторов, по рангу. */
function варианты(доска, прочтения, допустимые) {
    const итог = new Map();

    прочтения.forEach((текст, ранг) => {
        const найдено = найтиХод(доска, текст, допустимые);
        if (найдено.ход && !итог.has(найдено.ход.san)) итог.set(найдено.ход.san, { ход: найдено.ход, ранг });
    });

    return [...итог.values()];
}

/**
 * Сверить прочитанное с правилами.
 *
 * @param {Array<{прочтения: string[]}>} полуходы — из разобратьОтвет
 * @param {Object<number, string>} закреплено — полуход (с нуля) → SAN,
 *   выбранный человеком; такой полуход других вариантов не рассматривает
 * @returns {{
 *   ходы: string[],
 *   пометки: Array<{ статус, варианты: Array<{san, ранг}>, ранг }>,
 *   остановка: null | { полуход, причина }
 * }}
 *   статус: 'уверенно' — прочтение одно и оно возможно;
 *           'исправлено' — первое прочтение невозможно, взято другое;
 *           'сомнение' — возможно больше одного прочтения;
 *           'закреплено' — выбрал человек
 */
export function сверить(полуходы, закреплено = {}) {
    const { лучшая, финал, обрезано } = поиск(полуходы, закреплено);
    const n = лучшая.ходы.length;

    /*
     * Живая ли альтернатива — сперва смотрим среди цепочек, доживших до
     * конца: если какая-то из них прошла через этот ход, ответ готов. Заново
     * искать приходится, только если луч обрезался и альтернативу могли
     * выбросить по цене, не досчитав, — и тогда поиск начинается с этого
     * хода, а не с начала партии.
     */
    const живая = (i, san) => финал.some((ц) => ц.ходы[i] === san)
        || (обрезано && поиск(полуходы, { ...закреплено, [i]: san }, {
            полуход: i, fen: лучшая.выборы[i].fen, ходы: лучшая.ходы.slice(0, i), выборы: лучшая.выборы.slice(0, i)
        }).лучшая.ходы.length >= n);

    /*
     * Сомнение — только то, что не разрешилось дальше по партии.
     *
     * На двенадцатом ходу могут быть возможны и «Sd7», и «Sd2», но если
     * после «Sd2» через три хода партия упирается в невозможный ход, это
     * уже не сомнение: правила выбрали за человека. Спрашивать его о таком
     * — значит тратить его внимание на то, что решено. Поэтому каждая
     * альтернатива проверяется: доживает ли партия с ней до того же места.
     */
    const пометки = лучшая.выборы.map((в, i) => {
        if (в.закреплён) return { статус: 'закреплено', варианты: [{ san: в.san, ранг: 0 }], ранг: 0 };

        const живые = в.все.filter((а) => а.san === в.san || живая(i, а.san));

        const статус = живые.length > 1 ? 'сомнение' : в.ранг > 0 ? 'исправлено' : 'уверенно';
        return { статус, варианты: живые.map(({ san, ранг }) => ({ san, ранг })), ранг: в.ранг };
    });

    const остановка = n < полуходы.length
        ? {
            полуход: n,
            причина: !полуходы[n].прочтения.length
                ? 'клетка пустая или не прочитана'
                : закреплено[n]
                    ? `выбранный ход «${закреплено[n]}» здесь невозможен`
                    : `ни одно прочтение не подходит: ${полуходы[n].прочтения.map((п) => `«${п}»`).join(', ')}`
        }
        : null;

    return { ходы: лучшая.ходы, пометки, остановка };
}

const НАЧАЛО = new Chess().fen();

/**
 * Поиск лучом: самая длинная цепочка возможных ходов, при равной длине —
 * самая дешёвая.
 *
 * Цепочка хранит позицию строкой FEN, а не доской: следующую позицию
 * chess.js отдаёт готовой в подробном ходе (after), и делать ход на копии
 * доски не нужно. Это и есть основная экономия — сверка бланка на
 * шестьдесят ходов с сомнениями укладывается в доли секунды.
 *
 * @param {object} [от] — продолжить с полухода от.полуход из позиции от.fen
 * @returns {{ лучшая, финал, обрезано }} финал — все цепочки, дожившие до
 *   конца; обрезано — луч хоть раз отбрасывал цепочки по цене
 */
function поиск(полуходы, закреплено, от = null) {
    const старт = от
        ? { fen: от.fen, ходы: от.ходы, выборы: от.выборы, цена: 0 }
        : { fen: НАЧАЛО, ходы: [], выборы: [], цена: 0 };

    let цепочки = [старт];
    let обрезано = false;

    for (let i = от ? от.полуход : 0; i < полуходы.length; i++) {
        const следующие = [];

        for (const ц of цепочки) {
            const доска = new Chess(ц.fen);
            const допустимые = доска.moves({ verbose: true });

            let можно;
            if (закреплено[i]) {
                const найдено = найтиХод(доска, закреплено[i], допустимые);
                можно = найдено.ход ? [{ ход: найдено.ход, ранг: 0, закреплён: true }] : [];
            } else {
                можно = варианты(доска, полуходы[i].прочтения, допустимые);
            }

            const все = можно.map(({ ход, ранг }) => ({ san: ход.san, ранг }));

            for (const в of можно) {
                следующие.push({
                    fen: в.ход.after,
                    ходы: [...ц.ходы, в.ход.san],
                    выборы: [...ц.выборы, { san: в.ход.san, ранг: в.ранг, закреплён: !!в.закреплён, все, fen: ц.fen }],
                    цена: ц.цена + в.ранг * ЦЕНА_РАНГА
                });
            }
        }

        if (!следующие.length) break;

        следующие.sort((а, б) => а.цена - б.цена);
        if (следующие.length > ЛУЧ) обрезано = true;
        цепочки = следующие.slice(0, ЛУЧ);
    }

    return { лучшая: цепочки[0], финал: цепочки, обрезано };
}

/**
 * Полуходы, на которые человеку стоит взглянуть: всё, кроме уверенных.
 *
 * Плюс место остановки — его не обойти, без него партия дальше не идёт.
 */
export function сомнительные(сверка) {
    const итог = сверка.пометки
        .map((п, i) => ({ ...п, полуход: i }))
        .filter((п) => п.статус === 'сомнение' || п.статус === 'исправлено')
        .map((п) => п.полуход);

    if (сверка.остановка) итог.push(сверка.остановка.полуход);
    return итог;
}
