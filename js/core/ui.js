/**
 * Мелкие помощники сборки разметки.
 *
 * Разметка собирается строками и перерисовывается целиком, поэтому любое
 * значение обязано пройти через экранирование. В тренажёре почти всё своё —
 * имена нот и подписи уровней, — но своим оно быть перестанет в первый же
 * день, когда ребёнок впишет своё имя.
 */

const ЗАМЕНЫ = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
};

export const ui = {

    esc(значение) {
        if (значение === null || значение === undefined) return '';
        return String(значение).replace(/[&<>"']/g, (ch) => ЗАМЕНЫ[ch]);
    },

    /**
     * Шаблон с автоматическим экранированием подстановок:
     *   html`<div>${имя}</div>`
     *
     * Массивы склеиваются без разделителя — удобно для списков. Результат
     * помечен как готовая разметка, поэтому шаблоны вкладываются друг в
     * друга: экранируются только простые значения.
     */
    html(строки, ...значения) {
        const out = строки.reduce((acc, часть, i) => {
            if (i === 0) return часть;
            return acc + ui.render(значения[i - 1]) + часть;
        }, '');

        return ui.raw(out);
    },

    render(значение) {
        if (значение === null || значение === undefined || значение === false) return '';
        if (Array.isArray(значение)) return значение.map(ui.render).join('');
        if (значение && значение.__raw) return значение.value;
        return ui.esc(значение);
    },

    /**
     * Пометить строку как готовую разметку.
     *
     * toString обязателен: помеченная разметка попадает и в innerHTML, и в
     * обычные шаблонные строки, а там объект должен превращаться в свой
     * текст сам.
     */
    raw(значение) {
        return {
            __raw: true,
            value: String(значение ?? ''),
            toString() { return this.value; }
        };
    },

    /** Звёзды уровня: закрашенные и пустые, всегда три. */
    звёзды(сколько) {
        return ui.raw([0, 1, 2]
            .map((i) => `<span class="star ${i < сколько ? 'on' : ''}">★</span>`)
            .join(''));
    }
};
