/**
 * Распознать бланк: снимки → Gemini → полуходы с вариантами прочтения.
 *
 * Сам вопрос и сверка — в scoresheet.js и проверяются без сети. Здесь
 * только доставка: выбрать модель, спросить, разобрать ответ.
 *
 * Исполнитель подменяется проверками (задатьИсполнителя): экран
 * распознавания проверяется целиком, но ходить в Google ради этого нельзя —
 * нужен был бы настоящий ключ, и проверка зависела бы от чужой квоты.
 */

import { ai, МОДЕЛЬ_ПО_УМОЛЧАНИЮ } from './ai.js';
import { хранилище } from './store.js';
import { СХЕМА, вопрос, разобратьОтвет } from './scoresheet.js';

/**
 * Модель для запроса: заданная в настройках, иначе выбранная из списка
 * Google — и запомненная, чтобы не спрашивать список каждый раз.
 */
async function модель(ключ) {
    const н = хранилище.настройки();
    if (н.модель) return н.модель;

    try {
        const список = await ai.модели(ключ);
        const выбрана = ai.выбрать(список) || МОДЕЛЬ_ПО_УМОЛЧАНИЮ;
        хранилище.настроить({ модель: выбрана, модели: список });
        return выбрана;
    } catch {
        // Список не дался — пробуем умолчание; если ключ плох, скажет сам запрос
        return МОДЕЛЬ_ПО_УМОЛЧАНИЮ;
    }
}

const ИЗВЕСТНЫЕ_ЗАПАСНЫЕ = ['gemini-2.5-flash', 'gemini-2.5-pro'];

async function очередьМоделей(ключ) {
    const основная = await модель(ключ);
    const { модели } = хранилище.настройки();
    const запасные = ai.запасные(модели.length ? модели : ИЗВЕСТНЫЕ_ЗАПАСНЫЕ, основная);
    return [основная, ...запасные].slice(0, 3);
}

async function черезGemini(снимки, { наСостояние } = {}) {
    const { ключ } = хранилище.настройки();
    if (!ai.готов(ключ)) throw new Error('Ключ Gemini не задан. Впишите его в настройках — там же есть кнопка «Взять из трекера».');

    const ответ = await ai.спроситьJSON({
        ключ,
        // Основная и две запасные: при перегрузке основной чтение идёт дальше
        // по списку, который Google отдал этому ключу (Р-26). Списка ещё нет —
        // запасные известные; какой нет у ключа, та пропустится (404)
        модели: await очередьМоделей(ключ),
        наСостояние,
        снимки,
        текст: вопрос(снимки.length),
        схема: СХЕМА
    });

    return разобратьОтвет(ответ);
}

let исполнитель = черезGemini;

export const распознавание = {

    /** @returns {Promise<{ полуходы, заголовки }>} */
    выполнить(снимки, параметры = {}) {
        return исполнитель(снимки, параметры);
    },

    /** Только для проверок. Без аргумента — вернуть настоящего. */
    задатьИсполнителя(функция) {
        исполнитель = функция || черезGemini;
    }
};
