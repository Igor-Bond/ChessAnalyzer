/**
 * Установка на телефон: своя кнопка и честный ответ, почему её нет.
 *
 * Пункт меню Chrome «Установить приложение» пропадает молча, и человек
 * видит только «нет возможности установить» — без единой причины. После
 * переименования репозитория так и вышло: Chrome помнил незавершённую
 * установку и вместо «Установить» показывал «Открыть в приложении», которое
 * не открывалось (Р-24).
 *
 * Поэтому здесь две вещи. Кнопка: Chrome сообщает о готовности установить
 * событием beforeinstallprompt — один раз и в произвольный момент; событие
 * придерживается до нажатия. И диагностика: в каком режиме открыто, дал ли
 * Chrome событие, считает ли он приложение уже установленным
 * (getInstalledRelatedApps — по строке related_applications в манифесте).
 */

let отложенное = null;
let установлено = false;
let запущено = false;
const слушатели = new Set();

function известить() {
    for (const ф of слушатели) {
        try { ф(); } catch (e) { console.error('[Установка]', e); }
    }
}

export const установка = {

    /** Chrome готов установить прямо сейчас — можно показать кнопку. */
    get можно() {
        return отложенное !== null;
    },

    /** Открыто как установленное приложение, а не вкладкой браузера. */
    get вПриложении() {
        return matchMedia('(display-mode: standalone)').matches
            || matchMedia('(display-mode: fullscreen)').matches
            || navigator.standalone === true;
    },

    /** Шлёт ли браузер событие установки вообще (Chrome — да, Safari и Firefox — нет). */
    get поддерживается() {
        return 'onbeforeinstallprompt' in window;
    },

    наИзменение(функция) {
        слушатели.add(функция);
        return () => слушатели.delete(функция);
    },

    /** Показать системное окно установки. Событие одноразовое. */
    async установить() {
        if (!отложенное) return false;

        const событие = отложенное;
        отложенное = null;
        событие.prompt();
        const { outcome } = await событие.userChoice;
        известить();
        return outcome === 'accepted';
    },

    /**
     * Что думает браузер — для экрана настроек и для пересказа.
     *
     * @returns {Promise<{ состояние, установленКакСчитает, браузер }>}
     *   состояние: 'в-приложении' | 'можно' | 'считает-установленным' |
     *              'ждём' | 'вручную'
     */
    async диагноз({ связанные = navigator.getInstalledRelatedApps?.bind(navigator) } = {}) {
        let считаетУстановленным = установлено;

        try {
            const список = связанные ? await связанные() : [];
            if (Array.isArray(список) && список.some((п) => п.platform === 'webapp')) считаетУстановленным = true;
        } catch {
            // Не везде есть и не везде разрешено — тогда просто не знаем
        }

        const состояние = установка.вПриложении ? 'в-приложении'
            : установка.можно ? 'можно'
                : считаетУстановленным ? 'считает-установленным'
                    : установка.поддерживается ? 'ждём'
                        : 'вручную';

        return { состояние, считаетУстановленным, браузер: navigator.userAgent };
    },

    init() {
        // Повторный вызов навесил бы вторых слушателей
        if (запущено) return;
        запущено = true;

        window.addEventListener('beforeinstallprompt', (e) => {
            e.preventDefault();
            отложенное = e;
            известить();
        });

        window.addEventListener('appinstalled', () => {
            отложенное = null;
            установлено = true;
            известить();
        });
    },

    /** Только для проверок: забыть пойманное событие. */
    сбросить() {
        отложенное = null;
        установлено = false;
    }
};
