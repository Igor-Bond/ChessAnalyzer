export const фотоЭкран = {

    render(id) {
        if (с.id !== id) сбросить(id);

        const п = хранилище.партия(id);
        if (!п) {
            return html`
                <header class="topbar">
                    <button class="icon-btn" data-action="в-архив" aria-label="Назад">${raw(иконка('назад'))}</button>
                    <h1>Партия не найдена</h1>
                </header>
            `;
        }

        const { нотация } = хранилище.настройки();

        return html`
            <header class="topbar">
                <button class="icon-btn" data-action="к-вводу" aria-label="Назад к вводу" title="Назад к вводу">${raw(иконка('назад'))}</button>
                <h1>Фото бланка</h1>
            </header>

            ${с.этап === 'выбор' ? этапВыбора(нотация) : ''}
            ${с.этап === 'чтение' ? этапЧтения() : ''}
            ${с.этап === 'сверка' ? этапСверки(нотация) : ''}
        `;
    },

    after() {
        if (с.этап === 'сверка') подгрузитьВырезку(с.выбран);
    },

    // Ушли с фото, не взяв партию и не на её ввод, — пустую не оставляем
    leave(куда) {
        if (с.этап !== 'чтение') убратьПустую(с.id, куда);
    }
};

