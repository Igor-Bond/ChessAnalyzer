actions.on('фото', () => {
    const id = app.route.param;
    if (id) app.go('фото', id);
});

actions.on('к-вводу', () => app.go('ввод', с.id));

actions.onChange('снимки', async (el) => {
    // «Добавить вторую страницу» дописывает к уже снятой, остальные — заменяют
    const добавить = el.dataset.add === '1';
    const файлы = [...(el.files || [])].slice(0, СТРАНИЦ - (добавить ? с.снимки.length : 0));
    if (!файлы.length) return;

    с.ошибка = '';

    try {
        const новые = await Promise.all(файлы.map((ф) => уменьшить(ф)));
        с.снимки = добавить ? [...с.снимки, ...новые].slice(0, СТРАНИЦ) : новые;
    } catch (e) {
        if (!добавить) с.снимки = [];
        с.ошибка = e.message || String(e);
    }

    app.render();
});

actions.on('распознать', async () => {
    if (!с.снимки.length || с.этап === 'чтение') return;

    const id = с.id;
    с.этап = 'чтение';
    с.ошибка = '';
    с.состояниеЧтения = '';
    с.начато = Date.now();
    app.render();

    // Секунды на экране ожидания: без них минута выглядит зависанием
    const часы = setInterval(() => {
        if (app.route.name === 'фото' && с.этап === 'чтение') app.render({ фон: true });
    }, 1000);

    try {
        const итог = await распознавание.выполнить(с.снимки, {
            // «Google перегружен — повтор через 3 с»: без этого минута повторов
            // выглядела бы зависанием
            наСостояние: (текст) => {
                if (с.id !== id) return;
                с.состояниеЧтения = текст;
                if (app.route.name === 'фото') app.render({ фон: true });
            }
        });
        if (с.id !== id) return;

        if (!итог.полуходы.length) throw new Error('На снимке не нашлось ни одного хода. Снимите бланк ближе и ровнее.');

        с.полуходы = итог.полуходы;
        с.заголовки = итог.заголовки;
        с.закреплено = {};
        с.сверка = сверить(с.полуходы, с.закреплено);
        с.выбран = первыйСомнительный();
        с.вырезки = new Map();
        с.этап = 'сверка';
    } catch (e) {
        if (с.id !== id) return;
        с.этап = 'выбор';
        с.ошибка = e.message || String(e);
    } finally {
        clearInterval(часы);
    }

    if (app.route.name === 'фото') app.render();
});

actions.on('к-полуходу', (el) => {
    if (!с.сверка) return;
    с.выбран = Math.max(0, Number(el.dataset.ply) || 0);
    с.выбрано = null;
    с.ошибкаВвода = '';
    app.render();
});

actions.on('к-сомнительному', () => {
    if (!с.сверка) return;
    const список = сомнительные(с.сверка);
    const дальше = список.find((i) => i > с.выбран) ?? список[0];
    if (дальше !== undefined) с.выбран = дальше;
    с.ошибкаВвода = '';
    app.render();
});

/** Закрепить ход за полуходом и пересверить всё после него. */
function закрепить(полуход, san) {
    с.закреплено = { ...с.закреплено, [полуход]: san };
    с.сверка = сверить(с.полуходы, с.закреплено);
    с.выбрано = null;
    с.ошибкаВвода = '';

    // Дальше — к следующему вопросу после этого хода, если он есть
    const список = сомнительные(с.сверка);
    с.выбран = список.find((i) => i > полуход) ?? Math.min(полуход, с.сверка.ходы.length - 1);
}

actions.on('выбрать-вариант', (el) => {
    if (!с.сверка) return;
    закрепить(с.выбран, el.dataset.san);
    app.render();
});

actions.onSubmit('ручной-ход', (форма) => {
    if (!с.сверка) return;
    const текст = форма.querySelector('input[name="ход"]').value.trim();
    if (!текст) return;

    const найдено = найтиХод(доскаДо(с.выбран), текст);
    if (!найдено.ход) {
        с.ошибкаВвода = найдено.ошибка;
        app.render();
        // Набранное не стираем: ошибку исправляют, а не набирают заново
        const поле = document.getElementById('manual-move');
        if (поле) поле.value = текст;
        return;
    }

    закрепить(с.выбран, найдено.ход.san);
    app.render();
});

// Доска нажимаемая только на месте остановки: там ход вводят сами
actions.on('клетка-фото', (el) => {
    if (!с.сверка || с.сверка.остановка?.полуход !== с.выбран) return;

    const поле = el.dataset.square;
    const доска = доскаДо(с.выбран);

    if (с.выбрано) {
        const ход = доска.moves({ square: с.выбрано, verbose: true }).find((х) => х.to === поле && (!х.promotion || х.promotion === 'q'));
        if (ход) {
            закрепить(с.выбран, ход.san);
            return app.render();
        }
    }

    const фигура = доска.get(поле);
    с.выбрано = фигура && фигура.color === доска.turn() && поле !== с.выбрано ? поле : null;
    app.render();
});

actions.on('переснять', () => {
    с.этап = 'выбор';
    с.сверка = null;
    app.render();
});

actions.on('взять-партию', () => {
    const п = хранилище.партия(с.id);
    if (!п || !с.сверка?.ходы.length) return;

    if (п.ходы.length && !confirm('Заменить уже введённые ходы прочитанными с бланка?')) return;

    const з = с.заголовки;
    const доска = доскаДо(с.сверка.ходы.length);

    хранилище.сохранить({
        ...п,
        ходы: с.сверка.ходы,
        белые: з.белые || п.белые,
        чёрные: з.чёрные || п.чёрные,
        событие: з.событие || п.событие,
        дата: з.дата || п.дата,
        результат: з.результат || результатПоПозиции(доска) || п.результат || '*',
        разбор: null
    });

    const неполная = !!с.сверка.остановка;
    сбросить(null);
    app.go(неполная ? 'ввод' : 'разбор', п.id);
});

actions.on('снимки-заново', () => {
    с.снимки = [];
    с.ошибка = '';
    app.render();
});
