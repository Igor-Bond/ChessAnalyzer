/** Не больше двух страниц: на бланке их и бывает две, а каждая — время ответа. */
const СТРАНИЦ = 2;

const с = {
    id: null,
    этап: 'выбор',         // выбор | чтение | сверка
    снимки: [],
    ошибка: '',
    полуходы: [],
    заголовки: {},
    закреплено: {},
    сверка: null,
    выбран: 0,
    вырезки: new Map(),
    выбрано: null,         // поле фигуры при ручном ходе по доске
    ошибкаВвода: '',
    начато: 0,
    состояниеЧтения: ''
};

function сбросить(id) {
    Object.assign(с, {
        id, этап: 'выбор', снимки: [], ошибка: '', полуходы: [], заголовки: {},
        закреплено: {}, сверка: null, выбран: 0, вырезки: new Map(), выбрано: null,
        ошибкаВвода: '', начато: 0, состояниеЧтения: ''
    });
}

/** Первый полуход, на который стоит посмотреть, — или последний прочитанный. */
function первыйСомнительный() {
    const список = сомнительные(с.сверка);
    return список.length ? список[0] : Math.max(0, с.сверка.ходы.length - 1);
}

/** Доска после полухода i (с нуля); для места остановки — до него. */
function доскаДо(полуход) {
    const доска = new Chess();
    for (const san of с.сверка.ходы.slice(0, полуход)) доска.move(san);
    return доска;
}

/** Вырезку считаем один раз и подгружаем: показ экрана её не ждёт. */
function подгрузитьВырезку(полуход) {
    if (с.вырезки.has(полуход)) return;

    const п = с.полуходы[полуход];
    const снимок = с.снимки[п?.страница ?? 0];
    с.вырезки.set(полуход, null);

    вырезать(снимок, п?.рамка).then((адрес) => {
        с.вырезки.set(полуход, адрес || '');
        if (app.route.name === 'фото' && с.выбран === полуход) app.render({ фон: true });
    }).catch(() => с.вырезки.set(полуход, ''));
}

