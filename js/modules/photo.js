/**
 * Кнопка выбора снимка — label с невидимым полем файла.
 *
 * Камера и галерея — две разные кнопки (Р-27). Одно поле с multiple
 * Android открывает без камеры: только выбор готовых файлов, — и снять
 * бланк из приложения было нельзя. Поле с capture="environment" сразу
 * открывает заднюю камеру; поле галереи без capture и с multiple — выбор
 * готовых снимков, можно обе страницы разом.
 */
function кнопкаСнимка(подпись, значок, вид, галерея = false, добавить = false) {
    const поле = галерея
        ? '<input type="file" accept="image/*" multiple data-change="снимки" hidden>'
        : `<input type="file" accept="image/*" capture="environment" data-change="снимки"${добавить ? ' data-add="1"' : ''} hidden>`;

    return `<label class="btn ${вид} big file-btn">${иконка(значок)} ${подпись}${поле}</label>`;
}

function этапЧтения() {
    const прошло = Math.round((Date.now() - с.начато) / 1000);

    return html`
        <section class="card reading">
            <div class="spinner" aria-hidden="true"></div>
            <p><b>Gemini читает бланк…</b></p>
            ${с.состояниеЧтения ? html`<p class="small">${с.состояниеЧтения}</p>` : ''}
            <p class="muted small">Обычно 20–60 секунд${прошло > 3 ? ` · прошло ${прошло} с` : ''}.</p>
        </section>
    `;
}

function итогСверки() {
    const п = с.сверка.пометки;
    const счёт = (статус) => п.filter((х) => х.статус === статус).length;
    const ходов = Math.ceil(с.сверка.ходы.length / 2);
    // Вопрос — только то, что правила не решили: сомнение и место остановки.
    // Поправленное правилами подсвечено, но вопросом не считается
    const вопросов = счёт('сомнение') + (с.сверка.остановка ? 1 : 0);

    return html`
        <section class="card">
            <div class="recog-sum">
                <div><b>${ходов}</b><span>${склонение(ходов, 'ход прочитан', 'хода прочитано', 'ходов прочитано')}</span></div>
                <div class="st-исправлено"><b>${счёт('исправлено')}</b><span>поправили правила</span></div>
                <div class="st-сомнение"><b>${вопросов}</b><span>${вопросов ? 'на проверку' : 'вопросов нет'}</span></div>
            </div>
            ${с.сверка.остановка ? html`
                <p class="form-error">Ход ${номерХода(с.сверка.остановка.полуход + 1)} — ${с.сверка.остановка.причина}. Дальше партия не идёт, пока его не поправить.</p>
            ` : html`<p class="form-note">Вся запись сходится с правилами.</p>`}
        </section>
    `;
}

function карточкаПолухода(нотация) {
    const i = с.выбран;
    const сверка = с.сверка;
    const остановка = сверка.остановка?.полуход === i;
    const пометка = сверка.пометки[i];
    const прочтения = с.полуходы[i]?.прочтения || [];
    const вырезка = с.вырезки.get(i);
    const подпись = номерХода(i + 1);

    const заголовок = остановка
        ? html`${подпись} <span class="cls st-стоп">не читается</span>`
        : html`${подпись} ${показатьХод(сверка.ходы[i], нотация)} <span class="cls st-${пометка.статус}">${{
            уверенно: 'прочитано уверенно',
            исправлено: 'поправлено правилами',
            сомнение: 'проверьте',
            закреплено: 'выбрано вами'
        }[пометка.статус]}</span>`;

    // Возможные ходы: из прочтений, а для места остановки — пусто, там вводят сами
    const варианты = остановка ? [] : пометка.варианты;

    return html`
        <section class="card move-card recog-card">
            <div class="move-title">${заголовок}</div>

            ${вырезка ? html`<img class="cell-crop" src="${вырезка}" alt="Клетка бланка">`
                : вырезка === '' ? html`<p class="muted small">Место на снимке модель не указала.</p>`
                    : html`<div class="cell-crop placeholder"></div>`}

            ${прочтения.length ? html`
                <p class="small">Модель прочитала: ${прочтения.map((п, к) => html`<span class="reading-chip ${!остановка && пометка.варианты.some((в) => в.ранг === к) ? '' : 'dead'}">${п}</span>`)}</p>
            ` : ''}

            ${варианты.length > 1 ? html`
                <p class="small muted">Возможны ходы — выберите написанный:</p>
                <div class="choice-row">
                    ${варианты.map((в) => html`
                        <button class="btn ${в.san === сверка.ходы[i] ? 'primary' : ''}" data-action="выбрать-вариант" data-san="${в.san}">${показатьХод(в.san, нотация)}</button>
                    `)}
                </div>
            ` : ''}

            <form class="move-form" data-submit="ручной-ход" autocomplete="off">
                <label class="small muted" for="manual-move">${остановка ? 'Впишите ход с бланка или сделайте его на доске' : 'Или впишите ход сами'}</label>
                <div class="move-row">
                    <input id="manual-move" name="ход" class="move-input" placeholder="напр. Sbd7" autocapitalize="off" autocorrect="off" spellcheck="false">
                    <button class="btn" type="submit">Поставить</button>
                </div>
                ${с.ошибкаВвода ? html`<p class="form-error">${с.ошибкаВвода}</p>` : ''}
            </form>

            <div class="row-actions">
                <button class="btn ghost" data-action="к-полуходу" data-ply="${Math.max(0, i - 1)}" ${i === 0 ? 'disabled' : ''}>${raw(иконка('влево'))}</button>
                <button class="btn ghost" data-action="к-полуходу" data-ply="${Math.min(i + 1, сверка.ходы.length - (сверка.остановка ? 0 : 1))}">${raw(иконка('вправо'))}</button>
                <button class="btn ghost" data-action="к-сомнительному">Следующий отмеченный</button>
            </div>
        </section>
    `;
}

function списокПолуходов(нотация) {
    const с_ = с.сверка;
    const кнопка = (i) => {
        if (i < с_.ходы.length) {
            const статус = с_.пометки[i].статус;
            return html`<td><button class="mv-btn st-${статус} ${i === с.выбран ? 'on' : ''}" data-action="к-полуходу" data-ply="${i}">${показатьХод(с_.ходы[i], нотация)}</button></td>`;
        }
        if (с_.остановка?.полуход === i) {
            return html`<td><button class="mv-btn st-стоп ${i === с.выбран ? 'on' : ''}" data-action="к-полуходу" data-ply="${i}">?</button></td>`;
        }
        return html`<td></td>`;
    };

    const всего = с_.ходы.length + (с_.остановка ? 1 : 0);
    const строки = [];
    for (let i = 0; i < всего; i += 2) {
        строки.push(html`<tr><td class="mv-num">${i / 2 + 1}.</td>${кнопка(i)}${кнопка(i + 1)}</tr>`);
    }

    return html`
        <section class="card">
            <h2 class="card-title">Прочитанные ходы</h2>
            <p class="legend small">
                <span class="st-уверенно">уверенно</span>
                <span class="st-исправлено">поправили правила</span>
                <span class="st-сомнение">проверьте</span>
                <span class="st-закреплено">выбрано вами</span>
            </p>
            <table class="moves-table">${строки}</table>
        </section>
    `;
}

function этапСверки(нотация) {
    const i = с.выбран;
    const остановка = с.сверка.остановка?.полуход === i;

    // Для места остановки — позиция до хода, и по ней можно ходить
    const доска = доскаДо(остановка ? i : i + 1);
    const последний = доска.history({ verbose: true }).at(-1) || null;
    const цели = остановка && с.выбрано ? доска.moves({ square: с.выбрано, verbose: true }).map((х) => х.to) : [];

    return html`
        <div class="layout">
            <div class="board-col">
                <div class="board-wrap">
                    ${raw(нарисоватьДоску({
                        fen: доска.fen(),
                        последний: последний && !остановка ? { from: последний.from, to: последний.to } : null,
                        шах: полеШаха(доска),
                        выбрано: остановка ? с.выбрано : null,
                        цели,
                        нажимаемая: остановка,
                        действие: 'клетка-фото'
                    }))}
                </div>
            </div>

            <div class="panel-col">
                ${итогСверки()}
                ${карточкаПолухода(нотация)}

                <div class="cta">
                    <button class="btn primary big" data-action="взять-партию" ${с.сверка.ходы.length ? '' : 'disabled'}>
                        ${с.сверка.остановка ? `Взять ${Math.ceil(с.сверка.ходы.length / 2)} ходов, остальное вручную` : 'Взять партию и разобрать'}
                    </button>
                    <div class="row-actions">
                        <button class="btn ghost" data-action="переснять">Другой снимок</button>
                    </div>
                </div>

                ${списокПолуходов(нотация)}
            </div>
        </div>
    `;
}

