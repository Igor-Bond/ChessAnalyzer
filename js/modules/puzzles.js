function начать(задача) {
    Object.assign(с, {
        задача, ходы: [], шаг: 0, состояние: 'решаю', неверный: null, сообщение: '',
        засчитано: false, ошиблась: false, подсказка: false, итог: null, повтор: null,
        выбрано: null, превращение: null, пусто: ''
    });
}

/**
 * Следующая задача из выбранного источника.
 *
 * @param {boolean} пропустить — нынешняя задача пропущена нерешённой: своя
 *   не должна тут же вернуться первой в очереди
 */
async function загрузить(пропустить = false) {
    const источник = с.источник;
    // Поколение, а не источник: lichess → свои → lichess — снова lichess, но
    // загрузка уже другая, и ответ первой не должен подменить вторую
    const моя = ++с.поколение;
    с.загрузка = true;
    с.заметка = '';
    if (пропустить && с.задача && !с.засчитано) с.пропущенные.add(с.задача.id);
    с.задача = null;

    try {
        if (источник === 'lichess') {
            const { задача, заметка } = await задачник.следующая();
            if (с.поколение !== моя) {
                // Задачу достали, но не показали — обратно в запас, а не в никуда
                if (задача) задачник.вернуть(задача);
                return;
            }
            с.заметка = заметка;
            if (задача) начать(задача);
            else if (/подождать/.test(заметка)) с.пусто = `${заметка}: частые запросы с одного адреса lichess ненадолго ограничивает. Пока можно решать свои ошибки.`;
            else с.пусто = `${заметка}. Задачи lichess приходят из сети; когда связь появится, они загрузятся впрок.`;
        } else {
            const свои = задачник.свои(хранилище.партии());
            let задача = свои.очередь.find((з) => !с.пропущенные.has(з.id)) || null;

            // Остались одни пропущенные — пойти по ним по второму кругу: раньше
            // экран говорил «все выучены», а в меню значилось «пора решить: 1»
            if (!задача && свои.очередь.length) {
                с.пропущенные.clear();
                задача = свои.очередь[0];
            }

            if (задача) начать(задача);
            else с.пусто = пустоСвоих(свои);
        }
    } catch (e) {
        if (с.поколение === моя) с.пусто = `Задача не загрузилась: ${e.message || e}`;
    } finally {
        if (с.поколение === моя) с.загрузка = false;
        if (app.route.name === 'задачи') app.render();
    }
}

function пустоСвоих(свои) {
    if (!свои.задачи.length) return 'В разобранных партиях нет ошибок и зевков — задачам взяться неоткуда. Разберите ещё партию или решайте задачи lichess.';
    if (свои.следующая) return `Всё на сегодня решено. Следующая ошибка вернётся ${черезСколько(свои.следующая)}.`;
    return 'Все свои ошибки выучены.';
}

function черезСколько(когда) {
    const мин = Math.max(1, Math.round((когда - Date.now()) / 60000));
    if (мин < 60) return `через ${мин} ${склонение(мин, 'минуту', 'минуты', 'минут')}`;
    const ч = Math.round(мин / 60);
    if (ч < 24) return `через ${ч} ${склонение(ч, 'час', 'часа', 'часов')}`;
    const д = Math.round(ч / 24);
    return `через ${д} ${склонение(д, 'день', 'дня', 'дней')}`;
}

