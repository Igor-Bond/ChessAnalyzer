function списокХодов(нотация) {
    if (!с.ходы.length) return '';

    const fen = с.задача.fen;
    const номер0 = Number(fen.split(' ')[5]) || 1;
    const чёрныеПервые = fen.split(' ')[1] === 'b';
    const листать = закончена();

    return html`
        <div class="free-moves">
            ${с.ходы.map((х, i) => {
                const полуход = i + (чёрныеПервые ? 1 : 0);
                const номер = номер0 + Math.floor(полуход / 2);
                const подпись = полуход % 2 === 0 ? `${номер}.` : (i === 0 ? `${номер}…` : '');
                return html`${подпись ? html`<span class="mv-num">${подпись}</span>` : ''}<button class="var-mv ${i + 1 === с.шаг ? 'on' : ''}" data-action="задача-шаг" data-step="${i + 1}" ${листать ? '' : 'disabled'}>${показатьХод(х.san, нотация)}</button>`;
            })}
        </div>
    `;
}

