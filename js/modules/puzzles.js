/** Рейтинг за последние задачи — линией: виден рост, а не одно число. */
function графикРоста(история) {
    if (история.length < 2) return '';

    const Ш = 600;
    const В = 70;
    const р = история.map((т) => т.рейтинг);
    const мин = Math.min(...р) - 10;
    const макс = Math.max(...р) + 10;
    const точки = р.map((з, i) => `${((i / (р.length - 1)) * Ш).toFixed(1)},${(В - ((з - мин) / (макс - мин)) * В).toFixed(1)}`);

    return raw(`<svg class="rgraph" viewBox="0 0 ${Ш} ${В}" preserveAspectRatio="none" role="img" aria-label="Рейтинг по задачам"><polyline points="${точки.join(' ')}" /></svg>`);
}

