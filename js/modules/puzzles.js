actions.on('задачи-решать', (el) => {
    const источник = el.dataset.source === 'свои' ? 'свои' : 'lichess';
    const з = с.задача;

    // Начатая задача ждёт возвращения из меню. Нетронутая задача lichess
    // меняется, только если в меню сменили тему или сложность, — и уходит
    // обратно в запас: раньше она пропадала, хотя её так и не решали
    const нетронута = з && с.состояние === 'решаю' && !с.ходы.length && !с.засчитано && !с.подсказка;
    if (источник === 'lichess' && с.источник === источник && нетронута
        && (з.тема !== задачник.состояние().тема || з.сложность !== задачник.сложность())) {
        задачник.вернуть(з);
        с.задача = null;
        с.источник = null;
    }

    app.go('задачи', источник);
});

// ================== ДЕЙСТВИЯ: РЕШЕНИЕ ==================

actions.on('задача-клетка', async (el) => {
    if (с.состояние !== 'решаю' || !с.задача || с.шаг !== с.ходы.length) return;

    const поле = el.dataset.square;
    const доска = new Chess(живойFen());

    if (с.выбрано) {
        const ходы = доска.moves({ square: с.выбрано, verbose: true }).filter((м) => м.to === поле);
        if (ходы.length) {
            if (ходы.some((м) => м.promotion)) {
                с.превращение = { from: с.выбрано, to: поле };
                return app.render();
            }
            await ходРешающего(uciХода(ходы[0]));
            return app.render();
        }
    }

    const фигура = доска.get(поле);
    // С подсказкой выбор фигуры не сбрасывается нажатием мимо — подсказка остаётся видна
    с.выбрано = фигура && фигура.color === доска.turn() && поле !== с.выбрано ? поле : (с.подсказка ? с.выбрано : null);
    app.render();
});

actions.on('задача-превратить', async (el) => {
    if (!с.превращение || с.состояние !== 'решаю') return;
    const { from, to } = с.превращение;
    await ходРешающего(`${from}${to}${el.dataset.piece}`);
    app.render();
});

actions.on('задача-без-превращения', () => {
    с.превращение = null;
    с.выбрано = null;
    app.render();
});

actions.on('задача-подсказка', () => {
    if (с.состояние !== 'решаю') return;
    с.подсказка = true;
    с.выбрано = с.задача.решение[с.ходы.length].slice(0, 2);
    app.render();
});

actions.on('задача-ещё', () => {
    с.неверный = null;
    с.состояние = 'решаю';
    с.сообщение = '';
    с.выбрано = с.подсказка ? с.задача.решение[с.ходы.length].slice(0, 2) : null;
    app.render();
});

/** Решение целиком: оставшиеся ходы с того места, где решающий остановился. */
actions.on('задача-решение', () => {
    if (!с.задача || (с.состояние !== 'решаю' && с.состояние !== 'неверно')) return;
    засчитать(false);
    с.неверный = null;
    с.превращение = null;

    while (с.ходы.length < с.задача.решение.length) {
        с.ходы.push(сыграть(с.задача.решение[с.ходы.length], с.ходы.length % 2 === 0));
    }

    с.состояние = 'показана';
    с.шаг = с.ходы.length;
    с.сообщение = 'Решение показано — листайте ходы стрелками.';
    с.выбрано = null;
    app.render();
});

actions.on('задача-следующая', () => {
    if (с.загрузка) return;
    загрузить(true);
    app.render();
});

function шагнуть(куда) {
    с.шаг = Math.max(0, Math.min(с.ходы.length, куда(с.шаг, с.ходы.length)));
    app.render();
}

actions.on('задача-назад', () => шагнуть((i) => i - 1));
actions.on('задача-вперёд', () => шагнуть((i) => i + 1));
actions.on('задача-в-начало', () => шагнуть(() => 0));
actions.on('задача-в-конец', () => шагнуть((_, n) => n));
actions.on('задача-шаг', (el) => шагнуть(() => Number(el.dataset.step) || 0));

actions.on('задача-в-разбор', () => {
    const з = с.задача;
    if (!з || з.источник !== 'партия') return;
    открытьРазборНа(з.партия, з.полуход);
    app.go('разбор', з.партия);
});

actions.on('задача-доиграть', () => {
    if (!с.задача) return;
    app.go('доска', с.шаг ? с.ходы[с.шаг - 1].fen : с.задача.fen);
});

/** Для проверок: учёт повторений и пропущенное за подход. */
export function сброситьЗадачи() {
    Object.assign(с, { показан: null, источник: null, задача: null, загрузка: false, пусто: '', пропущенные: new Set(), поколение: с.поколение + 1 });
}
