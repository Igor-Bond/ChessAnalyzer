function итогЗадачи(нотация) {
    const з = с.задача;
    const части = [];

    if (з.источник === 'lichess') {
        if (с.итог) {
            const д = с.итог.стало - с.итог.было;
            части.push(html`<p class="small">Рейтинг: ${с.итог.было} → <b>${с.итог.стало}</b> <span class="delta ${д >= 0 ? 'ok' : 'bad'}">(${д >= 0 ? '+' : '−'}${Math.abs(д)})</span>${с.подсказка && д === 0 ? ' — с подсказкой не меняется' : ''}</p>`);
        }
        const темы = з.темы.filter((т) => ТЕМЫ[т]).map((т) => ТЕМЫ[т]);
        if (темы.length) части.push(html`<p class="small muted">Темы: ${темы.join(', ')}</p>`);
        части.push(html`<p class="small"><a href="${з.ссылка}" target="_blank" rel="noopener">Открыть задачу на lichess</a></p>`);
    } else {
        части.push(html`<p class="small">Лучше было: <b>${линияТекстом(з.fen, з.линия, нотация, 6)}</b></p>`);
        if (с.повтор) {
            части.push(html`<p class="small muted">${с.повтор.выучена ? 'Решена четвёртый раз подряд — выучена.' : `Вернётся ${черезСколько(с.повтор.когда)}.`}</p>`);
        }
    }

    return части;
}

function экранЗадачи(нотация) {
    const з = с.задача;
    const назад = html`<button class="icon-btn" data-action="задачи-меню" aria-label="К задачам" title="К задачам">${raw(иконка('назад'))}</button>`;
    const заголовок = с.источник === 'lichess' ? 'Задачи lichess' : 'Мои ошибки';

    if (с.загрузка || !з) {
        return html`
            <header class="topbar">${назад}<h1>${заголовок}</h1></header>
            <div class="narrow">
                ${с.загрузка ? html`
                    <section class="card">
                        <div class="progress-head"><span>${с.источник === 'lichess' ? 'Задачи загружаются с lichess' : 'Ищу задачу'}</span></div>
                        <div class="progress"><div class="progress-bar indeterminate"></div></div>
                    </section>
                ` : html`
                    <div class="empty-note">${с.пусто}</div>
                    <div class="row-actions">
                        ${с.источник === 'lichess'
                            ? html`<button class="btn primary" data-action="задача-следующая">Попробовать снова</button>
                                <button class="btn" data-action="задачи-решать" data-source="свои">Мои ошибки</button>`
                            : html`<button class="btn primary" data-action="задачи-решать" data-source="lichess">Задачи lichess</button>`}
                        <button class="btn" data-action="задачи-меню">К задачам</button>
                    </div>
                `}
            </div>
        `;
    }

    const сторона = з.fen.split(' ')[1];
    const живая = с.шаг === с.ходы.length;
    const неверный = живая && с.неверный ? с.неверный : null;
    const fen = неверный ? неверный.fen : с.шаг ? с.ходы[с.шаг - 1].fen : з.fen;
    const доска = new Chess(fen);
    const последний = неверный || с.ходы[с.шаг - 1] || з.последний;
    const нажимаемая = с.состояние === 'решаю' && живая && !с.превращение;
    const цели = с.выбрано && нажимаемая ? доска.moves({ square: с.выбрано, verbose: true }).map((м) => м.to) : [];

    let значок = null;
    // Подсказка видна, пока выделена именно фигура решения: после ответа
    // соперника выделение снято, и текст о нём был бы неправдой
    const подсказкаВидна = с.подсказка && с.состояние === 'решаю' && с.выбрано === з.решение[с.ходы.length]?.slice(0, 2);

    // Крестик — только по вердикту: пока движок проверяет, ход ещё может оказаться сильным
    if (неверный && с.состояние === 'неверно') значок = { поле: неверный.to, класс: 'зевок', знак: '✗' };
    else if (с.состояние === 'решена' && живая && с.ходы.at(-1)?.мой) значок = { поле: с.ходы.at(-1).to, класс: 'лучший', знак: '✓' };

    const тон = с.состояние === 'неверно' ? 'bad' : (с.состояние === 'решена' || с.состояние === 'ждём' || /^Верно/.test(с.сообщение)) ? 'ok' : '';

    return html`
        <header class="topbar">${назад}<h1>${заголовок}</h1></header>

        <div class="layout">
            <div class="board-col">
                <div class="board-wrap">
                    ${raw(нарисоватьДоску({
                        fen,
                        сторона,
                        последний: последний ? { from: последний.from, to: последний.to } : null,
                        выбрано: нажимаемая ? с.выбрано : null,
                        цели,
                        значок,
                        шах: полеШаха(доска),
                        нажимаемая,
                        действие: 'задача-клетка'
                    }))}
                </div>
                ${с.превращение ? выборПревращения(сторона) : ''}
                ${закончена() && с.ходы.length ? html`
                    <nav class="nav-row" aria-label="Листать решение">
                        <button class="nav-btn" data-action="задача-в-начало" data-key="home arrowup" aria-label="В начало">${raw(иконка('начало'))}</button>
                        <button class="nav-btn" data-action="задача-назад" data-key="arrowleft" aria-label="Назад">${raw(иконка('влево'))}</button>
                        <button class="nav-btn" data-action="задача-вперёд" data-key="arrowright" aria-label="Вперёд">${raw(иконка('вправо'))}</button>
                        <button class="nav-btn" data-action="задача-в-конец" data-key="end arrowdown" aria-label="В конец">${raw(иконка('конец'))}</button>
                    </nav>
                ` : ''}
            </div>

            <div class="panel-col">
                <section class="card puzzle-card">
                    ${условие(нотация)}
                    ${с.заметка ? html`<p class="small muted">${с.заметка}</p>` : ''}
                    ${с.сообщение ? html`<p class="puzzle-msg ${тон}" role="status">${с.сообщение}</p>` : ''}
                    ${с.состояние === 'проверяю' ? html`<div class="progress"><div class="progress-bar indeterminate"></div></div>` : ''}
                    ${списокХодов(нотация)}

                    ${с.состояние === 'решаю' || с.состояние === 'ждём' ? html`
                        <div class="row-actions">
                            <button class="btn" data-action="задача-подсказка" ${с.состояние !== 'решаю' ? 'disabled' : ''}>${raw(иконка('лампа'))} Подсказка</button>
                            <button class="btn ghost" data-action="задача-решение" ${с.состояние !== 'решаю' ? 'disabled' : ''}>Показать решение</button>
                            ${с.ходы.length || с.засчитано ? '' : html`<button class="btn ghost" data-action="задача-следующая">Пропустить</button>`}
                        </div>
                        ${подсказкаВидна ? html`<p class="muted small">Ходит выделенная фигура.${з.источник === 'lichess' ? ' С подсказкой рейтинг не меняется.' : ''}</p>` : ''}
                    ` : ''}

                    ${с.состояние === 'неверно' ? html`
                        <div class="row-actions">
                            <button class="btn primary" data-action="задача-ещё">Ещё раз</button>
                            <button class="btn ghost" data-action="задача-решение">Показать решение</button>
                        </div>
                        ${з.источник === 'lichess' && с.итог ? html`<p class="muted small">Рейтинг: ${с.итог.было} → ${с.итог.стало}. Решить можно и дальше — уже без очков.</p>` : ''}
                    ` : ''}

                    ${закончена() ? html`
                        ${итогЗадачи(нотация)}
                        <button class="btn primary big" data-action="задача-следующая">Следующая задача</button>
                        <div class="row-actions">
                            ${з.источник === 'партия' ? html`<button class="btn ghost" data-action="задача-в-разбор">Открыть в разборе</button>` : ''}
                            <button class="btn ghost" data-action="задача-доиграть">${raw(иконка('играть'))} Доиграть движком</button>
                        </div>
                    ` : ''}
                </section>
            </div>
        </div>
    `;
}

export const задачиЭкран = {

    render(п) {
        // Вход на экран — по смене маршрута; перерисовки на месте задач не трогают
        const вход = с.показан !== п;
        с.показан = п;

        if (!ИСТОЧНИКИ.includes(п)) return меню();

        if (вход) {
            const продолжить = с.источник === п && (с.загрузка || (с.задача && !закончена()));
            if (!продолжить) {
                с.источник = п;
                с.загрузка = true;
                queueMicrotask(() => загрузить());
            }
        }

        return экранЗадачи(хранилище.настройки().нотация);
    },

    leave() {
        с.показан = null;
    }
};

