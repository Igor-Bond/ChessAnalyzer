/** Неудача засчитывается сразу, при первой ошибке: вторая попытка — уже не решение. */
function засчитать(решена) {
    if (с.засчитано) return;
    с.засчитано = true;

    if (с.задача.источник === 'lichess') {
        с.итог = задачник.засчитать(с.задача, { решена, подсказка: с.подсказка });
    } else {
        с.повтор = задачник.отметитьСвою(с.задача, решена && !с.подсказка);
    }
}

function решено(сообщение = 'Решено!') {
    засчитать(true);
    с.состояние = 'решена';
    с.шаг = с.ходы.length;
    с.сообщение = сообщение;
}

function неверно(ход, сообщение) {
    засчитать(false);
    с.ошиблась = true;
    с.неверный = ход;
    с.состояние = 'неверно';
    с.сообщение = сообщение;
}

/** Ход на доске задачи: в позиции после всех сделанных. */
function сыграть(uci, мой) {
    const доска = new Chess(живойFen());
    const ход = доска.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] });
    return { san: ход.san, from: ход.from, to: ход.to, fen: доска.fen(), uci: uciХода(ход), мой };
}

async function ходРешающего(uci) {
    const з = с.задача;
    const шаг = с.ходы.length;
    const вид = проверитьХод(з, живойFen(), uci, шаг);
    const ход = сыграть(uci, true);
    с.выбрано = null;
    с.превращение = null;

    if (вид === 'верно' || вид === 'мат') {
        с.ходы.push(ход);
        с.шаг = с.ходы.length;

        if (вид === 'мат') return решено('Мат! Решено иначе, чем у автора, — засчитывается любой мат.');
        if (с.ходы.length >= з.решение.length) return решено();

        // Ответ соперника — по решению, с паузой, чтобы его было видно
        с.состояние = 'ждём';
        с.сообщение = 'Верно!';
        app.render();
        await new Promise((r) => setTimeout(r, ПАУЗА_ОТВЕТА));
        if (с.задача !== з) return;

        const ответ = сыграть(з.решение[с.ходы.length], false);
        с.ходы.push(ответ);
        с.шаг = с.ходы.length;
        if (с.ходы.length >= з.решение.length) return решено();

        с.состояние = 'решаю';
        с.сообщение = `Верно! Ответ: ${показатьХод(ответ.san, хранилище.настройки().нотация)}. Продолжайте.`;
        return;
    }

    if (вид === 'сыгран') {
        return неверно(ход, `Этот ход и был сыгран в партии — ${КЛАССЫ[з.класс].кратко}. Ищите другой.`);
    }

    if (вид === 'проверить') {
        // Свой ход в своей задаче: решает движок, не хуже ли он лучшего
        с.неверный = ход;
        с.состояние = 'проверяю';
        с.сообщение = 'Движок проверяет ваш ход…';
        app.render();

        try {
            const р = await оценитьОтвет(движок(), з, uci, Math.min(ГЛУБИНА_ПРОВЕРКИ, хранилище.настройки().глубина));
            if (с.задача !== з) return;

            if (р.принят) {
                с.неверный = null;
                с.ходы.push(ход);
                const лучший = new Chess(з.fen).move({ from: з.решение[0].slice(0, 2), to: з.решение[0].slice(2, 4), promotion: з.решение[0][4] });
                return решено(`Тоже сильный ход — решено! Движок чуть выше ставит ${показатьХод(лучший.san, хранилище.настройки().нотация)}.`);
            }
            return неверно(ход, `Не то: этот ход теряет ${Math.round(р.потеря)}% шансов против лучшего.`);
        } catch (e) {
            if (с.задача !== з) return;
            с.неверный = null;
            с.состояние = 'решаю';
            с.сообщение = `Движок не смог проверить ход: ${e.message || e}`;
            return;
        }
    }

    return неверно(ход, 'Не то — у позиции есть ход сильнее.');
}

